#!/usr/bin/env bash
set -euo pipefail

# SCARLIX OS v19.2.0 — Generate LiteLLM config.yaml from models.yaml
#
# v18.8.3 P1 (A-a): Dynamic LiteLLM config (was: ai/litellm/config.yaml had
#   hardcoded model IDs like openai/Qwen3-14B-AWQ. If user changed model in
#   models.yaml, LiteLLM still routed to old model → "model not found". Now:
#   this script reads models.yaml via yq and generates config.yaml so the
#   gateway always matches the actual backend model IDs.)
#
# Model ID derivation:
#   - SGLang: basename of model_path (e.g. /models/Qwen3-14B-AWQ → Qwen3-14B-AWQ)
#   - BeeLlama: hf_file (e.g. Qwen3-14B-Q4_K_M.gguf)
#   - Ollama: model field (e.g. qwen2.5:3b)
#
# Usage: generate-litellm-config.sh [models.yaml] [output config.yaml]
#   Defaults: /etc/scarlix/models.yaml → /opt/scarlix/ai/litellm/config.yaml

MODELS_YAML="${1:-/etc/scarlix/models.yaml}"
OUTPUT="${2:-/opt/scarlix/ai/litellm/config.yaml}"

if [ ! -f "$MODELS_YAML" ]; then
  echo "ERROR: models.yaml not found at $MODELS_YAML" >&2
  exit 1
fi

if ! command -v yq >/dev/null 2>&1; then
  echo "ERROR: yq not installed (pacman -S yq)" >&2
  exit 1
fi

# v18.8.8 P2-03: Validate YAML before reading keys (was: yq errors on individual
#   keys gave confusing "model_path missing" errors when the real problem was
#   invalid YAML syntax. Now: explicit validation first with clear error.)
if ! yq -e '.' "$MODELS_YAML" >/dev/null 2>&1; then
  echo "ERROR: $MODELS_YAML is invalid YAML — cannot generate LiteLLM config" >&2
  exit 1
fi

# Derive model IDs from models.yaml
# v18.8.7 P2-01: FAIL if any model ID is missing (was: hardcoded defaults like
#   Qwen3-14B-AWQ → if user forgot model_path in models.yaml, LiteLLM silently
#   routed to wrong model. Now: exit 1 with clear error.)
SGLANG_PATH=$(yq -r '.sglang.model_path // empty' "$MODELS_YAML" 2>/dev/null || echo "")
SGLANG_MODEL_ID=$(basename "$SGLANG_PATH" 2>/dev/null || echo "")
[ -z "$SGLANG_MODEL_ID" ] && {
  echo "ERROR: .sglang.model_path missing or empty in $MODELS_YAML" >&2
  exit 1
}

BEE_MODEL_ID=$(yq -r '.beellama.hf_file // empty' "$MODELS_YAML" 2>/dev/null || echo "")
[ -z "$BEE_MODEL_ID" ] && {
  echo "ERROR: .beellama.hf_file missing or empty in $MODELS_YAML" >&2
  exit 1
}

OLLAMA_MODEL_ID=$(yq -r '.ollama.model // empty' "$MODELS_YAML" 2>/dev/null || echo "")
[ -z "$OLLAMA_MODEL_ID" ] && {
  echo "ERROR: .ollama.model missing or empty in $MODELS_YAML" >&2
  exit 1
}

# v18.9.0 P1-05: Validate model ID charset (was: unvalidated → YAML injection if model_path has special chars)
validate_model_id() {
    local id="$1" name="$2"
    if ! [[ "$id" =~ ^[A-Za-z0-9._/@:-]+$ ]]; then
        echo "ERROR: $name contains invalid characters: '$id' (allowed: A-Za-z0-9._/@:-)" >&2
        exit 1
    fi
}
validate_model_id "$SGLANG_MODEL_ID" "SGLang model ID"
validate_model_id "$BEE_MODEL_ID" "BeeLlama model ID"
validate_model_id "$OLLAMA_MODEL_ID" "Ollama model ID"

# Ensure output directory exists
mkdir -p "$(dirname "$OUTPUT")"

# v19.2.0 P2 (2A): Derive version dynamically from VERSION file (was: hardcoded
#   v19.0.3 in generated config header — drifted across releases). Falls back
#   to "unknown" if VERSION file not found (non-fatal — config still generated).
#   Script lives at files/usr/local/bin/ — repo root is 4 levels up (bin→local→usr→files→root).
#   In installed mode (/usr/local/bin/), repo root resolves to "/" so /etc/scarlix/VERSION
#   is the primary source.
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../.." 2>/dev/null && cd .. 2>/dev/null && pwd 2>/dev/null || echo "")"
SCARLIX_VERSION="unknown"
for vfile in "$REPO_ROOT/VERSION" "/etc/scarlix/VERSION" "/usr/local/share/scarlix/VERSION"; do
  if [ -f "$vfile" ]; then
    SCARLIX_VERSION="$(tr -d '[:space:]' < "$vfile")"
    break
  fi
done

# Generate config.yaml (atomic via mktemp + mv)
TMP=$(mktemp "${OUTPUT}.XXXXXX") || exit 1
cat > "$TMP" << EOF
# SCARLIX OS v${SCARLIX_VERSION} — LiteLLM routing config (AUTO-GENERATED by generate-litellm-config.sh)
# DO NOT EDIT — changes will be overwritten. Edit models.yaml instead, then re-run.
#
# Generated from: $MODELS_YAML
# SGLang model ID: $SGLANG_MODEL_ID (from .sglang.model_path basename)
# BeeLlama model ID: $BEE_MODEL_ID (from .beellama.hf_file)
# Ollama model ID: $OLLAMA_MODEL_ID (from .ollama.model)
#
# v18.8.2 fallback: 3-tier (SGLang → Ollama → BeeLlama). vLLM excluded (experimental).
# scarlix-mode start_verified_ai() has full 4-tier for direct mode switching.

model_list:
  # PRIMARY: SGLang (GPU0) — Tier-1
  - model_name: scarlix-default
    litellm_params:
      model: openai/$SGLANG_MODEL_ID
      api_base: http://sglang:30000/v1
      api_key: not-needed

  # FALLBACK-1: Ollama (CPU) — separate model group
  - model_name: scarlix-ollama
    litellm_params:
      model: ollama/$OLLAMA_MODEL_ID
      api_base: http://ollama-agent:11434

  # FALLBACK-2: BeeLlama / llama.cpp (CPU) — separate model group
  - model_name: scarlix-beellama
    litellm_params:
      model: openai/$BEE_MODEL_ID
      api_base: http://beellama:8080/v1
      api_key: not-needed

router_settings:
  routing_strategy: simple-shuffle
  num_retries: 2
  # 3-tier chain: SGLang → Ollama → BeeLlama (matches scarlix-mode fallback order)
  fallbacks:
    - scarlix-default: ["scarlix-ollama", "scarlix-beellama"]

general_settings:
  master_key: os.environ/LITELLM_MASTER_KEY
  # SQLite DB persisted under mounted volume (v18.8.1 fix)
  database_url: sqlite:////app/data/litellm.db
EOF

mv -f "$TMP" "$OUTPUT"
# v18.8.6 P1-2: chmod 600 (was: 640 — but mktemp creates files with 600, so
#   640 actually LOOSENED permissions by adding group read). Keep mktemp's
#   strict default; do not loosen. File references os.environ/LITELLM_MASTER_KEY
#   (not the secret itself, but consistent with the project's security posture).
chmod 600 "$OUTPUT" 2>/dev/null || true
echo "✓ LiteLLM config generated: $OUTPUT"
echo "  scarlix-default → SGLang ($SGLANG_MODEL_ID)"
echo "  scarlix-ollama → Ollama ($OLLAMA_MODEL_ID)"
echo "  scarlix-beellama → BeeLlama ($BEE_MODEL_ID)"
