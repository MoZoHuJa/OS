#!/usr/bin/env bash
set -euo pipefail

# SCARLIX OS v18.8.5 — Generate LiteLLM config.yaml from models.yaml
#
# v18.8.3 P1 (A-a): Dynamic LiteLLM config (was: ai/litellm/config.yaml had
#   hardcoded model IDs like openai/Qwen3-14B-AWQ. If user changed model in
#   models.yaml, LiteLLM still routed to old model → "model not found". Now:
#   this script reads models.yaml via yq and generates config.yaml so the
#   gateway always matches the actual backend model IDs.)
#
# Model ID derivation:
#   - SGLang: basename of model_path (e.g. /models/Qwen3-14B-AWQ → Qwen3-14B-AWQ)
#   - BeeLlama: hf_file (e.g. Qwen3-14B-Q4_K_M.gguf)
#   - Ollama: model field (e.g. qwen2.5:3b)
#
# Usage: generate-litellm-config.sh [models.yaml] [output config.yaml]
#   Defaults: /etc/scarlix/models.yaml → /opt/scarlix/ai/litellm/config.yaml

MODELS_YAML="${1:-/etc/scarlix/models.yaml}"
OUTPUT="${2:-/opt/scarlix/ai/litellm/config.yaml}"

if [ ! -f "$MODELS_YAML" ]; then
  echo "ERROR: models.yaml not found at $MODELS_YAML" >&2
  exit 1
fi

if ! command -v yq >/dev/null 2>&1; then
  echo "ERROR: yq not installed (pacman -S yq)" >&2
  exit 1
fi

# Derive model IDs from models.yaml
SGLANG_PATH=$(yq -r '.sglang.model_path // empty' "$MODELS_YAML" 2>/dev/null || echo "")
SGLANG_MODEL_ID=$(basename "$SGLANG_PATH" 2>/dev/null || echo "")
[ -z "$SGLANG_MODEL_ID" ] && SGLANG_MODEL_ID="Qwen3-14B-AWQ"

BEE_MODEL_ID=$(yq -r '.beellama.hf_file // empty' "$MODELS_YAML" 2>/dev/null || echo "")
[ -z "$BEE_MODEL_ID" ] && BEE_MODEL_ID="Qwen3-14B-Q4_K_M.gguf"

OLLAMA_MODEL_ID=$(yq -r '.ollama.model // empty' "$MODELS_YAML" 2>/dev/null || echo "")
[ -z "$OLLAMA_MODEL_ID" ] && OLLAMA_MODEL_ID="qwen2.5:3b"

# Ensure output directory exists
mkdir -p "$(dirname "$OUTPUT")"

# Generate config.yaml (atomic via mktemp + mv)
TMP=$(mktemp "${OUTPUT}.XXXXXX") || exit 1
cat > "$TMP" << EOF
# SCARLIX OS v18.8.5 — LiteLLM routing config (AUTO-GENERATED by generate-litellm-config.sh)
# DO NOT EDIT — changes will be overwritten. Edit models.yaml instead, then re-run.
#
# Generated from: $MODELS_YAML
# SGLang model ID: $SGLANG_MODEL_ID (from .sglang.model_path basename)
# BeeLlama model ID: $BEE_MODEL_ID (from .beellama.hf_file)
# Ollama model ID: $OLLAMA_MODEL_ID (from .ollama.model)
#
# v18.8.2 fallback: 3-tier (SGLang → Ollama → BeeLlama). vLLM excluded (experimental).
# scarlix-mode start_verified_ai() has full 4-tier for direct mode switching.

model_list:
  # PRIMARY: SGLang (GPU0) — Tier-1
  - model_name: scarlix-default
    litellm_params:
      model: openai/$SGLANG_MODEL_ID
      api_base: http://sglang:30000/v1
      api_key: not-needed

  # FALLBACK-1: Ollama (CPU) — separate model group
  - model_name: scarlix-ollama
    litellm_params:
      model: ollama/$OLLAMA_MODEL_ID
      api_base: http://ollama-agent:11434

  # FALLBACK-2: BeeLlama / llama.cpp (CPU) — separate model group
  - model_name: scarlix-beellama
    litellm_params:
      model: openai/$BEE_MODEL_ID
      api_base: http://beellama:8080/v1
      api_key: not-needed

router_settings:
  routing_strategy: simple-shuffle
  num_retries: 2
  # 3-tier chain: SGLang → Ollama → BeeLlama (matches scarlix-mode fallback order)
  fallbacks:
    - scarlix-default: ["scarlix-ollama", "scarlix-beellama"]

general_settings:
  master_key: os.environ/LITELLM_MASTER_KEY
  # SQLite DB persisted under mounted volume (v18.8.1 fix)
  database_url: sqlite:////app/data/litellm.db
EOF

mv -f "$TMP" "$OUTPUT"
# v18.8.5 P2: Tighten perms to 640 (was: mktemp+mv left 644 world-readable).
#   File references os.environ/LITELLM_MASTER_KEY (not the secret itself, but
#   consistent with the project's security posture on routing config).
chmod 640 "$OUTPUT" 2>/dev/null || true
echo "✓ LiteLLM config generated: $OUTPUT"
echo "  scarlix-default → SGLang ($SGLANG_MODEL_ID)"
echo "  scarlix-ollama → Ollama ($OLLAMA_MODEL_ID)"
echo "  scarlix-beellama → BeeLlama ($BEE_MODEL_ID)"
