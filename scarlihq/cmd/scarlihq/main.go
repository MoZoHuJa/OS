// Version is the ScarliHQ application version.
// v18.2 P1: Changed from `const` to `var` — ldflags `-X main.Version` only works on vars.
// v18.0.0: injected via -ldflags "-X main.Version=$VERSION" in Dockerfile.
// Default here matches VERSION file (used when running `go run` without ldflags).
var Version = "19.5.1"

//go:embed frontend/dist/index.html
var indexHTML []byte

func main() {
	log.SetFlags(log.LstdFlags | log.Lshortfile)
	log.Printf("SCARLIX OS %s — ScarliHQ starting (host-bridge architecture)...", Version)

	// Auth token: required for all /api/* and /ws. Generated by generate-env.sh
	// into /etc/scarlix/.env (SCARLIHQ_TOKEN). Passed to container via compose env.
	authToken := os.Getenv("SCARLIHQ_TOKEN")
	if authToken == "" {
		log.Println("WARNING: SCARLIHQ_TOKEN not set — dashboard API will reject all requests. Set SCARLIHQ_TOKEN in /etc/scarlix/.env")
	}

	// Initialize subsystems (all file-based — no privileged host access needed)
	g := guard.New()
	mode := scarlix_mode.New()
	pf := profiles.New("/etc/scarlix/profiles")

	mux := http.NewServeMux()

	// Dashboard HTML (served WITHOUT auth — it's a shell that needs a token to act).
	// v18.7.5 P0: JS reads token from sessionStorage only (was: also from ?token= URL).
	// Without it, shows a token-entry form (paste-once-per-session via auth gate).
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/" {
			http.NotFound(w, r)
			return
		}
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Header().Set("Cache-Control", "no-cache")
		w.Write(indexHTML)
	})

	// REST API + MCP + WS — all behind token auth
	// v18.2 P1: pass Version to Handler (was: separate const — ldflags couldn't override)
	apiHandler := api.NewHandler(g, mode, pf, authToken, Version)
	// Compute lifecycle is opt-in. The bearer token maps to one configured principal;
	// do not enable this shared-token mode for multi-user deployments.
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_COMPUTE_ENABLED")), "true") {
		socketPath := strings.TrimSpace(os.Getenv("SCARLIHQ_COMPUTE_SOCKET"))
		allocationPath := strings.TrimSpace(os.Getenv("SCARLIHQ_ALLOCATION_STORE"))
		principal := strings.TrimSpace(os.Getenv("SCARLIHQ_COMPUTE_PRINCIPAL"))
		if socketPath == "" || allocationPath == "" || principal == "" {
			log.Fatal("compute lifecycle enabled but SCARLIHQ_COMPUTE_SOCKET, SCARLIHQ_ALLOCATION_STORE, or SCARLIHQ_COMPUTE_PRINCIPAL is missing")
		}
		store := allocation.NewStore(allocationPath)
		runtime, err := compute.New(store, socketPath)
		if err != nil {
			log.Fatalf("compute lifecycle initialization failed: %v", err)
		}
		if err := apiHandler.ConfigureCompute(runtime.Manager, principal); err != nil {
			runtime.Close()
			log.Fatalf("compute lifecycle configuration failed: %v", err)
		}
		log.Printf("Compute lifecycle API enabled (allocation store: %s); resource release remains reconciliation-gated", allocationPath)
	} else {
		log.Printf("Compute lifecycle API disabled; set SCARLIHQ_COMPUTE_ENABLED=true only after host bridge acceptance")
	}

	// AK-2 (v19.4.1): Agent Kernel session surface — opt-in, like the compute
	// lifecycle (Controlled Accumulation: small, reversible steps). Sessions
	// are bounded + in-memory; grants are request-supplied until AK-3
	// persists them admin-owned. Evaluate is pure — no host effects at all.
	// v19.5.0: kernelStore is hoisted so the Agent Fabric block below can
	// require it (the fabric routes intents through kernel sessions).
	var kernelStore *agentkernel.Store
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTKERNEL_ENABLED")), "true") {
		store, err := agentkernel.NewStore(agentkernel.DefaultMaxSessions)
		if err != nil {
			log.Fatalf("agent kernel initialization failed: %v", err)
		}
		kernelStore = store
		// AK-3 (v19.4.4): persisted, admin-owned grant registry — separate
		// opt-in (SCARLIHQ_AGENT_GRANTS_FILE + SCARLIHQ_AGENT_PRINCIPALS).
		// When configured, grants become admin-owned registry acts bound to
		// the reservation governor's user_tokens principal space; when not,
		// the AK-2 legacy contract (request-supplied grants) stays in force.
		// Load is fail-closed: a corrupt/tampered grants file aborts startup.
		grantsFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENT_GRANTS_FILE"))
		if grantsFile != "" {
			principalsRaw := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENT_PRINCIPALS"))
			if principalsRaw == "" {
				log.Fatal("agent kernel grant registry enabled but SCARLIHQ_AGENT_PRINCIPALS is missing (comma-separated principal names copied from the governor user_tokens config)")
			}
			var principals []string
			for _, p := range strings.Split(principalsRaw, ",") {
				if p = strings.TrimSpace(p); p != "" {
					principals = append(principals, p)
				}
			}
			registry, err := agentkernel.NewGrantRegistry(grantsFile, principals, agentkernel.DefaultMaxGrants, agentkernel.DefaultMaxAgents)
			if err != nil {
				log.Fatalf("agent kernel grant registry construction failed: %v", err)
			}
			if err := registry.Load(); err != nil {
				log.Fatalf("agent kernel grant registry load failed: %v (fix the file or remove it deliberately — never run on a tampered registry)", err)
			}
			if err := apiHandler.ConfigureAgentGrants(registry); err != nil {
				log.Fatalf("agent kernel grant registry configuration failed: %v", err)
			}
			log.Printf("Agent Kernel grant registry enabled (%s; principals: %s; bounds: %d grants/%d agents)", grantsFile, principalsRaw, agentkernel.DefaultMaxGrants, agentkernel.DefaultMaxAgents)
			if err := apiHandler.ConfigureAgentKernel(store, registry.Policy()); err != nil {
				log.Fatalf("agent kernel configuration failed: %v", err)
			}
		} else {
			if strings.TrimSpace(os.Getenv("SCARLIHQ_AGENT_PRINCIPALS")) != "" {
				log.Println("WARNING: SCARLIHQ_AGENT_PRINCIPALS is set but SCARLIHQ_AGENT_GRANTS_FILE is not — the grant registry stays disabled")
			}
			if err := apiHandler.ConfigureAgentKernel(store, agentkernel.Policy{}); err != nil {
				log.Fatalf("agent kernel configuration failed: %v", err)
			}
			log.Printf("Agent Kernel session API enabled (max %d sessions, legacy request-supplied grants; set SCARLIHQ_AGENT_GRANTS_FILE + SCARLIHQ_AGENT_PRINCIPALS for admin-owned grants)", agentkernel.DefaultMaxSessions)
		}

		// AK-4 (v19.4.5): append-only audit sink — separate opt-in
		// (SCARLIHQ_AGENT_AUDIT_FILE). When set, every evaluation is
		// persisted BEFORE its decision is served (fail-closed) and every
		// admin act is appended after its successful persist. Construction
		// is fail-closed (0600/0700 discipline — loose permissions abort
		// startup, tamper discipline like the grant registry).
		auditFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENT_AUDIT_FILE"))
		if auditFile != "" {
			sink, err := agentkernel.NewAuditSink(auditFile)
			if err != nil {
				log.Fatalf("agent kernel audit sink initialization failed: %v (fix the file/dir permissions or path — never run with a tampered audit trail)", err)
			}
			if err := apiHandler.ConfigureAgentAudit(sink); err != nil {
				log.Fatalf("agent kernel audit sink configuration failed: %v", err)
			}
			log.Printf("Agent Kernel audit sink enabled (%s; append-only JSONL, evaluations fail-closed on audit write)", auditFile)
		} else {
			log.Println("Agent Kernel audit sink disabled; set SCARLIHQ_AGENT_AUDIT_FILE to persist every decision and admin act")
		}
	} else {
		log.Printf("Agent Kernel session API disabled; set SCARLIHQ_AGENTKERNEL_ENABLED=true to enable")
	}

	// BF-1 (v19.5.0): Agent Fabric command surface (the ScarliBar backend) —
	// opt-in, like the kernel. The fabric REQUIRES the kernel (intents route
	// through kernel sessions — it has no standalone mode) and a persisted
	// commands file (the durable command history, grants.json discipline:
	// schema version, 0600/0700 fail-closed load, atomic tmp+rename persist,
	// bounded history). Enablement: SCARLIHQ_AGENTFABRIC_ENABLED=true +
	// SCARLIHQ_AGENTFABRIC_COMMANDS_FILE=/var/lib/scarlix-agentfabric/
	// commands.json.
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTFABRIC_ENABLED")), "true") {
		if kernelStore == nil {
			log.Fatal("agent fabric enabled but the agent kernel is not (agent fabric requires SCARLIHQ_AGENTKERNEL_ENABLED=true — intents route through kernel sessions)")
		}
		commandsFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTFABRIC_COMMANDS_FILE"))
		if commandsFile == "" {
			log.Fatal("agent fabric enabled but SCARLIHQ_AGENTFABRIC_COMMANDS_FILE is missing (the command history is persisted — grants.json discipline)")
		}
		fabricStore, err := agentfabric.NewCommandStore(commandsFile, agentfabric.DefaultMaxCommands)
		if err != nil {
			log.Fatalf("agent fabric command store construction failed: %v", err)
		}
		if err := fabricStore.Load(); err != nil {
			log.Fatalf("agent fabric command store load failed: %v (fix the file or archive it deliberately — never run on a tampered command history)", err)
		}
		if err := apiHandler.ConfigureAgentFabric(fabricStore); err != nil {
			log.Fatalf("agent fabric configuration failed: %v", err)
		}
		// BF-2 (v19.5.1): the workspace store rides the fabric opt-in — no
		// separate flag. Its file defaults to workspaces.json NEXT TO the
		// commands file (same 0700 directory, same tamper discipline);
		// SCARLIHQ_AGENTFABRIC_WORKSPACES_FILE overrides the location for
		// operators who want the stores on separate volumes. Fail-closed
		// load like every persisted store — a tampered workspaces file
		// aborts startup, it never degrades into "some workspaces work".
		workspacesFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTFABRIC_WORKSPACES_FILE"))
		if workspacesFile == "" {
			workspacesFile = filepath.Join(filepath.Dir(commandsFile), "workspaces.json")
		}
		wsStore, err := agentfabric.NewWorkspaceStore(workspacesFile, agentfabric.DefaultMaxWorkspaces)
		if err != nil {
			log.Fatalf("agent fabric workspace store construction failed: %v", err)
		}
		if err := wsStore.Load(); err != nil {
			log.Fatalf("agent fabric workspace store load failed: %v (fix the file or archive it deliberately — never run on a tampered workspace history)", err)
		}
		if err := apiHandler.ConfigureAgentWorkspaces(wsStore); err != nil {
			log.Fatalf("agent fabric workspace configuration failed: %v", err)
		}
		log.Printf("Agent Fabric command API enabled (ScarliBar backend; commands file: %s; bound %d records — the file is the history, rotate deliberately)", commandsFile, agentfabric.DefaultMaxCommands)
		log.Printf("Agent Fabric workspace API enabled (workspaces file: %s; bound %d workspaces / %d sessions each — ARCHIVED is the terminal tombstone)", workspacesFile, agentfabric.DefaultMaxWorkspaces, agentfabric.MaxSessionsPerWorkspace)
	} else {
		log.Printf("Agent Fabric command API disabled; set SCARLIHQ_AGENTFABRIC_ENABLED=true (requires the agent kernel + SCARLIHQ_AGENTFABRIC_COMMANDS_FILE)")
	}
	apiHandler.RegisterRoutes(mux)

	mcpServer := mcp.NewServer(g, mode, pf, authToken, Version)
	mcpServer.RegisterRoutes(mux)

	webui.RegisterWS(mux, authToken, mode, pf)

	// Start server
	port := os.Getenv("SCARLIHQ_PORT")
	if port == "" {
		port = "8090"
	}

	log.Printf("ScarliHQ %s listening on :%s", Version, port)
	// v18.7.5 P0: Removed ?token=<SCARLIHQ_TOKEN> from dashboard URL hint
	// (was: permanent token in URL → leaked in browser history/referrer/proxy logs).
	// Users now log in via the auth gate (token pasted once per browser session,
	// stored in sessionStorage — never in URL).
	log.Printf("Dashboard: http://localhost:%s/ (login with token from /etc/scarlix/.env)", port)
	log.Printf("REST API:    http://localhost:%s/api/*  (Bearer token)", port)
	log.Printf("MCP (JSON-RPC): http://localhost:%s/mcp  (Bearer token)", port)
	log.Printf("WebSocket:   ws://localhost:%s/ws?ticket=<one-time>  (POST /api/ws-ticket to obtain)", port)

	// v18.6 P1: Explicit HTTP server timeouts (was: ListenAndServe with no timeouts → slow-client DoS)
	srv := &http.Server{
		Addr:              ":" + port,
		Handler:           mux,
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       15 * time.Second,
		WriteTimeout:      30 * time.Second,
		IdleTimeout:       60 * time.Second,
		MaxHeaderBytes:    64 << 10, // v18.7.6 P1: 64KB (was: 1MB — unnecessarily large)
	}
	if err := srv.ListenAndServe(); err != nil {
		log.Fatalf("Server failed: %v", err)
	}
}
