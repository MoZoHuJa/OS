package main

import (
	_ "embed" // v18.5.1: blank import for //go:embed directive (Go 1.23 requires it)
	"log"
	"net/http"
	"os"
	"strings"
	"time" // v18.6 P1: explicit server timeouts

	"github.com/MoZoHuJa/OS/scarlihq/internal/agentkernel"
	"github.com/MoZoHuJa/OS/scarlihq/internal/allocation"
	"github.com/MoZoHuJa/OS/scarlihq/internal/api"
	"github.com/MoZoHuJa/OS/scarlihq/internal/compute"
	"github.com/MoZoHuJa/OS/scarlihq/internal/guard"
	"github.com/MoZoHuJa/OS/scarlihq/internal/mcp"
	"github.com/MoZoHuJa/OS/scarlihq/internal/profiles"
	"github.com/MoZoHuJa/OS/scarlihq/internal/scarlix_mode"
	"github.com/MoZoHuJa/OS/scarlihq/internal/webui"
)

// Version is the ScarliHQ application version.
// v18.2 P1: Changed from `const` to `var` — ldflags `-X main.Version` only works on vars.
// v18.0.0: injected via -ldflags "-X main.Version=$VERSION" in Dockerfile.
// Default here matches VERSION file (used when running `go run` without ldflags).
var Version = "19.4.1"

//go:embed frontend/dist/index.html
var indexHTML []byte

func main() {
	log.SetFlags(log.LstdFlags | log.Lshortfile)
	log.Printf("SCARLIX OS %s — ScarliHQ starting (host-bridge architecture)...", Version)

	// Auth token: required for all /api/* and /ws. Generated by generate-env.sh
	// into /etc/scarlix/.env (SCARLIHQ_TOKEN). Passed to container via compose env.
	authToken := os.Getenv("SCARLIHQ_TOKEN")
	if authToken == "" {
		log.Println("WARNING: SCARLIHQ_TOKEN not set — dashboard API will reject all requests. Set SCARLIHQ_TOKEN in /etc/scarlix/.env")
	}

	// Initialize subsystems (all file-based — no privileged host access needed)
	g := guard.New()
	mode := scarlix_mode.New()
	pf := profiles.New("/etc/scarlix/profiles")

	mux := http.NewServeMux()

	// Dashboard HTML (served WITHOUT auth — it's a shell that needs a token to act).
	// v18.7.5 P0: JS reads token from sessionStorage only (was: also from ?token= URL).
	// Without it, shows a token-entry form (paste-once-per-session via auth gate).
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/" {
			http.NotFound(w, r)
			return
		}
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Header().Set("Cache-Control", "no-cache")
		w.Write(indexHTML)
	})

	// REST API + MCP + WS — all behind token auth
	// v18.2 P1: pass Version to Handler (was: separate const — ldflags couldn't override)
	apiHandler := api.NewHandler(g, mode, pf, authToken, Version)
	// Compute lifecycle is opt-in. The bearer token maps to one configured principal;
	// do not enable this shared-token mode for multi-user deployments.
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_COMPUTE_ENABLED")), "true") {
		socketPath := strings.TrimSpace(os.Getenv("SCARLIHQ_COMPUTE_SOCKET"))
		allocationPath := strings.TrimSpace(os.Getenv("SCARLIHQ_ALLOCATION_STORE"))
		principal := strings.TrimSpace(os.Getenv("SCARLIHQ_COMPUTE_PRINCIPAL"))
		if socketPath == "" || allocationPath == "" || principal == "" {
			log.Fatal("compute lifecycle enabled but SCARLIHQ_COMPUTE_SOCKET, SCARLIHQ_ALLOCATION_STORE, or SCARLIHQ_COMPUTE_PRINCIPAL is missing")
		}
		store := allocation.NewStore(allocationPath)
		runtime, err := compute.New(store, socketPath)
		if err != nil {
			log.Fatalf("compute lifecycle initialization failed: %v", err)
		}
		if err := apiHandler.ConfigureCompute(runtime.Manager, principal); err != nil {
			runtime.Close()
			log.Fatalf("compute lifecycle configuration failed: %v", err)
		}
		log.Printf("Compute lifecycle API enabled (allocation store: %s); resource release remains reconciliation-gated", allocationPath)
	} else {
		log.Printf("Compute lifecycle API disabled; set SCARLIHQ_COMPUTE_ENABLED=true only after host bridge acceptance")
	}

	// AK-2 (v19.4.1): Agent Kernel session surface — opt-in, like the compute
	// lifecycle (Controlled Accumulation: small, reversible steps). Sessions
	// are bounded + in-memory; grants are request-supplied until AK-3
	// persists them admin-owned. Evaluate is pure — no host effects at all.
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTKERNEL_ENABLED")), "true") {
		store, err := agentkernel.NewStore(agentkernel.DefaultMaxSessions)
		if err != nil {
			log.Fatalf("agent kernel initialization failed: %v", err)
		}
		if err := apiHandler.ConfigureAgentKernel(store, agentkernel.Policy{}); err != nil {
			log.Fatalf("agent kernel configuration failed: %v", err)
		}
		log.Printf("Agent Kernel session API enabled (max %d sessions, in-memory grants; AK-3 will persist grants)", agentkernel.DefaultMaxSessions)
	} else {
		log.Printf("Agent Kernel session API disabled; set SCARLIHQ_AGENTKERNEL_ENABLED=true to enable")
	}
	apiHandler.RegisterRoutes(mux)

	mcpServer := mcp.NewServer(g, mode, pf, authToken, Version)
	mcpServer.RegisterRoutes(mux)

	webui.RegisterWS(mux, authToken, mode, pf)

	// Start server
	port := os.Getenv("SCARLIHQ_PORT")
	if port == "" {
		port = "8090"
	}

	log.Printf("ScarliHQ %s listening on :%s", Version, port)
	// v18.7.5 P0: Removed ?token=<SCARLIHQ_TOKEN> from dashboard URL hint
	// (was: permanent token in URL → leaked in browser history/referrer/proxy logs).
	// Users now log in via the auth gate (token pasted once per browser session,
	// stored in sessionStorage — never in URL).
	log.Printf("Dashboard: http://localhost:%s/ (login with token from /etc/scarlix/.env)", port)
	log.Printf("REST API:    http://localhost:%s/api/*  (Bearer token)", port)
	log.Printf("MCP (JSON-RPC): http://localhost:%s/mcp  (Bearer token)", port)
	log.Printf("WebSocket:   ws://localhost:%s/ws?ticket=<one-time>  (POST /api/ws-ticket to obtain)", port)

	// v18.6 P1: Explicit HTTP server timeouts (was: ListenAndServe with no timeouts → slow-client DoS)
	srv := &http.Server{
		Addr:              ":" + port,
		Handler:           mux,
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       15 * time.Second,
		WriteTimeout:      30 * time.Second,
		IdleTimeout:       60 * time.Second,
		MaxHeaderBytes:    64 << 10, // v18.7.6 P1: 64KB (was: 1MB — unnecessarily large)
	}
	if err := srv.ListenAndServe(); err != nil {
		log.Fatalf("Server failed: %v", err)
	}
}
