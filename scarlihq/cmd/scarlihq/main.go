func main() {
	log.SetFlags(log.LstdFlags | log.Lshortfile)
	log.Printf("SCARLIX OS %s — ScarliHQ starting (host-bridge architecture)...", Version)

	// Auth token: required for all /api/* and /ws. Generated by generate-env.sh
	// into /etc/scarlix/.env (SCARLIHQ_TOKEN). Passed to container via compose env.
	authToken := os.Getenv("SCARLIHQ_TOKEN")
	if authToken == "" {
		log.Println("WARNING: SCARLIHQ_TOKEN not set — dashboard API will reject all requests. Set SCARLIHQ_TOKEN in /etc/scarlix/.env")
	}

	// Initialize subsystems (all file-based — no privileged host access needed)
	g := guard.New()
	mode := scarlix_mode.New()
	pf := profiles.New("/etc/scarlix/profiles")

	mux := http.NewServeMux()

	// Dashboard HTML (served WITHOUT auth — it's a shell that needs a token to act).
	// v18.7.5 P0: JS reads token from sessionStorage only (was: also from ?token= URL).
	// Without it, shows a token-entry form (paste-once-per-session via auth gate).
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/" {
			http.NotFound(w, r)
			return
		}
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Header().Set("Cache-Control", "no-cache")
		w.Write(indexHTML)
	})

	// REST API + MCP + WS — all behind token auth
	// v18.2 P1: pass Version to Handler (was: separate const — ldflags couldn't override)
	apiHandler := api.NewHandler(g, mode, pf, authToken, Version)
	// Compute lifecycle is opt-in. The bearer token maps to one configured principal;
	// do not enable this shared-token mode for multi-user deployments.
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_COMPUTE_ENABLED")), "true") {
		socketPath := strings.TrimSpace(os.Getenv("SCARLIHQ_COMPUTE_SOCKET"))
		allocationPath := strings.TrimSpace(os.Getenv("SCARLIHQ_ALLOCATION_STORE"))
		principal := strings.TrimSpace(os.Getenv("SCARLIHQ_COMPUTE_PRINCIPAL"))
		if socketPath == "" || allocationPath == "" || principal == "" {
			log.Fatal("compute lifecycle enabled but SCARLIHQ_COMPUTE_SOCKET, SCARLIHQ_ALLOCATION_STORE, or SCARLIHQ_COMPUTE_PRINCIPAL is missing")
		}
		store := allocation.NewStore(allocationPath)
		runtime, err := compute.New(store, socketPath)
		if err != nil {
			log.Fatalf("compute lifecycle initialization failed: %v", err)
		}
		if err := apiHandler.ConfigureCompute(runtime.Manager, principal); err != nil {
			runtime.Close()
			log.Fatalf("compute lifecycle configuration failed: %v", err)
		}
		log.Printf("Compute lifecycle API enabled (allocation store: %s); resource release remains reconciliation-gated", allocationPath)
	} else {
		log.Printf("Compute lifecycle API disabled; set SCARLIHQ_COMPUTE_ENABLED=true only after host bridge acceptance")
	}

	// v19.7.1 (Compute Fabric Phase 2, roadmap §6.4): the aggregate
	// ADMISSION gate — decide + atomically reserve a multi-dimensional
	// resource vector (GPU VRAM per UUID, host RAM, CPU threads, KV
	// cache, storage free bytes + measured read profile, ports) against
	// the live v19.7.0 inventory snapshot, the models.d manifests, and
	// the RECORDED artifact verifications. Opt-in like every mutating
	// act: SCARLIHQ_ADMISSION_ENABLED=true + SCARLIHQ_ADMISSION_LEDGER
	// (a writable, 0600-capacity-accounting file — construction
	// fail-closes on a corrupt/tampered ledger; the routes answer 503
	// until enabled). The surface is ADMIN-gated (reserving capacity is
	// strictly stronger than reading the inventory) and the release is
	// reconciliation-verified, never blind.
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_ADMISSION_ENABLED")), "true") {
		ledgerPath := strings.TrimSpace(os.Getenv("SCARLIHQ_ADMISSION_LEDGER"))
		if ledgerPath == "" {
			log.Fatal("admission gate enabled but SCARLIHQ_ADMISSION_LEDGER is missing (a writable ledger path — capacity accounting is durable, never memory-only in production)")
		}
		admissionMgr, err := admission.NewProductionManager(ledgerPath)
		if err != nil {
			log.Fatalf("admission gate initialization failed: %v (fail closed — never run on a tampered capacity ledger)", err)
		}
		apiHandler.ConfigureAdmission(admissionMgr)
		log.Printf("Admission gate enabled (ledger: %s; policy %s, stale-snapshot hard refusal at %s, lease TTL %s)", ledgerPath, admissionMgr.Policy().PolicyVersion, admissionMgr.Policy().MaxSnapshotAge, admissionMgr.Policy().LeaseTTL)
	} else {
		log.Printf("Admission gate disabled; set SCARLIHQ_ADMISSION_ENABLED=true + SCARLIHQ_ADMISSION_LEDGER=<path> to enable the Compute Fabric Phase 2 surface")
	}

	// v19.7.2 (Compute Fabric Phase 3, roadmap §7): the deterministic
	// EXECUTION PLANNER — the pure, side-effect-free proposal engine over
	// the same snapshot + model seams the admission gate reads (one truth
	// about the machine, two gates). Wired UNCONDITIONALLY like the
	// read-only inventory: the planner reserves nothing, launches
	// nothing, and writes nowhere — POST /api/compute/plan computes a
	// PROPOSAL behind the READ gate (admission, separately opt-in above,
	// is still required before anything binds). Construction validates the
	// CLOSED backend capability registry (roadmap §7.2's "validated at
	// startup") and fail-closes on a malformed SCARLIHQ_PLANNER_IMAGES
	// declaration (backend=reference pairs, digest-pinned; the honest
	// default is EMPTY — every plan refuses plan-image-unconfigured until
	// the operator declares references, the same honesty as v19.7.1's
	// no-verified-manifests default).
	executionPlanner, err := planner.NewProductionPlanner()
	if err != nil {
		log.Fatalf("execution planner initialization failed: %v (fail closed — a malformed planner policy or an inconsistent capability registry is a startup error, never a per-request surprise)", err)
	}
	apiHandler.ConfigurePlanner(executionPlanner)
	if len(executionPlanner.Policy().Images) == 0 {
		log.Printf("Execution planner enabled (policy %s, plan TTL %s, %d priority backends; image registry EMPTY — every plan refuses plan-image-unconfigured until SCARLIHQ_PLANNER_IMAGES declares digest-pinned references)", executionPlanner.Policy().PolicyVersion, executionPlanner.Policy().PlanTTL, len(executionPlanner.Policy().PriorityBackends))
	} else {
		log.Printf("Execution planner enabled (policy %s, plan TTL %s, %d priority backends, %d digest-pinned image declarations)", executionPlanner.Policy().PolicyVersion, executionPlanner.Policy().PlanTTL, len(executionPlanner.Policy().PriorityBackends), len(executionPlanner.Policy().Images))
	}

	// v19.8.0 (Compute Fabric Phase 4, roadmap §8): the InferSSD runtime
	// profile state + the SGLang Expert Pack manifests — the operator's
	// §8.8 enablement surfaces, logged honestly at startup (the profile
	// seam is fail-closed inside the planner's construction above; these
	// lines state WHERE the deployment stands: not configured / disabled
	// documentation / enabled-and-experimental).
	if profile := executionPlanner.Policy().SSDProfile; profile != nil {
		log.Printf("InferSSD runtime profile %s ENABLED (experimental §8.3 planning-side adapter; model %s @ %s; storage device %s with the declared measured floors; every infer_ssd plan still requires the runtime OBSERVED running + healthy — the placement × runtime join)", profile.ProfileID, profile.Compatibility.ModelManifest, profile.Compatibility.CheckpointSHA256, profile.Resources.Storage.DeviceID)
	} else if path := strings.TrimSpace(os.Getenv(planner.InferSSDProfileEnv)); path != "" {
		log.Printf("InferSSD runtime profile %s loaded but DISABLED (roadmap §8.8's initial status — the profile is documentation; the planner stays not-configured and every infer_ssd plan refuses plan-ssd-profile-unconfigured)", path)
	} else {
		log.Printf("InferSSD runtime profile not configured (roadmap §8.8's initial status — SCARLIHQ_INFERSSD_PROFILE declares the path; every infer_ssd plan refuses plan-ssd-profile-unconfigured)")
	}
	// The SGLang Expert Pack manifests (scarlix.artifact/v1, §8.5): loaded
	// beside the model manifests, validated + checkpoint-bound at view
	// time, summarized at startup (invalid entries carry their named
	// reasons — the LoadManifests genre; the example pack ships
	// invalid-by-design documentation). The planner never schedules from
	// packs (the §8.8 enablement policy — pack execution needs pack-byte
	// verification + the §8.7 target-host acceptance matrix, named future
	// work).
	packsLoader := func() []modelmeta.BoundExpertPack {
		manifestsDir := modelmeta.ResolveManifestsDir()
		packsDir := modelmeta.ResolveExpertPacksDir(manifestsDir)
		if packsDir == "" {
			return nil
		}
		loaded := modelmeta.LoadExpertPacks(packsDir)
		manifests := modelmeta.LoadManifests(manifestsDir)
		return modelmeta.BindExpertPacks(loaded.Packs, manifests.Manifests)
	}
	apiHandler.ConfigureExpertPacks(packsLoader)
	if manifestsDir := modelmeta.ResolveManifestsDir(); manifestsDir != "" {
		if packsDir := modelmeta.ResolveExpertPacksDir(manifestsDir); packsDir != "" {
			loaded := modelmeta.LoadExpertPacks(packsDir)
			manifests := modelmeta.LoadManifests(manifestsDir)
			bound := modelmeta.BindExpertPacks(loaded.Packs, manifests.Manifests)
			boundCount := 0
			for _, b := range bound {
				if b.Bound {
					boundCount++
				}
			}
			log.Printf("SGLang Expert Pack manifests: %d loaded, %d checkpoint-bound, %d invalid (scarlix.artifact/v1 — cross-engine packs are refused by name; pack EXECUTION stays unplanned until pack-byte verification + the §8.7 target-host acceptance matrix pass)", len(loaded.Packs), boundCount, len(loaded.Invalid))
			for _, inv := range loaded.Invalid {
				log.Printf("Expert Pack manifest INVALID: %s — %s", inv.Path, strings.Join(inv.Reasons, "; "))
			}
		}
	}

	// v19.9.0 (Compute Fabric Phase 5, roadmap §9): the DISTRIBUTED FABRIC
	// — node identity + enrollment (invite-based, digest-only credentials,
	// rotation grace, quarantine), the observational registry with the
	// STRICTER remote freshness window (30s default), the replay-protected
	// agent pushes, and the network-aware multi-node planner behind the SAME
	// /api/compute/plan route. Opt-in like every mutating surface:
	// SCARLIHQ_FABRIC_ENABLED=true + SCARLIHQ_FABRIC_NODES_LEDGER (a writable
	// 0600 JSONL path — node identity is durable, never memory-only in
	// production). Tailscale/LAN remains TRANSPORT ONLY (roadmap §9.2): the
	// per-node credentials are the authorization, always. Without the
	// opt-in the fabric routes answer 503 and the planner stays single-node
	// — v19.8.1 behavior, unchanged.
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_FABRIC_ENABLED")), "true") {
		nodesPath := strings.TrimSpace(os.Getenv("SCARLIHQ_FABRIC_NODES_LEDGER"))
		if nodesPath == "" {
			log.Fatal("distributed fabric enabled but SCARLIHQ_FABRIC_NODES_LEDGER is missing (a writable node-identity JSONL path — node identity is durable, never memory-only in production)")
		}
		nodeReg, err := nodeidentity.NewRegistry(nodeidentity.NewStore(nodesPath), nodeidentity.SystemClock{}, nodeidentity.RegistryConfig{})
		if err != nil {
			log.Fatalf("distributed fabric initialization failed: %v (fail closed — never run on a corrupt node-identity store)", err)
		}
		fabricReg, err := fabric.NewRegistry(fabric.SystemClock{}, fabric.NewIdentityStatusSource(nodeReg), 0)
		if err != nil {
			log.Fatalf("fabric registry initialization failed: %v", err)
		}
		replayGuard := nodeidentity.NewReplayGuard(nil, 0, 0)
		// The operator-declared per-node latency classes ("node-a=A,node-b=B"
		// — cross-node latency is control-plane knowledge, never an agent
		// self-declaration; unknown nodes default to C, fail-closed).
		latency := parseFabricLatencyClasses(os.Getenv("SCARLIHQ_FABRIC_LATENCY"))
		if err := apiHandler.ConfigureFabric(api.FabricConfig{
			Nodes:          nodeReg,
			Registry:       fabricReg,
			Replay:         replayGuard,
			BasePlanner:    executionPlanner,
			LocalSnapshots: admission.ProductionSnapshotSource{},
			LatencyClasses: latency,
		}); err != nil {
			log.Fatalf("distributed fabric wiring failed: %v (fail closed)", err)
		}
		log.Printf("Distributed fabric enabled (node ledger: %s; %d nodes known, %d latency declarations, remote freshness %s; enroll nodes via POST /api/fabric/nodes — the one-time invite secret is returned exactly once)", nodesPath, len(nodeReg.List()), len(latency), fabricReg.RemoteSnapshotMaxAge())
	} else {
		log.Printf("Distributed fabric disabled; set SCARLIHQ_FABRIC_ENABLED=true + SCARLIHQ_FABRIC_NODES_LEDGER=<path> to enable the Compute Fabric Phase 5 surface (node enrollment + authenticated pushes + the network-aware multi-node planner)")
	}

	// AK-2 (v19.4.1): Agent Kernel session surface — opt-in, like the compute
	// lifecycle (Controlled Accumulation: small, reversible steps). Sessions
	// are bounded + in-memory; grants are request-supplied until AK-3
	// persists them admin-owned. Evaluate is pure — no host effects at all.
	// v19.5.0: kernelStore is hoisted so the Agent Fabric block below can
	// require it (the fabric routes intents through kernel sessions).
	var kernelStore *agentkernel.Store
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTKERNEL_ENABLED")), "true") {
		store, err := agentkernel.NewStore(agentkernel.DefaultMaxSessions)
		if err != nil {
			log.Fatalf("agent kernel initialization failed: %v", err)
		}
		kernelStore = store
		// AK-3 (v19.4.4): persisted, admin-owned grant registry — separate
		// opt-in (SCARLIHQ_AGENT_GRANTS_FILE + SCARLIHQ_AGENT_PRINCIPALS).
		// When configured, grants become admin-owned registry acts bound to
		// the reservation governor's user_tokens principal space; when not,
		// the AK-2 legacy contract (request-supplied grants) stays in force.
		// Load is fail-closed: a corrupt/tampered grants file aborts startup.
		grantsFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENT_GRANTS_FILE"))
		if grantsFile != "" {
			principalsRaw := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENT_PRINCIPALS"))
			if principalsRaw == "" {
				log.Fatal("agent kernel grant registry enabled but SCARLIHQ_AGENT_PRINCIPALS is missing (comma-separated principal names copied from the governor user_tokens config)")
			}
			var principals []string
			for _, p := range strings.Split(principalsRaw, ",") {
				if p = strings.TrimSpace(p); p != "" {
					principals = append(principals, p)
				}
			}
			registry, err := agentkernel.NewGrantRegistry(grantsFile, principals, agentkernel.DefaultMaxGrants, agentkernel.DefaultMaxAgents)
			if err != nil {
				log.Fatalf("agent kernel grant registry construction failed: %v", err)
			}
			if err := registry.Load(); err != nil {
				log.Fatalf("agent kernel grant registry load failed: %v (fix the file or remove it deliberately — never run on a tampered registry)", err)
			}
			if err := apiHandler.ConfigureAgentGrants(registry); err != nil {
				log.Fatalf("agent kernel grant registry configuration failed: %v", err)
			}
			log.Printf("Agent Kernel grant registry enabled (%s; principals: %s; bounds: %d grants/%d agents)", grantsFile, principalsRaw, agentkernel.DefaultMaxGrants, agentkernel.DefaultMaxAgents)
			if err := apiHandler.ConfigureAgentKernel(store, registry.Policy()); err != nil {
				log.Fatalf("agent kernel configuration failed: %v", err)
			}
		} else {
			if strings.TrimSpace(os.Getenv("SCARLIHQ_AGENT_PRINCIPALS")) != "" {
				log.Println("WARNING: SCARLIHQ_AGENT_PRINCIPALS is set but SCARLIHQ_AGENT_GRANTS_FILE is not — the grant registry stays disabled")
			}
			if err := apiHandler.ConfigureAgentKernel(store, agentkernel.Policy{}); err != nil {
				log.Fatalf("agent kernel configuration failed: %v", err)
			}
			log.Printf("Agent Kernel session API enabled (max %d sessions, legacy request-supplied grants; set SCARLIHQ_AGENT_GRANTS_FILE + SCARLIHQ_AGENT_PRINCIPALS for admin-owned grants)", agentkernel.DefaultMaxSessions)
		}

		// AK-4 (v19.4.5): append-only audit sink — separate opt-in
		// (SCARLIHQ_AGENT_AUDIT_FILE). When set, every evaluation is
		// persisted BEFORE its decision is served (fail-closed) and every
		// admin act is appended after its successful persist. Construction
		// is fail-closed (0600/0700 discipline — loose permissions abort
		// startup, tamper discipline like the grant registry).
		auditFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENT_AUDIT_FILE"))
		if auditFile != "" {
			sink, err := agentkernel.NewAuditSink(auditFile)
			if err != nil {
				log.Fatalf("agent kernel audit sink initialization failed: %v (fix the file/dir permissions or path — never run with a tampered audit trail)", err)
			}
			if err := apiHandler.ConfigureAgentAudit(sink); err != nil {
				log.Fatalf("agent kernel audit sink configuration failed: %v", err)
			}
			log.Printf("Agent Kernel audit sink enabled (%s; append-only JSONL, evaluations fail-closed on audit write)", auditFile)
		} else {
			log.Println("Agent Kernel audit sink disabled; set SCARLIHQ_AGENT_AUDIT_FILE to persist every decision and admin act")
		}
	} else {
		log.Printf("Agent Kernel session API disabled; set SCARLIHQ_AGENTKERNEL_ENABLED=true to enable")
	}

	// BF-1 (v19.5.0): Agent Fabric command surface (the ScarliBar backend) —
	// opt-in, like the kernel. The fabric REQUIRES the kernel (intents route
	// through kernel sessions — it has no standalone mode) and a persisted
	// commands file (the durable command history, grants.json discipline:
	// schema version, 0600/0700 fail-closed load, atomic tmp+rename persist,
	// bounded history). Enablement: SCARLIHQ_AGENTFABRIC_ENABLED=true +
	// SCARLIHQ_AGENTFABRIC_COMMANDS_FILE=/var/lib/scarlix-agentfabric/
	// commands.json.
	// BF-3 (v19.5.2): fabricBusRef carries the change-signal bus out of the
	// opt-in block — /ws/bar is ALWAYS registered (503 with a nil bus, the
	// fabric-off contract; never a silently-dead push surface).
	var fabricBusRef *agentfabric.FabricBus
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTFABRIC_ENABLED")), "true") {
		if kernelStore == nil {
			log.Fatal("agent fabric enabled but the agent kernel is not (agent fabric requires SCARLIHQ_AGENTKERNEL_ENABLED=true — intents route through kernel sessions)")
		}
		commandsFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTFABRIC_COMMANDS_FILE"))
		if commandsFile == "" {
			log.Fatal("agent fabric enabled but SCARLIHQ_AGENTFABRIC_COMMANDS_FILE is missing (the command history is persisted — grants.json discipline)")
		}
		fabricStore, err := agentfabric.NewCommandStore(commandsFile, agentfabric.DefaultMaxCommands)
		if err != nil {
			log.Fatalf("agent fabric command store construction failed: %v", err)
		}
		if err := fabricStore.Load(); err != nil {
			log.Fatalf("agent fabric command store load failed: %v (fix the file or archive it deliberately — never run on a tampered command history)", err)
		}
		if err := apiHandler.ConfigureAgentFabric(fabricStore); err != nil {
			log.Fatalf("agent fabric configuration failed: %v", err)
		}
		// BF-2 (v19.5.1): the workspace store rides the fabric opt-in — no
		// separate flag. Its file defaults to workspaces.json NEXT TO the
		// commands file (same 0700 directory, same tamper discipline);
		// SCARLIHQ_AGENTFABRIC_WORKSPACES_FILE overrides the location for
		// operators who want the stores on separate volumes. Fail-closed
		// load like every persisted store — a tampered workspaces file
		// aborts startup, it never degrades into "some workspaces work".
		workspacesFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTFABRIC_WORKSPACES_FILE"))
		if workspacesFile == "" {
			workspacesFile = filepath.Join(filepath.Dir(commandsFile), "workspaces.json")
		}
		wsStore, err := agentfabric.NewWorkspaceStore(workspacesFile, agentfabric.DefaultMaxWorkspaces)
		if err != nil {
			log.Fatalf("agent fabric workspace store construction failed: %v", err)
		}
		if err := wsStore.Load(); err != nil {
			log.Fatalf("agent fabric workspace store load failed: %v (fix the file or archive it deliberately — never run on a tampered workspace history)", err)
		}
		if err := apiHandler.ConfigureAgentWorkspaces(wsStore); err != nil {
			log.Fatalf("agent fabric workspace configuration failed: %v", err)
		}
		// BF-3 (v19.5.2): the execution store + the change-signal bus ride
		// the SAME opt-in (coding/research agent runtimes — no extra flag).
		// The file defaults to executions.json NEXT TO the commands file
		// (same 0700 directory, same tamper discipline);
		// SCARLIHQ_AGENTFABRIC_EXECUTIONS_FILE overrides the location. The
		// runtime mapping invariant is checked at load (a drifted
		// kernel/mapping pair aborts startup — the fabric never runs with
		// a partial mapping). The bus is the /ws/bar push backbone
		// (bounded 16×16, drop-not-block, no replay).
		executionsFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTFABRIC_EXECUTIONS_FILE"))
		if executionsFile == "" {
			executionsFile = filepath.Join(filepath.Dir(commandsFile), "executions.json")
		}
		if err := agentfabric.ValidateRuntimeMapping(); err != nil {
			log.Fatalf("agent fabric runtime mapping invalid: %v (a new kernel capability must declare its runtime deliberately)", err)
		}
		execStore, err := agentfabric.NewExecutionStore(executionsFile, agentfabric.DefaultMaxExecutions)
		if err != nil {
			log.Fatalf("agent fabric execution store construction failed: %v", err)
		}
		if err := execStore.Load(); err != nil {
			log.Fatalf("agent fabric execution store load failed: %v (fix the file or archive it deliberately — never run on a tampered execution history)", err)
		}
		fabricBus := agentfabric.NewFabricBus()
		if err := apiHandler.ConfigureAgentFabricExecutions(execStore, fabricBus); err != nil {
			log.Fatalf("agent fabric execution configuration failed: %v", err)
		}
		// BF-4 (v19.5.3): the approval store rides the SAME opt-in (the
		// operator approval gate — no extra flag). The file defaults to
		// approvals.json NEXT TO the commands file (same 0700 directory,
		// same tamper discipline); SCARLIHQ_AGENTFABRIC_APPROVALS_FILE
		// overrides the location. Fail-closed load like every persisted
		// store — a tampered approvals file aborts startup, it never
		// degrades into "some approvals work". The approval boundary is
		// the runtime boundary (coding acts require the operator's yes;
		// research acts execute directly — read-only by construction).
		approvalsFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTFABRIC_APPROVALS_FILE"))
		if approvalsFile == "" {
			approvalsFile = filepath.Join(filepath.Dir(commandsFile), "approvals.json")
		}
		apvStore, err := agentfabric.NewApprovalStore(approvalsFile, agentfabric.DefaultMaxApprovals)
		if err != nil {
			log.Fatalf("agent fabric approval store construction failed: %v", err)
		}
		if err := apvStore.Load(); err != nil {
			log.Fatalf("agent fabric approval store load failed: %v (fix the file or archive it deliberately — never run on a tampered approval history)", err)
		}
		if err := apiHandler.ConfigureAgentFabricApprovals(apvStore); err != nil {
			log.Fatalf("agent fabric approval configuration failed: %v", err)
		}
		// CF-3 (v19.6.2): the proposal store rides the SAME opt-in (the LLM
		// propose surface — no extra flag; the proposal is a fabric entity:
		// it becomes a command only through the operator's accept). The file
		// defaults to proposals.json NEXT TO the commands file (same 0700
		// directory, same tamper discipline); SCARLIHQ_AGENTFABRIC_PROPOSALS_FILE
		// overrides the location. Fail-closed load like every persisted store —
		// a tampered proposals file aborts startup, it never degrades into
		// "some proposals work". The propose endpoint additionally requires
		// SCARLIHQ_AIRUNTIME_ENABLED=true (the runtime side of the bridge);
		// accept/dismiss/list need only the fabric — 503 otherwise, honestly.
		proposalsFile := strings.TrimSpace(os.Getenv("SCARLIHQ_AGENTFABRIC_PROPOSALS_FILE"))
		if proposalsFile == "" {
			proposalsFile = filepath.Join(filepath.Dir(commandsFile), "proposals.json")
		}
		prpStore, err := agentfabric.NewProposalStore(proposalsFile, agentfabric.DefaultMaxProposals)
		if err != nil {
			log.Fatalf("agent fabric proposal store construction failed: %v", err)
		}
		if err := prpStore.Load(); err != nil {
			log.Fatalf("agent fabric proposal store load failed: %v (fix the file or archive it deliberately — never run on a tampered proposal history)", err)
		}
		if err := apiHandler.ConfigureAgentFabricProposals(prpStore); err != nil {
			log.Fatalf("agent fabric proposal configuration failed: %v", err)
		}
		log.Printf("Agent Fabric proposal API enabled (the LLM propose surface: an LLM response becomes a fabric PROPOSAL — never an auto-submitted command; the operator's accept is the only door to a command; proposals file: %s; bound %d records — one command reference per proposal, decisions are terminal; POST /api/ai/propose additionally needs SCARLIHQ_AIRUNTIME_ENABLED=true)", proposalsFile, agentfabric.DefaultMaxProposals)
		log.Printf("Agent Fabric command API enabled (ScarliBar backend; commands file: %s; bound %d records — the file is the history, rotate deliberately)", commandsFile, agentfabric.DefaultMaxCommands)
		log.Printf("Agent Fabric workspace API enabled (workspaces file: %s; bound %d workspaces / %d sessions each — ARCHIVED is the terminal tombstone)", workspacesFile, agentfabric.DefaultMaxWorkspaces, agentfabric.MaxSessionsPerWorkspace)
		log.Printf("Agent Fabric execution API enabled (runtimes: research read-only / coding bridged; executions file: %s; bound %d records — one execution per command, records are terminal; stale-allow guard evaluates FRESH at execute time)", executionsFile, agentfabric.DefaultMaxExecutions)
		log.Printf("Agent Fabric approval API enabled (the operator gate: coding acts require an explicit yes — research acts execute directly; approvals file: %s; bound %d records — one request per command, decisions are terminal)", approvalsFile, agentfabric.DefaultMaxApprovals)
		fabricBusRef = fabricBus
	} else {
		log.Printf("Agent Fabric command API disabled; set SCARLIHQ_AGENTFABRIC_ENABLED=true (requires the agent kernel + SCARLIHQ_AGENTFABRIC_COMMANDS_FILE)")
	}

	// CF-2 (v19.6.1): Universal AI Runtime — the normalized LLM layer behind
	// the pure CF-1 contract (internal/airuntime, untouched). Opt-in like
	// every user-facing surface: four local-stack adapters + the health
	// prober + the REST surface (/api/ai/*), all fail-closed (503) until
	// SCARLIHQ_AIRUNTIME_ENABLED=true. Endpoints default to the API-map host
	// ports; inside this container the stack is reachable by service name —
	// override with SCARLIHQ_AIRUNTIME_SGLANG_URL / _VLLM_URL / _BEELLAMA_URL / _OLLAMA_URL.
	// Chat is transport-only: an LLM response becoming a fabric PROPOSAL is
	// CF-3, behind the fabric's approvals ("LLM navrhuje, politika
	// rozhoduje").
	if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_AIRUNTIME_ENABLED")), "true") {
		endpoints, err := airt.EndpointsFromEnv(os.Getenv)
		if err != nil {
			log.Fatalf("ai runtime endpoint configuration failed: %v (an invalid override is never a silent fall-back — fix the env)", err)
		}
		// KPK-02 (v19.6.3): the per-attempt chat timeout is operator-tunable
		// (SCARLIHQ_AIRUNTIME_CHAT_TIMEOUT — default 30s, the stack's own
		// timeout_ms precedent; upper bound 300s, a named number never an
		// unbounded one). The END-TO-END budget for one AI request is the
		// timeout × the closed four-tier set (airt.ChatBudget — the complete
		// honest failover walk); the API layer imposes it as the request
		// deadline and extends the HTTP write path beyond it (see
		// internal/api/airuntime.go). One coherent contract, documented once.
		chatTimeout := airt.DefaultAdapterTimeout
		if raw := strings.TrimSpace(os.Getenv("SCARLIHQ_AIRUNTIME_CHAT_TIMEOUT")); raw != "" {
			d, err := time.ParseDuration(raw)
			if err != nil || d <= 0 || d > airt.MaxAdapterTimeout {
				log.Fatalf("ai runtime chat timeout %q is not a positive Go duration within the %s upper bound (e.g. 30s — the per-attempt bound; the end-to-end budget is 4x that)", raw, airt.MaxAdapterTimeout)
			}
			chatTimeout = d
		}
		// KPK-03 (v19.6.4) + KPK-19.6.4-P2-01 (v19.6.5) + KPK-19.6.5-P2-01
		// (v19.6.6): the trusted dial networks for service-name endpoints —
		// the dial guard RESOLVES a configured name, validates EVERY
		// answered address against these networks (loopback is always
		// trusted) and PINNS the connection to a validated address. Unset →
		// the Docker default address pool ENUMERATED as fifteen canonical
		// /16s (172.17.0.0/16 … 172.31.0.0/16 — v19.6.6: the non-canonical
		// "172.17.0.0/12" shorthand masked to 172.16.0.0/12 and trusted
		// 172.16.0.0/16 by accident of CIDR normalization; the home-LAN
		// range 192.168.0.0/16 is NOT implicit either — an operator whose
		// scarlix-net lives outside the pool declares it, e.g. the subnet
		// from 'docker network inspect scarlix-net'); a declared set
		// REPLACES the default (an explicit 10.0.0.0/8 must be declared —
		// no blind RFC1918 trust; a UNIVERSAL route 0.0.0.0/0 / ::/0 is
		// refused — it would nullify the boundary).
		// Fail-closed on garbage, like every env surface.
		var dialOpts []airt.DialOption
		if raw := strings.TrimSpace(os.Getenv(airt.TrustedCIDRsEnvVar)); raw != "" {
			cidrs, err := airt.TrustedDialCIDRsFromEnv(os.Getenv)
			if err != nil {
				log.Fatalf("ai runtime trusted dial networks configuration failed: %v (an invalid override is never a silent fall-back — fix the env)", err)
			}
			dialOpts = append(dialOpts, airt.WithTrustedDialCIDRs(cidrs))
		} else if names := airt.UndeclaredServiceNameEndpoints(endpoints); len(names) > 0 {
			// v19.6.6 (the SK-audit P2-01 guidance): service-name endpoints
			// with NO trusted-network declaration are riding the Docker
			// default address pool enumeration (172.17.0.0/16 …
			// 172.31.0.0/16); a scarlix-net created OUTSIDE that pool will
			// fail at DIAL time, not at boot. A loud startup warning with
			// the exact derivation command — the operator declares the
			// ACTUAL subnet before production (explicit, visible,
			// auditable), and the log line is the evidence it was asked.
			log.Printf("WARNING: AI runtime endpoints use service names (%v) while %s is UNSET — only Docker's default address pool (172.17.0.0/16…172.31.0.0/16, no 172.16.0.0/16) is trusted by default; if scarlix-net lives elsewhere, derive the ACTUAL subnet with 'docker network inspect scarlix-net -f '{{range .IPAM.Config}}{{.Subnet}}{{end}}'' and declare it in %s (v19.6.6, SK-audit P2-01)", names, airt.TrustedCIDRsEnvVar, airt.TrustedCIDRsEnvVar)
		}
		adapters, prober, err := airt.NewLocalStack(endpoints, chatTimeout, dialOpts...)
		if err != nil {
			log.Fatalf("ai runtime transport construction failed: %v", err)
		}
		registry, err := airuntime.NewModelRegistry(airuntime.DefaultMaxModels)
		if err != nil {
			log.Fatalf("ai runtime model registry construction failed: %v", err)
		}
		aiRuntime, err := airt.NewRuntime(registry, airuntime.NewHealthTable(), prober, adapters, airt.ChatBudget(chatTimeout))
		if err != nil {
			log.Fatalf("ai runtime construction failed: %v", err)
		}
		// Operator bootstrap: SCARLIHQ_AIRUNTIME_MODELS="provider:model,..."
		// declares the initial routing surface (the registry IS the routing
		// surface; the pair splits on the FIRST colon — model ids may carry
		// their own, e.g. qwen3:4b). A malformed declaration aborts startup:
		// the runtime never boots on a guessed registry.
		if raw := strings.TrimSpace(os.Getenv("SCARLIHQ_AIRUNTIME_MODELS")); raw != "" {
			for _, pair := range strings.Split(raw, ",") {
				pair = strings.TrimSpace(pair)
				if pair == "" {
					continue
				}
				parts := strings.SplitN(pair, ":", 2)
				if len(parts) != 2 {
					log.Fatalf("ai runtime models bootstrap: %q is not provider:model (split on the first colon — model ids may carry their own)", pair)
				}
				if err := aiRuntime.Register(airuntime.Provider(parts[0]), airuntime.ModelID(parts[1])); err != nil {
					log.Fatalf("ai runtime models bootstrap: %q: %v", pair, err)
				}
			}
		}
		// Freshness loop: probing on an interval is opt-in (without it,
		// POST /api/ai/probe is the operator's refresh — the table never
		// expires entries on its own, the CF-1 discipline).
		if raw := strings.TrimSpace(os.Getenv("SCARLIHQ_AIRUNTIME_PROBE_INTERVAL")); raw != "" {
			interval, err := time.ParseDuration(raw)
			if err != nil || interval <= 0 {
				log.Fatalf("ai runtime probe interval %q is not a positive Go duration (e.g. 30s)", raw)
			}
			if _, err := aiRuntime.StartProber(interval); err != nil {
				log.Fatalf("ai runtime prober start failed: %v", err)
			}
			log.Printf("Universal AI Runtime probe loop started (interval %s — every tier probed and recorded each round)", interval)
		}
		// v19.6.7 (KPK-19.6.6-P2-02): the ENFORCED monthly token budget —
		// the durable usage ledger (reserve-before-forward, settle the
		// provider-reported usage after; atomic tmp+rename persist; the
		// grants.json tamper discipline). Default path:
		// /var/lib/scarlihq-budget/token-budget.json (mount it rw in the
		// compose — see the v19.6.7 note there). An EXPLICIT
		// SCARLIHQ_AIRUNTIME_BUDGET_LEDGER that fails to load/validate
		// ABORTS STARTUP (never run on a tampered ledger); a failed DEFAULT
		// path degrades the budgets to loudly-warned informational metadata
		// (the documented degraded policy — an unaccountable budget is not
		// a budget, so the runtime says so instead of pretending).
		budgetPath := strings.TrimSpace(os.Getenv("SCARLIHQ_AIRUNTIME_BUDGET_LEDGER"))
		budgetExplicit := budgetPath != ""
		if budgetPath == "" {
			budgetPath = "/var/lib/scarlihq-budget/token-budget.json"
		}
		budgetLedger, budgetErr := profiles.NewBudgetLedger(budgetPath)
		if budgetErr != nil {
			if budgetExplicit {
				log.Fatalf("token budget ledger initialization failed: %v (fix the file or archive it deliberately — never run on a tampered usage ledger)", budgetErr)
			}
			log.Printf("WARNING: token budget enforcement UNAVAILABLE (%v) — declared monthly budgets degrade to INFORMATIONAL metadata until %s is writable; mount /var/lib/scarlihq-budget rw (see scarlihq/docker-compose.yml) or set SCARLIHQ_AIRUNTIME_BUDGET_LEDGER (KPK-19.6.6-P2-02)", budgetErr, budgetPath)
		} else {
			if err := apiHandler.ConfigureBudgetLedger(budgetLedger); err != nil {
				log.Fatalf("token budget ledger configuration failed: %v", err)
			}
			log.Printf("Token budget enforcement ENABLED (ledger: %s) — monthly budgets are enforced on /api/ai/chat: reserve-before-forward, settle the provider-reported usage, failed attempts not billed, the monthly window is a UTC calendar month, exhaustion is a stable 429 (KPK-19.6.6-P2-02)", budgetPath)
		}
		if err := apiHandler.ConfigureAIRuntime(aiRuntime); err != nil {
			log.Fatalf("ai runtime configuration failed: %v", err)
		}
		log.Printf("Universal AI Runtime API enabled (/api/ai/health, /api/ai/models, /api/ai/probe, /api/ai/chat, /api/ai/propose with the fabric's proposal store — Bearer-gated; sglang %s · vllm %s · beellama %s · ollama %s; %d models registered; per-attempt %s, end-to-end budget %s (KPK-02 — the write path extends beyond it); the local-only transport: no redirects, no ambient proxy, dial-guarded with resolve-validate-pin over the trusted local networks (KPK-01/KPK-03 — unset %s means the Docker default address pool, enumerated canonical /16s 172.17.0.0/16…172.31.0.0/16, no 172.16.0.0/16; a cancelled probe round records nothing, KPK-04); the LLM proposes, policy decides)", endpoints[airuntime.ProviderSGLang], endpoints[airuntime.ProviderVLLM], endpoints[airuntime.ProviderBeeLlama], endpoints[airuntime.ProviderOllama], registry.Len(), chatTimeout, airt.ChatBudget(chatTimeout), airt.TrustedCIDRsEnvVar)
	} else {
		log.Printf("Universal AI Runtime API disabled; set SCARLIHQ_AIRUNTIME_ENABLED=true to enable (/api/ai/* — adapters for the local stack + health probing + failover chat)")
	}

	// v19.6.7 (KPK-19.6.6-P1-01): PER-PROFILE AUTHENTICATION — the family
	// profiles become identity-bound. A per-profile token index (one
	// profile:token per line in the tokens file, or the inline env form)
	// activates MULTI-USER mode: every token resolves to exactly one
	// principal, the profile reference is checked against it (a family
	// token cannot select the zmor admin profile or skip its own policy),
	// and an omitted reference is DERIVED from the principal — there is
	// no policy-free path. The household SCARLIHQ_TOKEN remains the ADMIN
	// identity (the operator); ROTATE it when enabling multi-user mode if
	// it was ever shared. Without an index the deployment is SINGLE-USER
	// (one token, one identity, the admin) — named explicitly, never
	// mistaken for household isolation.
	var profileTokenIndex *profiles.TokenIndex
	if raw := strings.TrimSpace(os.Getenv("SCARLIHQ_PROFILE_TOKENS")); raw != "" {
		idx, err := profiles.ParseTokenIndex(raw, authToken)
		if err != nil {
			log.Fatalf("per-profile token configuration failed: %v (an invalid identity source is never a silent fall-back — fix the env)", err)
		}
		profileTokenIndex = idx
	} else {
		tokensFile := strings.TrimSpace(os.Getenv("SCARLIHQ_PROFILE_TOKENS_FILE"))
		if tokensFile == "" {
			tokensFile = "/etc/scarlix/profile-tokens.conf"
		}
		if _, err := os.Stat(tokensFile); err == nil {
			idx, err := profiles.LoadTokenIndex(tokensFile, authToken)
			if err != nil {
				log.Fatalf("per-profile token configuration failed: %v (a broken identity source is never a silent fall-back — fix the file)", err)
			}
			profileTokenIndex = idx
		}
	}
	if profileTokenIndex != nil {
		if err := apiHandler.ConfigureProfileAuthz(profileTokenIndex); err != nil {
			log.Fatalf("per-profile authentication wiring failed: %v", err)
		}
		log.Printf("Per-profile authentication ENABLED (multi-user): %d profile identities bound to their own Bearer tokens — profile references are checked against the authenticated principal and omissions are DERIVED from it (REST + MCP, one shared authorization function); the household token remains the ADMIN identity — rotate it if it was ever shared (KPK-19.6.6-P1-01)", profileTokenIndex.Len())
	} else if strings.EqualFold(strings.TrimSpace(os.Getenv("SCARLIHQ_SINGLE_USER")), "true") {
		log.Printf("Profile authentication: SINGLE-USER mode (SCARLIHQ_SINGLE_USER=true, explicit) — the household token is the ONE identity (the admin); profile references select policy contexts, they do not isolate users (KPK-19.6.6-P1-01)")
	} else {
		log.Printf("Profile authentication: single-user (implicit — no per-profile tokens configured and SCARLIHQ_SINGLE_USER is unset): the household token is the ONE identity. For household isolation create /etc/scarlix/profile-tokens.conf (profile:token per line, chmod 400) or set SCARLIHQ_PROFILE_TOKENS=name:token,... — see docs/SCARLIX_SECURITY_MAP.md (KPK-19.6.6-P1-01)")
	}

	apiHandler.RegisterRoutes(mux)

	mcpServer := mcp.NewServer(g, mode, pf, authToken, Version)
	if profileTokenIndex != nil {
		if err := mcpServer.ConfigureProfileAuthz(profileTokenIndex); err != nil {
			log.Fatalf("per-profile authentication wiring (MCP) failed: %v", err)
		}
	}
	mcpServer.RegisterRoutes(mux)

	webui.RegisterWS(mux, authToken, mode, pf)
	// BF-3 (v19.5.2): the fabric push surface — /ws/bar shares the ticket
	// discipline AND the wsSlots budget with /ws; a nil bus (fabric off)
	// answers 503 before the upgrade. Change signals, not state: the
	// client refetches through the auth-gated REST surface.
	webui.RegisterBarWS(mux, fabricBusRef)

	// Start server
	port := os.Getenv("SCARLIHQ_PORT")
	if port == "" {
		port = "8090"
	}

	log.Printf("ScarliHQ %s listening on :%s", Version, port)
	// v18.7.5 P0: Removed ?token=<SCARLIHQ_TOKEN> from dashboard URL hint
	// (was: permanent token in URL → leaked in browser history/referrer/proxy logs).
	// Users now log in via the auth gate (token pasted once per browser session,
	// stored in sessionStorage — never in URL).
	log.Printf("Dashboard: http://localhost:%s/ (login with token from /etc/scarlix/.env)", port)
	log.Printf("REST API:    http://localhost:%s/api/*  (Bearer token)", port)
	log.Printf("MCP (JSON-RPC): http://localhost:%s/mcp  (Bearer token)", port)
	log.Printf("WebSocket:   ws://localhost:%s/ws?ticket=<one-time>  (POST /api/ws-ticket to obtain)", port)

	// v18.6 P1: Explicit HTTP server timeouts (was: ListenAndServe with no timeouts → slow-client DoS)
	// v19.6.3 (KPK-02): WriteTimeout stays the 30s DEFAULT for every surface;
	// /api/ai/chat and /api/ai/propose extend their own per-request write deadline
	// beyond the AI chat budget (http.ResponseController — internal/api/airuntime.go),
	// so a legitimate slow local-model answer is written, never cut by this default.
	srv := &http.Server{
		Addr:              ":" + port,
		Handler:           mux,
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       15 * time.Second,
		WriteTimeout:      30 * time.Second,
		IdleTimeout:       60 * time.Second,
		MaxHeaderBytes:    64 << 10, // v18.7.6 P1: 64KB (was: 1MB — unnecessarily large)
	}
	if err := srv.ListenAndServe(); err != nil {
		log.Fatalf("Server failed: %v", err)
	}
}
