// BF-2 (v19.5.1): the agent workspace model. A workspace is a named,
// persisted ISOLATION CONTEXT: agent sessions may be attached to it (at
// most one workspace per session — isolation means the session's routing
// namespace is unambiguous) and commands may be submitted into it (a
// workspace-scoped command routes ONLY through that workspace's member
// sessions; an unscoped command keeps the BF-1 behavior).
//
// The model follows the BF-1 command discipline exactly:
//   - typed validated IDs ("ws-" + 16 crypto-random bytes hex, RNG
//     fail-closed — a predictable ID is never issued);
//   - a CLOSED state enumeration: ACTIVE → ARCHIVED (terminal). ARCHIVED
//     is a tombstone: the workspace stays readable (its commands stay
//     visible, cancellable — a user act), but no new routing, no new
//     submissions, no membership changes. Re-activating an archived
//     workspace is deliberately NOT possible — a fresh workspace is a
//     fresh context (the "file is the history" discipline: states never
//     move backwards);
//   - bounded text fields (name ≤ 64 runes, description ≤ 256 runes, NO
//     control characters — they land in a JSON file, REST responses and
//     the dashboard DOM);
//   - bounded membership (MaxSessionsPerWorkspace) and invariants
//     enforced at load AND after every mutation.
package agentfabric

import (
	"fmt"
	"strings"
	"time"
	"unicode/utf8"
)

// ---------------------------------------------------------------------------
// Workspace identity
// ---------------------------------------------------------------------------

// WorkspaceID is a typed, validated workspace identifier: "ws-" + 16
// crypto-random bytes hex (35 chars). Generated by the store (fail-closed
// RNG — the cmd-/aks- precedent).
type WorkspaceID string

const (
	workspaceIDPrefix = "ws-"
	workspaceIDHexLen = 32 // 16 bytes hex
	workspaceIDLen    = len(workspaceIDPrefix) + workspaceIDHexLen
)

// Validate checks the canonical workspace ID shape.
func (w WorkspaceID) Validate() error {
	s := string(w)
	if s == "" {
		return fmt.Errorf("agentfabric: workspace id is empty")
	}
	if len(s) != workspaceIDLen {
		return fmt.Errorf("agentfabric: workspace id %q must be %d chars (ws- + 32 hex)", s, workspaceIDLen)
	}
	if !strings.HasPrefix(s, workspaceIDPrefix) {
		return fmt.Errorf("agentfabric: workspace id %q must start with %q", s, workspaceIDPrefix)
	}
	for _, r := range s[len(workspaceIDPrefix):] {
		if (r >= '0' && r <= '9') || (r >= 'a' && r <= 'f') {
			continue
		}
		return fmt.Errorf("agentfabric: workspace id %q hex part must be [0-9a-f]", s)
	}
	return nil
}

// ---------------------------------------------------------------------------
// Text bounds (name / description)
// ---------------------------------------------------------------------------

// MaxWorkspaceNameRunes bounds one workspace name. Names are identifiers a
// human scans in a table — a paragraph is not a name.
const MaxWorkspaceNameRunes = 64

// MaxWorkspaceDescriptionRunes bounds one workspace description (the
// human-facing "what is this context for" line).
const MaxWorkspaceDescriptionRunes = 256

// ValidateWorkspaceName checks the workspace name: trimmed non-empty, at
// most MaxWorkspaceNameRunes runes, NO control characters (same rule as
// the intent — JSON file, REST response, dashboard DOM).
func ValidateWorkspaceName(name string) error {
	trimmed := strings.TrimSpace(name)
	if trimmed == "" {
		return fmt.Errorf("agentfabric: workspace name is empty after trimming")
	}
	if utf8.RuneCountInString(trimmed) > MaxWorkspaceNameRunes {
		return fmt.Errorf("agentfabric: workspace name longer than %d runes", MaxWorkspaceNameRunes)
	}
	for _, r := range trimmed {
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf("agentfabric: workspace name contains control character U+%04X", r)
		}
	}
	return nil
}

// ValidateWorkspaceDescription checks the workspace description: at most
// MaxWorkspaceDescriptionRunes runes, NO control characters; empty is
// legal (the description is optional).
func ValidateWorkspaceDescription(desc string) error {
	trimmed := strings.TrimSpace(desc)
	if utf8.RuneCountInString(trimmed) > MaxWorkspaceDescriptionRunes {
		return fmt.Errorf("agentfabric: workspace description longer than %d runes", MaxWorkspaceDescriptionRunes)
	}
	for _, r := range trimmed {
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf("agentfabric: workspace description contains control character U+%04X", r)
		}
	}
	return nil
}

// ---------------------------------------------------------------------------
// Session membership shape
// ---------------------------------------------------------------------------

// validSessionIDShape reports whether s has the kernel session ID shape:
// "aks-" + 32 hex (35 chars). The shape check is a LOAD-TIME integrity
// guard only — existence and ACTIVITY are the kernel's business, resolved
// by the API layer at join/route time (the store never talks to the
// kernel; separate concerns, composed at the boundary).
func validSessionIDShape(s string) bool {
	if len(s) != len("aks-")+32 {
		return false
	}
	if !strings.HasPrefix(s, "aks-") {
		return false
	}
	for _, r := range s[len("aks-"):] {
		if (r >= '0' && r <= '9') || (r >= 'a' && r <= 'f') {
			continue
		}
		return false
	}
	return true
}

// ---------------------------------------------------------------------------
// Workspace lifecycle (closed enumeration)
// ---------------------------------------------------------------------------

// WorkspaceState is the workspace lifecycle. ARCHIVED is terminal.
//
// ACTIVE: sessions may join/leave; commands may be submitted into the
// workspace and routed through its member sessions.
// ARCHIVED: the tombstone — no submissions, no routing, no membership
// changes. The workspace and its command history stay readable (and
// live commands stay CANCELABLE — cancellation is a user act on visible
// state, not a routing event).
type WorkspaceState string

const (
	WorkspaceActive   WorkspaceState = "ACTIVE"
	WorkspaceArchived WorkspaceState = "ARCHIVED"
)

// validWorkspaceState reports whether s is a known state.
func validWorkspaceState(s WorkspaceState) bool {
	switch s {
	case WorkspaceActive, WorkspaceArchived:
		return true
	}
	return false
}

// ---------------------------------------------------------------------------
// Workspace record
// ---------------------------------------------------------------------------

// WorkspaceRecord is one persisted workspace. Sessions is the membership
// list in join order (stable, deduplicated, load-validated). A session
// belongs to AT MOST ONE workspace — the store enforces the claim across
// all records (isolation means an unambiguous routing namespace).
type WorkspaceRecord struct {
	ID          string         `json:"id"`
	Name        string         `json:"name"`
	Description string         `json:"description,omitempty"`
	State       WorkspaceState `json:"state"`
	Sessions    []string       `json:"sessions"`
	CreatedAt   time.Time      `json:"created_at"`
	ArchivedAt  *time.Time     `json:"archived_at,omitempty"`
	UpdatedAt   time.Time      `json:"updated_at"`
}

// validate checks the record invariants (used at load AND after every
// mutation — the store never persists a record it would refuse to load).
//
// Invariants:
//   - ID shape, name/description bounds, closed-enumeration state
//   - ACTIVE: archived_at absent; ARCHIVED: archived_at present
//   - every session ID has the aks- shape; no duplicates
//   - at most MaxSessionsPerWorkspace members
//   - monotone timestamps: created ≤ archived ≤ updated
func (r WorkspaceRecord) validate() error {
	if err := WorkspaceID(r.ID).Validate(); err != nil {
		return err
	}
	if err := ValidateWorkspaceName(r.Name); err != nil {
		return err
	}
	if err := ValidateWorkspaceDescription(r.Description); err != nil {
		return err
	}
	if !validWorkspaceState(r.State) {
		return fmt.Errorf("agentfabric: workspace %s: unknown state %q", r.ID, r.State)
	}
	if len(r.Sessions) > MaxSessionsPerWorkspace {
		return fmt.Errorf("agentfabric: workspace %s: %d member sessions exceed the bound %d", r.ID, len(r.Sessions), MaxSessionsPerWorkspace)
	}
	seen := make(map[string]bool, len(r.Sessions))
	for _, sid := range r.Sessions {
		if !validSessionIDShape(sid) {
			return fmt.Errorf("agentfabric: workspace %s: member session id %q does not have the aks- shape", r.ID, sid)
		}
		if seen[sid] {
			return fmt.Errorf("agentfabric: workspace %s: duplicate member session id %s", r.ID, sid)
		}
		seen[sid] = true
	}
	if r.CreatedAt.IsZero() {
		return fmt.Errorf("agentfabric: workspace %s: zero created_at", r.ID)
	}
	if r.UpdatedAt.Before(r.CreatedAt) {
		return fmt.Errorf("agentfabric: workspace %s: updated_at before created_at", r.ID)
	}
	switch r.State {
	case WorkspaceActive:
		if r.ArchivedAt != nil {
			return fmt.Errorf("agentfabric: workspace %s: ACTIVE record carries archived_at", r.ID)
		}
	case WorkspaceArchived:
		if r.ArchivedAt == nil {
			return fmt.Errorf("agentfabric: workspace %s: ARCHIVED record misses archived_at", r.ID)
		}
		if r.ArchivedAt.Before(r.CreatedAt) {
			return fmt.Errorf("agentfabric: workspace %s: archived_at before created_at", r.ID)
		}
		if r.UpdatedAt.Before(*r.ArchivedAt) {
			return fmt.Errorf("agentfabric: workspace %s: updated_at before archived_at", r.ID)
		}
	}
	return nil
}

// IsMember reports whether the session is a member of the workspace.
func (r WorkspaceRecord) IsMember(sessionID string) bool {
	for _, sid := range r.Sessions {
		if sid == sessionID {
			return true
		}
	}
	return false
}

// copyWorkspaceRecord returns a deep copy of the record (the Sessions
// slice is re-allocated — callers can never mutate store state through a
// returned record; the copyCommandRecord discipline).
func copyWorkspaceRecord(r WorkspaceRecord) WorkspaceRecord {
	out := r
	if r.Sessions != nil {
		out.Sessions = make([]string, len(r.Sessions))
		copy(out.Sessions, r.Sessions)
	}
	if r.ArchivedAt != nil {
		t := *r.ArchivedAt
		out.ArchivedAt = &t
	}
	return out
}
