// BF-4 (v19.5.3): the operator approval model — the human gate for
// MUTATING acts. The contract, in one breath:
//
//	the coding runtime performs acts that change host state (mode
//	requests, compute reserve/release through the bridges). BF-3
//	executes them on a single POST; BF-4 inserts a HUMAN decision
//	between the request and the act: a coding execution first creates
//	a PENDING approval request (params captured, submitter labeled),
//	an operator APPROVES (the act runs, the fresh kernel evaluation
//	still applies) or REJECTS (terminal, no act ever). Research acts
//	are read-only by construction — they execute directly, no
//	approval is ever created for them.
//
// The approval boundary IS the runtime boundary:
// ApprovalRequiredForCapability answers exactly the capabilities bound to
// RuntimeCoding. This is a derivation, not a second literal map — the two
// policies cannot drift: whatever mutates requires an explicit operator
// yes, whatever only observes does not. A capability that needs different
// treatment is a runtime-mapping change, not an approval-map guess.
//
// Approval states are a closed enumeration. PENDING is the ONLY in-flight
// state in the whole fabric (deliberately: the execution record stays
// terminal-by-construction — the approval request is the thing a human
// is holding, the execution record is the thing the machine did):
//
//	PENDING   — requested, awaiting the operator
//	APPROVED  — the operator said yes; the act ran (execution_id
//	            references the terminal execution record — always,
//	            even when the fresh evaluation denied at approve time:
//	            APPROVED + SKIPPED is the honest composition "the
//	            operator allowed it, the kernel did not")
//	REJECTED  — the operator said no; terminal, no act ever ran
//
// There is deliberately NO withdrawn state: a PENDING request's command
// is DECIDED — terminal in the command lifecycle, it can never be
// cancelled after the fact — and commands are never deleted. The request
// therefore cannot drift out from under the operator: it stays answerable
// (approve or reject) until the operator decides, and a request nobody
// answers stays PENDING in the reviewable history. A state no surface
// can reach would be a lie in the enumeration.
//
// One approval request per command, ever — the mirror of one-execution-
// per-command. A rejected request closes the command's execution path
// (retry is a NEW intent at the bar; the file is the history).
//
// Invariants enforced at load AND before persist (the store discipline):
//   - state↔fields coherence: PENDING carries no approver/execution/
//     decision time; APPROVED requires approver + execution_id + decided_at;
//     REJECTED requires approver + decided_at, never an execution.
//   - runtime↔capability coherence: the record's runtime must equal
//     RuntimeForCapability(capability) — the closed mapping is record
//     integrity, exactly like execution records.
//   - params↔capability coherence: the captured params match the closed
//     params shape for the capability — research capabilities never carry
//     params (no approval exists for them at all), mode.request carries
//     mode only, compute.reserve/release carry allocation_id only.
//   - approver/submitter labels are bounded (ValidatePrincipalLabel) —
//     labels are ATTRIBUTION, not credentials: the bearer token remains
//     the only authentication boundary (single-principal deployments).
package agentfabric

