// Package agentfabric is the Agent Fabric foundation (BF-1, v19.5.x line).
//
// Phase B opens the user-facing line above the Agent Kernel: ScarliBar is
// the intent entry point (the bar where a user says WHAT they want) and the
// Agent Fabric is the machinery that turns a captured intent into a routed,
// kernel-decided, user-visible command. Per the P4 contract
// (docs/SCARLIX_P4_CONTRACT_INTEGRATION_GATE.md) ScarliBar owns intent
// capture and user-visible command status — it does NOT own privileged
// operations or execution; every capability question goes through the
// deterministic Agent Kernel ("LLM navrhuje, politika rozhoduje" — here,
// in BF-1, there is no LLM at all: routing and evaluation are rule-based).
//
// BF-1 scope (this file set): the typed command model — validated intent
// text, crypto-random command IDs, a bounded command state machine — plus
// the persisted command store (JSON file, grants.json discipline). The
// REST surface (/api/bar/commands) and the ScarliBar dashboard panel
// arrive in the same release; agent workspaces, coding/research agent
// runtimes and approvals follow in BF-2+.
//
// Honest non-goals for BF-1:
//   - an ALLOWED command is a kernel DECISION, not an execution — the
//     execution plumbing for allowed intents arrives with the agent
//     runtime (BF-2+); compute intake (AK-5) already exists for agents
//     acting through sessions directly.
//   - no LLM integration (Phase C, Universal AI Runtime) — the fabric is
//     deterministic first, like the kernel beneath it.
//   - no multi-principal submitter identity: deployments are
//     single-principal (one bearer token); the commands file is 0600
//     server-side. Submitter identity lands with the approval UX line.
package agentfabric

import (
	"fmt"
	"strings"
	"time"
	"unicode/utf8"

	"github.com/MoZoHuJa/OS/scarlihq/internal/agentkernel"
)

// ---------------------------------------------------------------------------
// Command identity
// ---------------------------------------------------------------------------

// CommandID is a typed, validated command identifier: "cmd-" + 16
// crypto-random bytes hex (36 chars). IDs are generated by the store
// (fail-closed RNG — a predictable ID is never issued, the aks- precedent
// from the kernel session store).
type CommandID string

const (
	commandIDPrefix = "cmd-"
	commandIDHexLen = 32 // 16 bytes hex
	commandIDLen    = len(commandIDPrefix) + commandIDHexLen
)

// Validate checks the canonical command ID shape.
func (c CommandID) Validate() error {
	s := string(c)
	if s == "" {
		return fmt.Errorf("agentfabric: command id is empty")
	}
	if len(s) != commandIDLen {
		return fmt.Errorf("agentfabric: command id %q must be %d chars (cmd- + 32 hex)", s, commandIDLen)
	}
	if !strings.HasPrefix(s, commandIDPrefix) {
		return fmt.Errorf("agentfabric: command id %q must start with %q", s, commandIDPrefix)
	}
	for _, r := range s[len(commandIDPrefix):] {
		if (r >= '0' && r <= '9') || (r >= 'a' && r <= 'f') {
			continue
		}
		return fmt.Errorf("agentfabric: command id %q hex part must be [0-9a-f]", s)
	}
	return nil
}

// ---------------------------------------------------------------------------
// Intent validation (the bar input)
// ---------------------------------------------------------------------------

// MaxIntentRunes bounds one captured intent. The bar is a single-line
// input: intents are deliberately small — a novel is not an intent.
const MaxIntentRunes = 512

// ValidateIntent checks the captured intent text: trimmed non-empty, at
// most MaxIntentRunes runes, and NO control characters (the intent lands
// in a JSON file, a REST response and the dashboard DOM — control
// characters have no honest role there. Multi-line intents are a
// deliberate future extension, not an accident).
func ValidateIntent(intent string) error {
	trimmed := strings.TrimSpace(intent)
	if trimmed == "" {
		return fmt.Errorf("agentfabric: intent is empty after trimming")
	}
	if utf8.RuneCountInString(trimmed) > MaxIntentRunes {
		return fmt.Errorf("agentfabric: intent longer than %d runes", MaxIntentRunes)
	}
	for _, r := range trimmed {
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf("agentfabric: intent contains control character U+%04X (single-line intents only)", r)
		}
	}
	return nil
}

// ---------------------------------------------------------------------------
// Command lifecycle (bounded, observable — kernel state-machine discipline)
// ---------------------------------------------------------------------------

// CommandState is the command lifecycle. DECIDED and CANCELLED are terminal.
//
// SUBMITTED: the intent is captured (persisted) but not yet bound to an
// agent session ("awaiting routing" — the intent is never lost).
// ROUTED: the command is bound to one ACTIVE session of its agent; a
// re-route re-binds it (ROUTED → ROUTED) to the newest ACTIVE session.
// DECIDED: the kernel has evaluated the capability question; the decision
// (allow AND deny — a denial is a successful, auditable evaluation, the
// kernel's denial-is-200 contract) is recorded on the command.
// CANCELLED: the user withdrew the command before a decision.
type CommandState string

const (
	CommandSubmitted CommandState = "SUBMITTED"
	CommandRouted    CommandState = "ROUTED"
	CommandDecided   CommandState = "DECIDED"
	CommandCancelled CommandState = "CANCELLED"
)

// commandTransitions is the legal-transition table. DECIDED/CANCELLED are
// terminal. ROUTED → ROUTED is the re-bind (a new routing attempt for a
// command whose previous attempt did not reach a decision).
var commandTransitions = map[CommandState]map[CommandState]bool{
	CommandSubmitted: {CommandRouted: true, CommandCancelled: true},
	CommandRouted:    {CommandRouted: true, CommandDecided: true, CommandCancelled: true},
	CommandDecided:   {},
	CommandCancelled: {},
}

// LegalCommandTransitions returns the allowed next states (empty for
// terminal states).
func LegalCommandTransitions(from CommandState) []CommandState {
	allowed := commandTransitions[from]
	out := make([]CommandState, 0, len(allowed))
	for s := range allowed {
		out = append(out, s)
	}
	return out
}

// validCommandState reports whether s is a known state.
func validCommandState(s CommandState) bool {
	switch s {
	case CommandSubmitted, CommandRouted, CommandDecided, CommandCancelled:
		return true
	}
	return false
}

// ---------------------------------------------------------------------------
// Command record
// ---------------------------------------------------------------------------

// CommandRecord is one captured intent and its lifecycle. The record is
// the user-visible command status (P4: ScarliBar's second ownership).
// SessionID/Decision/timestamps are present exactly when the state says
// so — load-time validation enforces these invariants fail-closed.
// WorkspaceID (BF-2) is the isolation scope: empty = unscoped (the BF-1
// behavior — any ACTIVE session of the agent); non-empty = the command
// routes ONLY through member sessions of that workspace.
type CommandRecord struct {
	ID          string                 `json:"id"`
	Intent      string                 `json:"intent"`
	AgentID     agentkernel.AgentID    `json:"agent_id"`
	Capability  agentkernel.Capability `json:"capability"`
	WorkspaceID string                 `json:"workspace_id,omitempty"`
	SessionID   string                 `json:"session_id,omitempty"`
	State       CommandState           `json:"state"`
	Decision    *agentkernel.Decision  `json:"decision,omitempty"`
	SubmittedAt time.Time              `json:"submitted_at"`
	RoutedAt    *time.Time             `json:"routed_at,omitempty"`
	DecidedAt   *time.Time             `json:"decided_at,omitempty"`
	CancelledAt *time.Time             `json:"cancelled_at,omitempty"`
	UpdatedAt   time.Time              `json:"updated_at"`
}

// validate checks the record invariants (used at load AND after every
// mutation — the store never persists a record it would refuse to load).
//
// Invariants:
//   - ID shape, intent bounds, agent ID shape, closed-enumeration capability
//   - SUBMITTED: nothing bound, nothing decided, nothing cancelled
//   - ROUTED: session + routed_at present; no decision
//   - DECIDED: session + routed_at + decision + decided_at present
//   - CANCELLED: cancelled_at present; decision absent; session/routed_at
//     present iff the command was routed before cancellation
//   - monotone timestamps: submitted ≤ routed ≤ decided/cancelled ≤ updated
func (r CommandRecord) validate() error {
	if err := CommandID(r.ID).Validate(); err != nil {
		return err
	}
	if err := ValidateIntent(r.Intent); err != nil {
		return err
	}
	if err := r.AgentID.Validate(); err != nil {
		return err
	}
	if !r.Capability.IsValid() {
		return fmt.Errorf("agentfabric: command %s: unknown capability %q (closed enumeration)", r.ID, r.Capability)
	}
	// BF-2: the isolation scope, when present, must be a well-formed
	// workspace ID. Whether the workspace exists (and is ACTIVE) is the
	// API layer's check at submission/routing time — the store persists
	// the scope, it does not resolve it.
	if r.WorkspaceID != "" {
		if err := WorkspaceID(r.WorkspaceID).Validate(); err != nil {
			return fmt.Errorf("agentfabric: command %s: %v", r.ID, err)
		}
	}
	if !validCommandState(r.State) {
		return fmt.Errorf("agentfabric: command %s: unknown state %q", r.ID, r.State)
	}
	if r.SubmittedAt.IsZero() {
		return fmt.Errorf("agentfabric: command %s: zero submitted_at", r.ID)
	}
	if r.UpdatedAt.Before(r.SubmittedAt) {
		return fmt.Errorf("agentfabric: command %s: updated_at before submitted_at", r.ID)
	}
	switch r.State {
	case CommandSubmitted:
		if r.SessionID != "" || r.RoutedAt != nil || r.Decision != nil || r.DecidedAt != nil || r.CancelledAt != nil {
			return fmt.Errorf("agentfabric: command %s: SUBMITTED record carries routing/decision/cancellation fields", r.ID)
		}
	case CommandRouted:
		if r.SessionID == "" || r.RoutedAt == nil {
			return fmt.Errorf("agentfabric: command %s: ROUTED record misses session_id/routed_at", r.ID)
		}
		if r.Decision != nil || r.DecidedAt != nil || r.CancelledAt != nil {
			return fmt.Errorf("agentfabric: command %s: ROUTED record carries decision/cancellation fields", r.ID)
		}
	case CommandDecided:
		if r.SessionID == "" || r.RoutedAt == nil || r.Decision == nil || r.DecidedAt == nil {
			return fmt.Errorf("agentfabric: command %s: DECIDED record misses session/routing/decision fields", r.ID)
		}
		if strings.TrimSpace(r.Decision.Reason) == "" {
			return fmt.Errorf("agentfabric: command %s: DECIDED record carries an empty decision reason (every kernel decision names its rule)", r.ID)
		}
		if r.CancelledAt != nil {
			return fmt.Errorf("agentfabric: command %s: DECIDED record carries cancelled_at", r.ID)
		}
	case CommandCancelled:
		if r.CancelledAt == nil {
			return fmt.Errorf("agentfabric: command %s: CANCELLED record misses cancelled_at", r.ID)
		}
		if r.Decision != nil || r.DecidedAt != nil {
			return fmt.Errorf("agentfabric: command %s: CANCELLED record carries decision fields", r.ID)
		}
		if (r.SessionID == "") != (r.RoutedAt == nil) {
			return fmt.Errorf("agentfabric: command %s: CANCELLED record has mismatched session/routing fields", r.ID)
		}
	}
	if r.RoutedAt != nil {
		if r.RoutedAt.Before(r.SubmittedAt) {
			return fmt.Errorf("agentfabric: command %s: routed_at before submitted_at", r.ID)
		}
	}
	if r.DecidedAt != nil && r.RoutedAt != nil && r.DecidedAt.Before(*r.RoutedAt) {
		return fmt.Errorf("agentfabric: command %s: decided_at before routed_at", r.ID)
	}
	if r.CancelledAt != nil && r.CancelledAt.Before(r.SubmittedAt) {
		return fmt.Errorf("agentfabric: command %s: cancelled_at before submitted_at", r.ID)
	}
	return nil
}

// transition applies a legal state transition with the kernel's
// discipline: unknown states, terminal-state violations, illegal moves and
// backwards clocks are rejected.
func (r *CommandRecord) transition(to CommandState, now time.Time) error {
	if r == nil {
		return fmt.Errorf("agentfabric: nil command record")
	}
	if !validCommandState(r.State) {
		return fmt.Errorf("agentfabric: unknown command state %q", r.State)
	}
	if r.State == CommandDecided || r.State == CommandCancelled {
		return fmt.Errorf("agentfabric: %s is terminal — no transitions allowed", r.State)
	}
	if !commandTransitions[r.State][to] {
		return fmt.Errorf("agentfabric: illegal transition %s → %s", r.State, to)
	}
	if now.Before(r.UpdatedAt) {
		return fmt.Errorf("agentfabric: transition timestamp before UpdatedAt")
	}
	r.State = to
	r.UpdatedAt = now.UTC()
	return nil
}
