// ---------------------------------------------------------------------------
// Proposal identity
// ---------------------------------------------------------------------------

// ProposalID is a typed, validated proposal identifier: "prp-" + 16
// crypto-random bytes hex (36 chars). Generated by the store-side
// capture path (fail-closed RNG — the cmd-/ws-/afx-/apv- precedent; a
// predictable ID is never issued).
type ProposalID string

const (
	proposalIDPrefix = "prp-"
	proposalIDHexLen = 32 // 16 bytes hex
	proposalIDLen    = len(proposalIDPrefix) + proposalIDHexLen
)

// Validate checks the canonical proposal ID shape.
func (p ProposalID) Validate() error {
	s := string(p)
	if s == "" {
		return fmt.Errorf("agentfabric: proposal id is empty")
	}
	if len(s) != proposalIDLen {
		return fmt.Errorf("agentfabric: proposal id %q must be %d chars (prp- + 32 hex)", s, proposalIDLen)
	}
	if !strings.HasPrefix(s, proposalIDPrefix) {
		return fmt.Errorf("agentfabric: proposal id %q must start with %q", s, proposalIDPrefix)
	}
	for _, r := range s[len(proposalIDPrefix):] {
		if (r >= '0' && r <= '9') || (r >= 'a' && r <= 'f') {
			continue
		}
		return fmt.Errorf("agentfabric: proposal id %q hex part must be [0-9a-f]", s)
	}
	return nil
}

// NewProposalID generates a fresh proposal ID (the API layer's capture
// composition — fail-closed RNG).
func NewProposalID() (string, error) {
	return rngProposalID()
}

// rngProposalID generates "prp-" + 16 crypto-random bytes hex.
// Package-level variable so tests can inject RNG failure (the
// cmd-/ws-/afx-/apv- precedent).
var rngProposalID = func() (string, error) {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return "", ErrProposalRNG
	}
	return proposalIDPrefix + hex.EncodeToString(b), nil
}

// ---------------------------------------------------------------------------
// Proposal lifecycle (closed enumeration)
// ---------------------------------------------------------------------------

// ProposalState is the operator-decision lifecycle of a model-authored
// proposal. PENDING is the only in-flight state; ACCEPTED/DISMISSED are
// terminal.
type ProposalState string

const (
	// ProposalPending: captured from an LLM response, awaiting the
	// operator's decision.
	ProposalPending ProposalState = "PENDING"
	// ProposalAccepted: the operator said yes; the proposal became a
	// captured command through the BF-1 submission path (CommandID
	// references it — always). Everything after intent capture is the
	// EXISTING fabric flow: routing, the kernel decision, the BF-4
	// approval gate for coding acts — untouched by CF-3.
	ProposalAccepted ProposalState = "ACCEPTED"
	// ProposalDismissed: the operator said no; terminal, no command
	// ever. The model can propose again in a NEW chat response; the
	// history records both.
	ProposalDismissed ProposalState = "DISMISSED"
)

// validProposalState reports whether s is a known state.
func validProposalState(s ProposalState) bool {
	switch s {
	case ProposalPending, ProposalAccepted, ProposalDismissed:
		return true
	}
	return false
}

// ---------------------------------------------------------------------------
// The proposal block (the LLM's one structured freedom)
// ---------------------------------------------------------------------------

// ProposalFenceTag is the EXACT fence line that opens a proposal block.
// Column 0, trailing whitespace tolerated, indentation NOT: a loose fence
// would match code samples ABOUT proposals. This is the whole of the
// model's structured freedom — everything else is deterministic
// discipline.
const ProposalFenceTag = "```scarlix-proposal"

// ProposalDraft is one parsed proposal block: the intent, the agent and
// the capability the model proposed — nothing else (no params, no
// workspace, no defaults; the closed three-field shape IS the contract).
type ProposalDraft struct {
	Intent     string
	AgentID    agentkernel.AgentID
	Capability agentkernel.Capability
}

// proposalJSON is the closed decode shape of the block content. Unknown
// fields are rejected; every field is required non-empty after trimming
// (the parser never fills in a blank).
type proposalJSON struct {
	Intent     string `json:"intent"`
	AgentID    string `json:"agent_id"`
	Capability string `json:"capability"`
}

var (
	// ErrNoProposal: the response carries no proposal block — the
	// model answered and proposed nothing. NOT a failure: the honest
	// null (the caller surfaces "proposal": null).
	ErrNoProposal = errors.New("agentfabric: no proposal block in the response (the model proposed nothing)")

	// ErrMalformedProposal: the response carries a proposal block that
	// does not parse — bad JSON, unknown or missing fields, invalid
	// values, an unterminated fence, or TWO blocks (ambiguity is
	// never resolved by guessing). NOTHING is captured on this error
	// — fail-closed, not fail-blind: the named reason rides along.
	ErrMalformedProposal = errors.New("agentfabric: malformed proposal block")
)

// ParseProposal scans an assistant response for exactly ONE fenced
// proposal block and returns the validated draft. Pure text processing:
// no network, no clock, no randomness — same input, same output, byte
// for byte. Zero blocks → ErrNoProposal; anything wrong → an error that
// wraps ErrMalformedProposal with the named reason; only a fully
// valid block returns a draft (the parser never returns a partial
// guess).
func ParseProposal(content string) (ProposalDraft, error) {
	lines := strings.Split(content, "\n")
	var blocks []string
	inBlock := false
	var current []string
	for _, line := range lines {
		if !inBlock {
			if strings.TrimRight(line, " \t\r") == ProposalFenceTag {
				inBlock = true
				current = nil
			}
			continue
		}
		if strings.HasPrefix(strings.TrimRight(line, " \t\r"), "```") {
			blocks = append(blocks, strings.Join(current, "\n"))
			inBlock = false
			continue
		}
		current = append(current, line)
	}
	if inBlock {
		return ProposalDraft{}, fmt.Errorf("%w: the ```scarlix-proposal fence is never closed", ErrMalformedProposal)
	}
	switch len(blocks) {
	case 0:
		return ProposalDraft{}, ErrNoProposal
	case 1:
		// the one allowed block
	default:
		return ProposalDraft{}, fmt.Errorf("%w: %d proposal blocks (exactly one allowed — an example plus a real proposal is ambiguity, never resolved by guessing)", ErrMalformedProposal, len(blocks))
	}

	block := strings.TrimSpace(blocks[0])
	if block == "" {
		return ProposalDraft{}, fmt.Errorf("%w: the proposal block is empty", ErrMalformedProposal)
	}
	decoder := json.NewDecoder(strings.NewReader(block))
	decoder.DisallowUnknownFields()
	var raw proposalJSON
	if err := decoder.Decode(&raw); err != nil {
		return ProposalDraft{}, fmt.Errorf("%w: %v", ErrMalformedProposal, err)
	}
	var extra any
	if err := decoder.Decode(&extra); err != io.EOF {
		return ProposalDraft{}, fmt.Errorf("%w: the block must carry exactly one JSON object", ErrMalformedProposal)
	}

	intent := strings.TrimSpace(raw.Intent)
	if err := ValidateIntent(intent); err != nil {
		return ProposalDraft{}, fmt.Errorf("%w: %v", ErrMalformedProposal, err)
	}
	agent := agentkernel.AgentID(strings.TrimSpace(raw.AgentID))
	if err := agent.Validate(); err != nil {
		return ProposalDraft{}, fmt.Errorf("%w: %v", ErrMalformedProposal, err)
	}
	capability := agentkernel.Capability(strings.TrimSpace(raw.Capability))
	if !capability.IsValid() {
		return ProposalDraft{}, fmt.Errorf("%w: unknown capability %q (closed enumeration — the parser never guesses)", ErrMalformedProposal, capability)
	}
	return ProposalDraft{Intent: intent, AgentID: agent, Capability: capability}, nil
}

// ---------------------------------------------------------------------------
// Proposal record
// ---------------------------------------------------------------------------

// ProposalRecord is one model-authored proposal and its operator
// decision. The record is the reviewable history of WHAT the model
// proposed (with runtime attribution — which provider AND which model,
// typed CF-1 values) and what the operator did about it. Fields are
// present exactly when the state says so — load-time validation
// enforces these invariants fail-closed (the store discipline).
type ProposalRecord struct {
	ID         string                 `json:"id"`
	Intent     string                 `json:"intent"`
	AgentID    agentkernel.AgentID    `json:"agent_id"`
	Capability agentkernel.Capability `json:"capability"`
	// Proposer attribution (typed CF-1 values, validated): WHICH tier
	// answered and WHICH model proposed — attribution survives
	// failover, and the proposal records it honestly. The fabric
	// records WHO proposed using the runtime's own typed identity;
	// this is the bridge entity's defining field.
	ProposerProvider airuntime.Provider `json:"proposer_provider"`
	ProposerModel    airuntime.ModelID  `json:"proposer_model"`
	State            ProposalState      `json:"state"`
	// Operator: the bounded principal label of WHO accepted or
	// dismissed — attribution for the reviewable history, never a
	// credential (single-principal deployments; the bearer token is
	// the only authentication boundary).
	Operator string `json:"operator,omitempty"`
	// Reason: the optional bounded why of a dismissal (the BF-4
	// reject precedent). An ACCEPTED record never carries one.
	Reason string `json:"reason,omitempty"`
	// CommandID: present exactly when ACCEPTED — the captured command
	// this proposal became (one command reference per proposal, ever;
	// a DISMISSED record never carries one).
	CommandID  string     `json:"command_id,omitempty"`
	CapturedAt time.Time  `json:"captured_at"`
	DecidedAt  *time.Time `json:"decided_at,omitempty"`
	UpdatedAt  time.Time  `json:"updated_at"`
}

// validate checks the record invariants (used at load AND before every
// persist — the store never holds a record it would refuse to load).
//
// Invariants:
//   - ID shape; the bar's own intent/agent/capability validators (no
//     second, weaker standard for model-authored intents)
//   - typed proposer attribution (closed provider enumeration, model id
//     shape)
//   - PENDING: nothing decided, no operator, no reason, no command
//   - ACCEPTED: operator + valid command reference + decided_at; no
//     reason
//   - DISMISSED: operator + decided_at; NEVER a command reference
//   - monotone timestamps: captured ≤ decided ≤ updated
func (r ProposalRecord) validate() error {
	if err := ProposalID(r.ID).Validate(); err != nil {
		return err
	}
	if err := ValidateIntent(r.Intent); err != nil {
		return fmt.Errorf("agentfabric: proposal %s: %v", r.ID, err)
	}
	if err := r.AgentID.Validate(); err != nil {
		return fmt.Errorf("agentfabric: proposal %s: %v", r.ID, err)
	}
	if !r.Capability.IsValid() {
		return fmt.Errorf("agentfabric: proposal %s: unknown capability %q (closed enumeration)", r.ID, r.Capability)
	}
	if err := r.ProposerProvider.Validate(); err != nil {
		return fmt.Errorf("agentfabric: proposal %s: proposer provider: %v", r.ID, err)
	}
	if err := r.ProposerModel.Validate(); err != nil {
		return fmt.Errorf("agentfabric: proposal %s: proposer model: %v", r.ID, err)
	}
	if !validProposalState(r.State) {
		return fmt.Errorf("agentfabric: proposal %s: unknown state %q", r.ID, r.State)
	}
	if r.Operator != "" {
		if err := ValidatePrincipalLabel(r.Operator); err != nil {
			return fmt.Errorf("agentfabric: proposal %s: operator: %v", r.ID, err)
		}
	}
	if r.Reason != "" {
		if err := ValidateExecutionReason(r.Reason); err != nil {
			return fmt.Errorf("agentfabric: proposal %s: reason: %v", r.ID, err)
		}
	}
	if r.CapturedAt.IsZero() {
		return fmt.Errorf("agentfabric: proposal %s: zero captured_at", r.ID)
	}
	if r.UpdatedAt.Before(r.CapturedAt) {
		return fmt.Errorf("agentfabric: proposal %s: updated_at before captured_at", r.ID)
	}
	switch r.State {
	case ProposalPending:
		if r.Operator != "" || r.Reason != "" || r.CommandID != "" || r.DecidedAt != nil {
			return fmt.Errorf("agentfabric: proposal %s: PENDING record carries decision fields", r.ID)
		}
	case ProposalAccepted:
		if r.Operator == "" {
			return fmt.Errorf("agentfabric: proposal %s: ACCEPTED record misses the operator label", r.ID)
		}
		if err := CommandID(r.CommandID).Validate(); err != nil {
			return fmt.Errorf("agentfabric: proposal %s: ACCEPTED record: %v", r.ID, err)
		}
		if r.DecidedAt == nil {
			return fmt.Errorf("agentfabric: proposal %s: ACCEPTED record misses decided_at", r.ID)
		}
		if r.Reason != "" {
			return fmt.Errorf("agentfabric: proposal %s: ACCEPTED record carries a reason (reason is the dismissal's why)", r.ID)
		}
	case ProposalDismissed:
		if r.Operator == "" {
			return fmt.Errorf("agentfabric: proposal %s: DISMISSED record misses the operator label", r.ID)
		}
		if r.DecidedAt == nil {
			return fmt.Errorf("agentfabric: proposal %s: DISMISSED record misses decided_at", r.ID)
		}
		if r.CommandID != "" {
			return fmt.Errorf("agentfabric: proposal %s: DISMISSED record carries a command reference — a dismissal never became a command", r.ID)
		}
	}
	if r.DecidedAt != nil && r.DecidedAt.Before(r.CapturedAt) {
		return fmt.Errorf("agentfabric: proposal %s: decided_at before captured_at", r.ID)
	}
	return nil
}

// copyProposalRecord returns a deep copy (the DecidedAt pointer is
// re-allocated — callers never alias the store's records; the
// copyApprovalRecord discipline).
func copyProposalRecord(r ProposalRecord) ProposalRecord {
	out := r
	if r.DecidedAt != nil {
		t := *r.DecidedAt
		out.DecidedAt = &t
	}
	return out
}
