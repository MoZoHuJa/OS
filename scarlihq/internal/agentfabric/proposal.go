// CF-3 (v19.6.2): the LLM propose surface — the bridge the whole Phase C
// exists for. The contract, in one breath:
//
//	an LLM response becomes a fabric PROPOSAL — never an auto-submitted command.
//
// CF-2's chat is transport only: the response text goes back to the
// caller and stops. CF-3 adds the honest next step: a response may
// carry ONE structured proposal block (a fenced ```scarlix-proposal
// JSON object naming an intent, an agent and a capability — nothing
// else). The parser below extracts it PURELY and fail-closed; the
// capture persists it as a PENDING ProposalRecord; the operator — and
// ONLY the operator — ACCEPTS it (the proposal becomes a captured
// command through the exact BF-1 submission path: routing, the kernel
// decision, the BF-4 approval gate all still apply downstream,
// untouched) or DISMISSES it (terminal, no command ever). The Phase C
// charter, on one line: LLM navrhuje, politika rozhoduje — the LLM
// proposes; policy decides. The model never holds a pen that writes
// into the fabric.
//
// The parser's discipline (every rule tested):
//   - the fence line is exactly ```scarlix-proposal at column 0
//     (trailing whitespace tolerated, indentation NOT — a loose fence
//     would match code samples ABOUT proposals);
//   - the block content is ONE JSON object, DisallowUnknownFields, the
//     CLOSED three-field shape intent/agent_id/capability — every field
//     required, NO defaults: the parser never fills in a blank agent or
//     guesses a capability;
//   - values are validated with the BAR'S OWN validators (ValidateIntent,
//     AgentID.Validate, Capability.IsValid) — a proposal is held to the
//     same standard as a bar submission; there is deliberately no
//     second, weaker standard for model-authored intents;
//   - ZERO blocks is not an error (the model answered and proposed
//     nothing — the honest null); TWO OR MORE blocks is malformed — an
//     example plus a real proposal is AMBIGUITY — ambiguity is never resolved by guessing
//     which one was meant.
//
// Proposal states are a closed enumeration, the BF-4 genre applied to
// model intents: PENDING is the only in-flight state; ACCEPTED requires
// the operator's yes and references the captured command (ALWAYS);
// DISMISSED is the operator's no — terminal, no command ever. There is
// deliberately NO withdrawn state and NO expiry: a proposal nobody
// answers stays PENDING in the reviewable history — an expiry would
// silently turn a non-decision into a decision (the BF-4 line, word for
// word).
package agentfabric

