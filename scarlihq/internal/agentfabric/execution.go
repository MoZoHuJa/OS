// BF-3 (v19.5.2): the execution record — what it means for a DECIDED,
// kernel-ALLOWED command to actually RUN. The contract, in one breath:
//
//	an execution record is TERMINAL BY CONSTRUCTION. There is no in-flight
//	state, no PENDING, no RUNNING — the execute surface is synchronous
//	(bounded act), and the record is persisted exactly once, at the end,
//	in one of three states:
//
//	- COMPLETED: the fresh kernel evaluation allowed the act AND the act
//	  reported success. Outcome carries the bounded act summary (the
//	  status snapshot line, the mode-request acceptance, …).
//	- FAILED: the fresh evaluation allowed the act but the act itself
//	  returned an error (bridge rejection, disabled dependency, …).
//	  Reason carries the act error. A failed act is an honest terminal
//	  outcome — it is surfaced, not retried by the fabric (retry is a NEW
//	  intent at the bar; the file is the history).
//	- SKIPPED: the STALE-ALLOW GUARD fired — the command carries an old
//	  kernel decision, but the FRESH evaluation at execute time DENIED
//	  (session suspended/closed, capability disabled since, grant revoked
//	  since). The act never runs. The fresh denial is AUDITED (an
//	  evaluate line in the AK-4 sink — fail-closed) and Reason carries
//	  the fresh denial rule. Allow is false.
//
// Invariants enforced at load AND before persist (the store discipline):
//   - state↔fields coherence: COMPLETED requires a non-empty outcome and
//     allow=true; FAILED requires a non-empty reason and allow=true;
//     SKIPPED requires a non-empty reason and allow=false (the guard's
//     denial) — a SKIPPED record with allow=true or a COMPLETED record
//     with allow=false is a corrupt file, not a degraded success.
//   - runtime↔capability coherence: the record's runtime must equal
//     RuntimeForCapability(capability) — the closed mapping is part of
//     the record's integrity (a hand-edited file that relabels a coding
//     execution as research aborts the load).
//   - one execution per command: enforced by the store (Record refuses a
//     second execution for the same command id; Load aborts on duplicate
//     command references in the file).
package agentfabric

import (
	"fmt"
	"strings"
	"time"

	"github.com/MoZoHuJa/OS/scarlihq/internal/agentkernel"
)

// ---------------------------------------------------------------------------
// Execution identity
// ---------------------------------------------------------------------------

// ExecutionID is a typed, validated execution identifier: "afx-" + 16
// crypto-random bytes hex (36 chars). Generated by the store (fail-closed
// RNG — the cmd-/ws-/aks- precedent).
type ExecutionID string

const (
	executionIDPrefix = "afx-"
	executionIDHexLen = 32 // 16 bytes hex
	executionIDLen    = len(executionIDPrefix) + executionIDHexLen
)

// Validate checks the canonical execution ID shape.
func (e ExecutionID) Validate() error {
	s := string(e)
	if s == "" {
		return fmt.Errorf("agentfabric: execution id is empty")
	}
	if len(s) != executionIDLen {
		return fmt.Errorf("agentfabric: execution id %q must be %d chars (afx- + 32 hex)", s, executionIDLen)
	}
	if !strings.HasPrefix(s, executionIDPrefix) {
		return fmt.Errorf("agentfabric: execution id %q must start with %q", s, executionIDPrefix)
	}
	for _, r := range s[len(executionIDPrefix):] {
		if (r >= '0' && r <= '9') || (r >= 'a' && r <= 'f') {
			continue
		}
		return fmt.Errorf("agentfabric: execution id %q hex part must be [0-9a-f]", s)
	}
	return nil
}

// ---------------------------------------------------------------------------
// Execution lifecycle (closed enumeration — ALL states terminal)
// ---------------------------------------------------------------------------

// ExecutionState is the execution outcome. Every state is TERMINAL: an
// execution record is persisted once, at the end of the synchronous
// execute call. There is no transition table because there are no
// transitions — the enumeration documents outcomes, not a lifecycle.
type ExecutionState string

const (
	// ExecutionCompleted: fresh evaluation allowed, act succeeded.
	ExecutionCompleted ExecutionState = "COMPLETED"
	// ExecutionFailed: fresh evaluation allowed, act returned an error.
	ExecutionFailed ExecutionState = "FAILED"
	// ExecutionSkipped: fresh evaluation DENIED (stale-allow guard) — the
	// act never ran; the fresh denial is audited and named in Reason.
	ExecutionSkipped ExecutionState = "SKIPPED"
)

// validExecutionState reports whether s is a known state.
func validExecutionState(s ExecutionState) bool {
	switch s {
	case ExecutionCompleted, ExecutionFailed, ExecutionSkipped:
		return true
	}
	return false
}

// ExecutionStates returns the closed outcome enumeration (deterministic
// order) — the read surface's counts key set.
func ExecutionStates() []ExecutionState {
	return []ExecutionState{ExecutionCompleted, ExecutionFailed, ExecutionSkipped}
}

// ---------------------------------------------------------------------------
// Execution record
// ---------------------------------------------------------------------------

// ExecutionRecord is one executed command's terminal outcome. The record
// carries its OWN evaluation snapshot (Allow + Reason are the FRESH
// evaluation at execute time, not the command's original decision — the
// stale-allow guard makes the fresh result the one that counts). Params
// are echoed on the REST view by the API layer; the record keeps what the
// file needs to be reviewed: who, what, where, which runtime, what
// happened, when.
type ExecutionRecord struct {
	ID          string                 `json:"id"`
	CommandID   string                 `json:"command_id"`
	AgentID     agentkernel.AgentID    `json:"agent_id"`
	Capability  agentkernel.Capability `json:"capability"`
	WorkspaceID string                 `json:"workspace_id,omitempty"`
	SessionID   string                 `json:"session_id"`
	Runtime     RuntimeID              `json:"runtime"`
	State       ExecutionState         `json:"state"`
	Allow       bool                   `json:"allow"`
	Outcome     string                 `json:"outcome,omitempty"`
	Reason      string                 `json:"reason,omitempty"`
	Intent      string                 `json:"intent"`
	ExecutedAt  time.Time              `json:"executed_at"`
}

// validate checks the record invariants (used at load AND before every
// persist — the store never holds a record it would refuse to load).
//
// Invariants:
//   - ID shape (afx-), command ID shape (cmd-), agent ID shape, closed
//     capability enumeration, runtime == RuntimeForCapability(capability)
//   - workspace scope (ws- shape when present), session (aks- shape)
//   - intent bounds (the command's captured intent, echoed verbatim)
//   - closed state enumeration; state↔allow↔fields coherence:
//     COMPLETED → allow=true, non-empty outcome, empty reason allowed
//     FAILED    → allow=true, empty outcome, non-empty reason
//     SKIPPED   → allow=false, empty outcome, non-empty reason
//   - non-zero executed_at
func (r ExecutionRecord) validate() error {
	if err := ExecutionID(r.ID).Validate(); err != nil {
		return err
	}
	if err := CommandID(r.CommandID).Validate(); err != nil {
		return fmt.Errorf("agentfabric: execution %s: %v", r.ID, err)
	}
	if err := r.AgentID.Validate(); err != nil {
		return fmt.Errorf("agentfabric: execution %s: %v", r.ID, err)
	}
	if !r.Capability.IsValid() {
		return fmt.Errorf("agentfabric: execution %s: unknown capability %q (closed enumeration)", r.ID, r.Capability)
	}
	rt, ok := RuntimeForCapability(r.Capability)
	if !ok || rt != r.Runtime {
		return fmt.Errorf("agentfabric: execution %s: capability %q must execute under runtime %q, record says %q (closed mapping coherence)", r.ID, r.Capability, rt, r.Runtime)
	}
	if r.WorkspaceID != "" {
		if err := WorkspaceID(r.WorkspaceID).Validate(); err != nil {
			return fmt.Errorf("agentfabric: execution %s: %v", r.ID, err)
		}
	}
	if !validSessionIDShape(r.SessionID) {
		return fmt.Errorf("agentfabric: execution %s: session id %q does not have the aks- shape", r.ID, r.SessionID)
	}
	if !validExecutionState(r.State) {
		return fmt.Errorf("agentfabric: execution %s: unknown state %q", r.ID, r.State)
	}
	if err := ValidateIntent(r.Intent); err != nil {
		return fmt.Errorf("agentfabric: execution %s: %v", r.ID, err)
	}
	if r.ExecutedAt.IsZero() {
		return fmt.Errorf("agentfabric: execution %s: zero executed_at", r.ID)
	}
	switch r.State {
	case ExecutionCompleted:
		if !r.Allow {
			return fmt.Errorf("agentfabric: execution %s: COMPLETED with allow=false — a completed act required a fresh allow (corrupt record)", r.ID)
		}
		if err := ValidateOutcome(r.Outcome); err != nil {
			return fmt.Errorf("agentfabric: execution %s: %v", r.ID, err)
		}
		if r.Reason != "" {
			if err := ValidateExecutionReason(r.Reason); err != nil {
				return fmt.Errorf("agentfabric: execution %s: %v", r.ID, err)
			}
		}
	case ExecutionFailed:
		if !r.Allow {
			return fmt.Errorf("agentfabric: execution %s: FAILED with allow=false — a failed act ran, so the fresh evaluation allowed it; a fresh denial is SKIPPED (corrupt record)", r.ID)
		}
		if r.Outcome != "" {
			return fmt.Errorf("agentfabric: execution %s: FAILED record carries an outcome — the act failed, there is no act result (corrupt record)", r.ID)
		}
		if err := ValidateExecutionReason(r.Reason); err != nil {
			return fmt.Errorf("agentfabric: execution %s: %v", r.ID, err)
		}
	case ExecutionSkipped:
		if r.Allow {
			return fmt.Errorf("agentfabric: execution %s: SKIPPED with allow=true — the stale-allow guard skips only on a fresh DENIAL (corrupt record)", r.ID)
		}
		if r.Outcome != "" {
			return fmt.Errorf("agentfabric: execution %s: SKIPPED record carries an outcome — the act never ran (corrupt record)", r.ID)
		}
		if err := ValidateExecutionReason(r.Reason); err != nil {
			return fmt.Errorf("agentfabric: execution %s: %v", r.ID, err)
		}
	}
	return nil
}

// copyExecutionRecord returns a copy of the record (no pointer fields —
// the copyCommandRecord discipline, trivially satisfied here; the
// function exists so callers cannot alias future pointer fields by
// accident).
func copyExecutionRecord(r ExecutionRecord) ExecutionRecord {
	return r
}
