// validatePolicy checks the policy's closed shapes: valid backend IDs,
// no duplicate priorities, non-empty image references, positive
// freshness/TTL bounds.
func validatePolicy(policy PlannerPolicy) error {
	seen := map[airuntime.BackendID]bool{}
	for _, b := range policy.PriorityBackends {
		if err := b.Validate(); err != nil {
			return err
		}
		if seen[b] {
			return fmt.Errorf("priority list repeats backend %q", b)
		}
		seen[b] = true
	}
	for b, ref := range policy.Images {
		if err := b.Validate(); err != nil {
			return err
		}
		if strings.TrimSpace(ref) == "" {
			return fmt.Errorf("image reference for backend %q is empty (remove the entry or declare a real reference)", b)
		}
	}
	if policy.MaxSnapshotAge <= 0 {
		return fmt.Errorf("max_snapshot_age must be > 0 (a non-positive freshness bound refuses nothing)")
	}
	if policy.PlanTTL <= 0 {
		return fmt.Errorf("plan_ttl must be > 0 (a plan without expiry violates the revalidation invariant)")
	}
	// v19.8.0 (roadmap §8): the SSD profile rides the policy as a
	// VALIDATED, ENABLED fact — an invalid profile or a disabled one
	// carried in the policy is a named wiring error (the production
	// seam turns disabled into not-configured; documentation never
	// reaches the planning path).
	if policy.SSDProfile != nil {
		if reasons := infer_ssd.ValidateRuntimeProfile(policy.SSDProfile); len(reasons) > 0 {
			return fmt.Errorf("the InferSSD runtime profile is invalid: %s", strings.Join(reasons, "; "))
		}
		if !policy.SSDProfile.Enabled {
			return fmt.Errorf("the InferSSD runtime profile %q is DISABLED — a disabled profile in the policy is a wiring bug (the seam turns disabled into not-configured; documentation never plans)", policy.SSDProfile.ProfileID)
		}
	}
	return nil
}

// candidate is one backend's complete evaluation (only constructed
// when the backend survived every hard constraint — exclusions travel
// the named trail instead).
type candidate struct {
	backend airuntime.BackendID
	row     airuntime.BackendCapabilities

	// placement
	strategy string
	gpu      *inventory.GPU // nil for CPU execution classes
	vector   admission.ResourceVector
	image    PinnedImage
	util     int     // the observed utilization (queue-delay proxy)
	frag     float64 // demand/allocatable — higher = tighter fit = lower fragmentation

	// v19.8.0 (roadmap §8): the ssd-backed-moe evaluation's own facts
	// (zero values for the resident strategies — the strategy itself is
	// the discriminator).
	ssdProfile   *infer_ssd.RuntimeProfile // the enabled profile the strategy derived from
	ssdQual      infer_ssd.Qualification   // the §8.6 measured qualification verdict
	ssdGPUCompat string                    // the §8.2 GPU join detail (carried into the explanation)
	ssdCapped    int                       // the §8.8-capped max concurrency (0 = not capped)
}

// modelGates is steps 3 of the §7.4/§7.5 pipeline, extracted verbatim for
// the v19.9.0 fabric planner (the same gate sequence serves the single-node
// and multi-node paths — the gates are node-INDEPENDENT by construction:
// manifest, eligibility, revision, context, VERIFIED artifact, and the
// v19.8.1 manifest-identity binding all resolve against the control
// plane's ModelSource). Returns (manifest, verification, refusal, ok).
func (p *Planner) modelGates(req ExecutionRequest, base PlanResult, now time.Time) (*modelmeta.Manifest, *modelmeta.ArtifactVerification, PlanResult, bool) {
	manifest, ok := p.models.Manifest(req.ModelID)
	if !ok || manifest == nil {
		return nil, nil, p.refuseWith(base, ReasonPlanModelUnknown, fmt.Sprintf("no schema-valid manifest declares model %q", req.ModelID)), false
	}
	if invalid := modelmeta.ValidateManifest(manifest); len(invalid) > 0 {
		return nil, nil, p.refuseWith(base, ReasonPlanModelIneligible, fmt.Sprintf("manifest for %q fails validation: %s", req.ModelID, strings.Join(invalid, "; "))), false
	}
	if elig := modelmeta.PlacementEligible(manifest); !elig.Eligible {
		return nil, nil, p.refuseWith(base, ReasonPlanModelIneligible, fmt.Sprintf("manifest for %q is placement-ineligible: %s", req.ModelID, strings.Join(elig.Reasons, "; "))), false
	}
	// The planner's own derivation rule (honest extension of the
	// placement gate): the VECTOR derivation needs the weights
	// footprint — a dense model with unknown shared bytes is refused
	// BY NAME rather than planned from a parsed parameter label
	// ("14B" is a declared label, not bytes; never schedule from
	// unverified estimates).
	if manifest.Architecture.Kind == modelmeta.ArchitectureDense && manifest.Architecture.SharedBytes == 0 {
		return nil, nil, p.refuseWith(base, ReasonPlanModelIneligible, fmt.Sprintf("manifest for %q declares no architecture.shared_bytes — the planner's dense vector derivation requires the weights footprint (a parameter label is a label, not bytes; never schedule from unverified estimates)", req.ModelID)), false
	}
	if req.ModelRevision != "" && req.ModelRevision != manifest.Revision {
		return nil, nil, p.refuseWith(base, ReasonPlanModelRevisionMismatch, fmt.Sprintf("requested revision %q does not match the manifest revision %q", req.ModelRevision, manifest.Revision)), false
	}
	if req.ContextTokens > manifest.Runtime.ContextLimit {
		return nil, nil, p.refuseWith(base, ReasonPlanContextExceedsLimit, fmt.Sprintf("context_tokens %d exceeds the model's declared context limit %d — planning an unservable context would be a phantom capability", req.ContextTokens, manifest.Runtime.ContextLimit)), false
	}
	verif, ok := p.models.Verification(req.ModelID)
	if !ok || verif == nil || !verif.AllVerified {
		return nil, nil, p.refuseWith(base, ReasonPlanModelUnverified, fmt.Sprintf("model %q has no fully-verified artifact record (declared digests are declarations — the planner consumes VERIFIED records, KPK-19.7.0-P2-04)", req.ModelID)), false
	}
	if age := now.Sub(verif.VerifiedAt); age > p.policy.VerificationMaxAge {
		return nil, nil, p.refuseWith(base, ReasonPlanModelUnverified, fmt.Sprintf("model %q verification is %s old (bound %s) — a stale verification is absent verification", req.ModelID, age.Truncate(time.Second), p.policy.VerificationMaxAge)), false
	}
	// The manifest-identity binding (v19.8.1, KPK-19.8.0-P1-02): the
	// verification record must be bound to the CURRENT manifest's
	// canonical fingerprint — a manifest whose revision/checkpoint/
	// pack declaration changed after verification is UNVERIFIED until the
	// operator re-runs the verification pass. The planner checks it
	// independently of the admission gate (every stage verifies its own
	// conditions).
	if verif.ManifestFingerprint == "" {
		return nil, nil, p.refuseWith(base, ReasonPlanModelUnverified, fmt.Sprintf(
			"model %q's verification record carries NO manifest fingerprint (a pre-v19.8.1 record) — re-run scarlix-inventory --verify-manifests so the record binds to the exact manifest identity", req.ModelID)), false
	}
	if current := modelmeta.ManifestFingerprint(manifest); current != verif.ManifestFingerprint {
		return nil, nil, p.refuseWith(base, ReasonPlanModelVerificationIdentityMismatch, fmt.Sprintf(
			"model %q's verification record (fingerprint %s) is not bound to the current manifest (fingerprint %s) — the manifest's identity-bearing fields changed after verification; re-run scarlix-inventory --verify-manifests (KPK-19.8.0-P1-02)", req.ModelID, verif.ManifestFingerprint, current)), false
	}
	return manifest, verif, PlanResult{}, true
}

// joinBackends is steps 4–6 of the §7.4/§7.5 pipeline, extracted verbatim
// for the v19.9.0 fabric planner: the capability × presence × capacity ×
// image join over every DECLARED backend against ONE node's snapshot,
// with hard constraints and named exclusions. Node-independent in shape —
// the LOCAL and every REMOTE node view run the identical join against
// their own snapshot.
func (p *Planner) joinBackends(manifest *modelmeta.Manifest, snap *inventory.InventorySnapshotV2, req ExecutionRequest) (complete []candidate, trail []string, downstream []string) {
	declared := append([]string(nil), manifest.Runtime.SupportedBackends...)
	sort.Strings(declared) // deterministic evaluation order (the trail reads stably)
	trail = make([]string, 0, len(declared))
	complete = make([]candidate, 0, len(declared))
	for _, slug := range declared {
		b := airuntime.BackendID(slug)
		row, err := airuntime.BackendCapabilitiesFor(b)
		if err != nil {
			trail = append(trail, fmt.Sprintf("%s: not in the closed capability registry (%v)", slug, err))
			continue
		}
		// Hard constraint: model format × backend capability.
		if !containsFold(row.ModelFormats, manifest.Checkpoint.Format) {
			trail = append(trail, fmt.Sprintf("%s: excluded — format %q not in capability formats %v", slug, manifest.Checkpoint.Format, row.ModelFormats))
			continue
		}
		// Hard constraint: architecture × backend capability.
		arch := string(manifest.Architecture.Kind)
		if !containsFold(row.Architectures, arch) {
			trail = append(trail, fmt.Sprintf("%s: excluded — architecture %q not in capability architectures %v", slug, arch, row.Architectures))
			continue
		}
		if manifest.Architecture.Kind == modelmeta.ArchitectureMoE && !row.SupportsMoE {
			trail = append(trail, fmt.Sprintf("%s: excluded — supports_moe is false", slug))
			continue
		}
		// Hard constraint: required runtime features ⊆ capability
		// features (the v2 manifest schema does not yet declare
		// features — the empty set is the honest present; the check
		// stands for the schema's future, exact-match never fuzzy).
		if missing := firstMissingFeature(manifest, row); missing != "" {
			trail = append(trail, fmt.Sprintf("%s: excluded — required feature %q not provided (capability features %v)", slug, missing, row.Features))
			continue
		}
		// Hard constraint: placement × runtime presence (the join that
		// refuses a declared-but-not-running backend — and every
		// v19.7.2 infer_ssd plan, the declared-future backend).
		rt := findRuntime(snap, string(b))
		if rt == nil || !rt.Running || (row.HealthRequired && !rt.Healthy) {
			state := "not observed in the snapshot"
			if rt != nil {
				state = fmt.Sprintf("running=%t healthy=%t", rt.Running, rt.Healthy)
			}
			trail = append(trail, fmt.Sprintf("%s: excluded — runtime presence failed (%s)", slug, state))
			continue
		}
		// The hard capacity / image evaluation (the named downstream
		// refusal codes: image pinning, GPU/RAM capacity).
		c, exclCode, exclDetail := p.evaluateCapacity(b, row, manifest, rt, snap, req)
		if exclCode != "" {
			trail = append(trail, fmt.Sprintf("%s: excluded — %s (%s)", slug, exclCode, exclDetail))
			downstream = append(downstream, exclCode)
			continue
		}
		complete = append(complete, c)
		trail = append(trail, fmt.Sprintf("%s: eligible — strategy %s%s (utilization %d%%)", slug, c.strategy, gpuSuffix(c.gpu), c.util))
	}
	return complete, trail, downstream
}

// Plan computes the deterministic execution plan for req (or the named
// refusal). The full §7.4/§7.5 pipeline: validate the request → verify
// snapshot freshness (HARD) → resolve the model (manifest, eligibility,
// revision, context, VERIFIED artifact) → the capability × presence ×
// capacity × image join over every DECLARED backend (hard constraints,
// named exclusions) → the deterministic priority ordering → assemble
// the plan (content-hash PlanID, expiry, the generated explanation).
func (p *Planner) Plan(req ExecutionRequest) PlanResult {
	now := p.now()

	// 1. request shape.
	if reasons := req.Validate(); len(reasons) > 0 {
		return p.refuse(ReasonPlanRequestInvalid, fmt.Sprintf("request invalid: %s", strings.Join(reasons, "; ")), nil)
	}

	// 2. snapshot availability + freshness (HARD — KPK-19.7.0-P2-01).
	snap, err := p.snapshots.Current()
	if err != nil || snap == nil {
		return p.refuse(ReasonPlanSnapshotUnavailable, fmt.Sprintf("inventory snapshot unavailable: %v", err), nil)
	}
	if age := now.Sub(snap.ObservedAt); age > p.policy.MaxSnapshotAge {
		return p.refuse(ReasonPlanSnapshotStale, fmt.Sprintf("snapshot %s is %s old (bound %s) — a stale free-VRAM/free-space value is never current capacity (KPK-19.7.0-P2-01, HARD refusal)", snap.SnapshotID, age.Truncate(time.Second), p.policy.MaxSnapshotAge), snap)
	}
	base := PlanResult{SnapshotID: snap.SnapshotID, PolicyVersion: p.policy.PolicyVersion}

	// 3. model resolution: manifest → schema → placement gate →
	// revision → context → VERIFIED artifact (shared with the fabric
	// planner — modelGates).
	manifest, verif, refusal, ok := p.modelGates(req, base, now)
	if !ok {
		return refusal
	}

	// 4-6. the capability × presence × capacity × image join over every
	// DECLARED backend — hard constraints with named exclusions (shared
	// with the fabric planner — joinBackends).
	complete, trail, downstream := p.joinBackends(manifest, snap, req)
	base.Considered = trail

	if len(complete) == 0 {
		// The precise-code path: when the join reached the downstream
		// evaluation for EXACTLY ONE backend, its named refusal IS the
		// answer (the common deployed shape — one model, one backend);
		// multiple failures aggregate honestly into no-candidates with
		// the full trail.
		if len(downstream) == 1 {
			return p.refuseWith(base, downstream[0], fmt.Sprintf("no declared backend survived the join — %s — trail: %s", downstream[0], strings.Join(trail, " | ")))
		}
		return p.refuseWith(base, ReasonPlanBackendNoCandidates, fmt.Sprintf("no declared backend survived the capability × presence × capacity × image join — trail: %s", strings.Join(trail, " | ")))
	}

	// 7. the deterministic ordering (roadmap §7.5's tie-break
	// sequence): (1) policy priority, (2) lowest observed utilization
	// (the honest v19.7.2 queue-delay proxy — a real queue model
	// arrives with workload metrics, v19.8.0+), (3) tightest fit
	// (lowest fragmentation), (4) stable lexical backend + GPU UUID.
	sort.SliceStable(complete, func(i, j int) bool {
		return p.less(complete[i], complete[j])
	})
	winner := complete[0]

	// 8. assembly: the plan is a PROPOSAL (admission still required).
	plan := p.assemblePlan(req, manifest, verif, winner, snap, now, NodeLocal)
	out := base
	out.Selected = true
	out.ReasonCode = ReasonPlanOK
	out.Explanation = fmt.Sprintf("plan %s: model %s on %s (strategy %s, tier %d, policy priority %d) — a PROPOSAL: admission is still required; the plan expires at %s", plan.PlanID, req.ModelID, winner.backend, winner.strategy, tierOf(winner.backend), p.priorityOf(winner.backend)+1, plan.ExpiresAt.UTC().Format(time.RFC3339))
	out.Plan = plan
	return out
}

// less is the deterministic candidate comparator (roadmap §7.5's
// tie-break sequence): (1) policy priority, (2) lowest observed GPU
// utilization (the queue-delay proxy — CPU classes carry 0), (3)
// tightest fit (highest demand/allocatable ratio = lowest
// fragmentation), (4) stable lexical backend + GPU UUID.
func (p *Planner) less(a, b candidate) bool {
	pa, pb := p.priorityOf(a.backend), p.priorityOf(b.backend)
	if pa != pb {
		return pa < pb
	}
	if a.util != b.util {
		return a.util < b.util
	}
	if a.frag != b.frag {
		return a.frag > b.frag // tighter fit wins
	}
	if a.backend != b.backend {
		return a.backend < b.backend
	}
	return gpuUUID(a.gpu) < gpuUUID(b.gpu)
}

// priorityOf is the backend's position in the policy's priority list
// (not-listed ranks last, stably).
func (p *Planner) priorityOf(b airuntime.BackendID) int {
	for i, x := range p.policy.PriorityBackends {
		if x == b {
			return i
		}
	}
	return len(p.policy.PriorityBackends)
}

// evaluateCapacity computes the candidate's full vector + placement
// from the manifest × capability row × snapshot, or the named
// exclusion. The admission-shaped capacity math: the safety headroom
// is subtracted BEFORE the check; the OBSERVED free VRAM is the
// ceiling; single-GPU only; resident-only strategies (no storage
// demand in v19.7.2 — the weights are already on disk, the artifact
// verification proved them there).
func (p *Planner) evaluateCapacity(b airuntime.BackendID, row airuntime.BackendCapabilities, m *modelmeta.Manifest, rt *inventory.Runtime, snap *inventory.InventorySnapshotV2, req ExecutionRequest) (candidate, string, string) {
	// v19.8.0 (roadmap §8, Compute Fabric Phase 4): the InferSSD
	// execution class has its OWN evaluation — the ssd-backed-moe
	// strategy behind the operator's enabled runtime profile (the image
	// comes from the profile, the VRAM demand pages the experts out to
	// the approved SSD device, and the §8.2 GPU join + the §8.6 measured
	// qualification are hard constraints the resident path never had).
	if b == airuntime.BackendInferSSD {
		return p.evaluateInferSSD(b, row, m, snap, req)
	}
	c := candidate{backend: b, row: row}

	// The image hard constraint (operator-declared + digest-pinned).
	ref, has := p.policy.Images[b]
	if !has {
		return c, ReasonPlanImageUnconfigured, "the operator policy declares no image for this backend (the honest v19.7.2 default — declare digest-pinned references in the policy)"
	}
	if !strings.Contains(ref, "@sha256:") {
		return c, ReasonPlanImageNotDigestPinned, fmt.Sprintf("reference %q carries no @sha256: digest (roadmap §7.4's invariant — every image is digest-pinned)", ref)
	}
	c.image = PinnedImage{Reference: ref, DigestPinned: true}

	// The KV-cache derivation: declared when the manifest's estimate is
	// known; 0 + the honest explanation when it is not (runtimes size
	// the KV cache themselves — PlacementEligible's documented rule).
	kvBytes := uint64(req.ContextTokens) * m.Runtime.KVCache.BytesPerTokenEstimate

	// The weights footprint by architecture (the v19.7.2 strategies
	// are RESIDENT-ONLY: shared + ALL experts wherever they live).
	var sharedBytes, expertTotal uint64
	if m.Architecture.Kind == modelmeta.ArchitectureMoE {
		sharedBytes = m.Architecture.SharedBytes
		expertTotal = uint64(m.Architecture.ExpertCount) * m.Architecture.ExpertBytes
	} else {
		sharedBytes = m.Architecture.SharedBytes // dense: the whole checkpoint footprint
	}

	if row.RequiresGPU {
		// GPU execution class: the whole checkpoint + KV resident in
		// VRAM (the deployed sglang/vllm behavior).
		demand := sharedBytes + expertTotal + kvBytes
		if m.Architecture.Kind == modelmeta.ArchitectureMoE {
			c.strategy = StrategyMoEGPUResident
		} else {
			c.strategy = StrategyDenseResident
		}
		gpu, alloc, util, exclCode, exclDetail := p.pickGPU(snap, demand)
		if exclCode != "" {
			return c, exclCode, exclDetail
		}
		c.gpu = gpu
		c.util = util
		c.vector = admission.ResourceVector{
			GPU: []admission.GPURequest{{
				GPUUUID:   gpu.UUID,
				VRAMBytes: demand,
				Exclusive: true, // the v19.7.1+ safe default — sharing without compute-share enforcement is a phantom capability
			}},
			KVCacheBytes: kvBytes,
			RAMBytes:     p.policy.RuntimeOverheadRAMBytes, // honest 0 default: no measured runtime-RAM profile exists
			CPUThreads:   p.policy.DefaultCPUThreads,
		}
		c.frag = fragRatio(demand, alloc)
		return c, "", ""
	}

	// CPU execution class: the whole checkpoint + KV resident in host
	// RAM (llama.cpp-family behavior).
	ramDemand := sharedBytes + expertTotal + kvBytes + p.policy.RuntimeOverheadRAMBytes
	if m.Architecture.Kind == modelmeta.ArchitectureMoE {
		c.strategy = StrategyMoECPUResident
	} else {
		c.strategy = StrategyCPUResident
	}
	avail := snap.Host.RAMAvailableBytes
	if ramDemand > avail {
		return c, ReasonPlanRAMInsufficient, fmt.Sprintf("host-RAM demand %d bytes exceeds the observed available %d bytes (CPU execution class)", ramDemand, avail)
	}
	c.vector = admission.ResourceVector{
		RAMBytes:     ramDemand,
		KVCacheBytes: kvBytes,
		CPUThreads:   p.policy.DefaultCPUThreads,
	}
	c.frag = fragRatio(ramDemand, avail)
	return c, "", ""
}

// pickGPU deterministically selects the single GPU for a VRAM demand.
// The capacity check is admission-shaped: observed free minus the
// safety-headroom fraction of TOTAL. Among fitting GPUs the §7.5
// placement tie-breaks apply: lowest observed utilization (the
// queue-delay proxy) → tightest fit (lowest fragmentation) → stable
// UUID. No healthy GPU → plan-gpu-unavailable; no fitting GPU →
// plan-gpu-insufficient (multi-GPU splits are v19.8.0+ with measured
// per-GPU overhead profiles, never a guessed split).
func (p *Planner) pickGPU(snap *inventory.InventorySnapshotV2, demand uint64) (*inventory.GPU, uint64, int, string, string) {
	type fit struct {
		gpu   inventory.GPU
		alloc uint64
		util  int
	}
	var fits []fit
	for i := range snap.GPUs {
		g := snap.GPUs[i]
		if !g.Healthy {
			continue
		}
		total := uint64(g.VRAMTotalMB) << 20
		free := uint64(g.VRAMFreeMB) << 20
		headroom := uint64(float64(total) * p.policy.VRAMSafetyFraction)
		alloc := saturatingSub(free, headroom)
		if demand <= alloc {
			fits = append(fits, fit{gpu: g, alloc: alloc, util: g.UtilizationPct})
		}
	}
	if len(fits) == 0 {
		healthy := 0
		largest := uint64(0)
		for i := range snap.GPUs {
			if !snap.GPUs[i].Healthy {
				continue
			}
			healthy++
			total := uint64(snap.GPUs[i].VRAMTotalMB) << 20
			free := uint64(snap.GPUs[i].VRAMFreeMB) << 20
			alloc := saturatingSub(free, uint64(float64(total)*p.policy.VRAMSafetyFraction))
			if alloc > largest {
				largest = alloc
			}
		}
		if healthy == 0 {
			return nil, 0, 0, ReasonPlanGPUUnavailable, "no healthy GPU in the snapshot (GPU execution class)"
		}
		return nil, 0, 0, ReasonPlanGPUInsufficient, fmt.Sprintf("demand %d bytes exceeds every single GPU's allocatable (largest %d bytes after the %v headroom) — multi-GPU splits need measured per-GPU overhead profiles (v19.8.0+), never a guessed split", demand, largest, p.policy.VRAMSafetyFraction)
	}
	// (2) utilization → (3) tightest fit → (4) stable UUID.
	sort.SliceStable(fits, func(i, j int) bool {
		if fits[i].util != fits[j].util {
			return fits[i].util < fits[j].util
		}
		if fits[i].alloc != fits[j].alloc {
			return fits[i].alloc < fits[j].alloc // smaller sufficient allocatable = tighter fit
		}
		return fits[i].gpu.UUID < fits[j].gpu.UUID
	})
	best := fits[0]
	gpu := best.gpu
	return &gpu, best.alloc, best.util, "", ""
}

// evaluateInferSSD is the v19.8.0 InferSSD execution class's own hard
// constraint chain (roadmap §8, Compute Fabric Phase 4) — reached only
// AFTER the placement × runtime join observed an infer_ssd runtime
// running + healthy (the join in Plan() refuses every default
// deployment first). The chain, every refusal BY NAME:
//
//	(1) the enabled runtime profile        → plan-ssd-profile-unconfigured
//	(2) the §8.2 model binding             → plan-ssd-profile-model-mismatch
//	(3) the profile's serving ceiling      → plan-context-exceeds-profile-limit
//	(4) the profile's digest-pinned image  → plan-image-not-digest-pinned
//	(5) the §8.2 GPU compatibility join    → plan-ssd-gpu-incompatible
//	    + the admission-shaped VRAM check  → plan-gpu-unavailable / -insufficient
//	(6) the §8.6 measured qualification    → plan-ssd-device-unknown /
//	                                           plan-ssd-unqualified /
//	                                           plan-ssd-storage-insufficient
//
// The strategy is ssd-backed-moe: shared weights + KV resident in VRAM
// (plus the profile's own additive demands), experts paged from the
// approved SSD path — the vector carries the storage demand WITH the
// profile's measured floors so admission revalidates the same facts.
func (p *Planner) evaluateInferSSD(b airuntime.BackendID, row airuntime.BackendCapabilities, m *modelmeta.Manifest, snap *inventory.InventorySnapshotV2, req ExecutionRequest) (candidate, string, string) {
	c := candidate{backend: b, row: row}

	// (1) §8.8's enablement policy: the profile hard constraint. The
	// honest v19.8.0 default is NO enabled profile — nothing ships one,
	// and even an observed running runtime plans nothing without the
	// operator's deliberate, validated, digest-pinned enablement act.
	profile := p.policy.SSDProfile
	if profile == nil {
		return c, ReasonPlanSSDProfileUnconfigured, "no ENABLED InferSSD runtime profile is configured (roadmap §8.8's initial status: enabled=false — the operator's deliberate act follows the compatibility matrix + the target-host acceptance; SCARLIHQ_INFERSSD_PROFILE declares the path)"
	}

	// (2) the §8.2 model binding (the adapter's own join, reused — one
	// implementation of the exact-combination rule, the planner and the
	// Host Bridge path read the same verdict).
	bind := infer_ssd.BindModel(profile, m.Execution(""))
	if !bind.Qualified {
		return c, ReasonPlanSSDProfileModelMismatch, fmt.Sprintf("%s — %s (roadmap §8.2: the profile is the evidence record for ONE exact model × engine combination)", bind.Code, bind.Detail)
	}

	// (3) the profile's serving ceiling (§8.4's execution.context_limit —
	// a second, tighter ceiling under the model's own; the request is
	// what is served, so the request is what is checked).
	if req.ContextTokens > profile.Execution.ContextLimit {
		return c, ReasonPlanProfileContextExceedsLimit, fmt.Sprintf("context_tokens %d exceeds the runtime profile's serving ceiling %d (roadmap §8.4's execution.context_limit — the experimental engine's own bound)", req.ContextTokens, profile.Execution.ContextLimit)
	}

	// (4) the image: the profile's digest-pinned reference IS the image
	// for this backend (the loader validated the pin; the re-check here
	// is defense in depth — the same enforcement expression the resident
	// path uses).
	ref := profile.Image.Reference
	if !strings.Contains(ref, "@sha256:") {
		return c, ReasonPlanImageNotDigestPinned, fmt.Sprintf("the runtime profile's image reference %q carries no @sha256: digest (roadmap §8.4's exit criterion — runtime profiles are digest-pinned and fixed)", ref)
	}
	c.image = PinnedImage{Reference: ref, DigestPinned: true}

	// The ssd-backed-moe derivation: shared + the profile's own reserve
	// resident in VRAM; the KV cache rides ResourceVector.KVCacheBytes and
	// the ADMISSION gate adds it to the assigned GPU exactly once
	// (v19.8.1, KPK-19.8.0-P2-03's single-count contract: baking KV into
	// VRAMBytes made the gate count it twice and refuse workloads that
	// fit); the experts live on the SSD.
	kvBytes := uint64(req.ContextTokens) * m.Runtime.KVCache.BytesPerTokenEstimate
	vramDemand := m.Architecture.SharedBytes + profile.Resources.GPU.VRAMReserveBytes
	expertTotal := infer_ssd.ExpertStorageBytes(m.Execution(""))
	c.strategy = StrategySSDBackedMoE

	// (5) the §8.2 GPU compatibility join (declared compute capabilities
	// + EXACT CUDA + minimum driver against the OBSERVED GPU) folded
	// into the same admission-shaped capacity + tie-break discipline as
	// pickGPU: utilization → tightest fit → stable UUID.
	gpu, alloc, util, compatDetail, exclCode, exclDetail := p.pickGPUForProfile(profile, snap, vramDemand)
	if exclCode != "" {
		return c, exclCode, exclDetail
	}
	c.gpu = gpu
	c.util = util
	c.frag = fragRatio(vramDemand, alloc)
	c.ssdGPUCompat = compatDetail

	// (6) the §8.6 measured SSD qualification on the profile's device:
	// MEASURED conservative capacity only — a measured-performance floor
	// without a measurement is a named refusal, never an estimate.
	var dev *storage.Device
	for i := range snap.Storage {
		if snap.Storage[i].ID == profile.Resources.Storage.DeviceID {
			dev = &snap.Storage[i]
			break
		}
	}
	qual := infer_ssd.QualifySSD(profile, dev, expertTotal)
	if !qual.Qualified {
		switch qual.Code {
		case infer_ssd.QualificationDeviceUnknown:
			return c, ReasonPlanSSDDeviceUnknown, qual.Detail
		case infer_ssd.QualificationNoReadProfile, infer_ssd.QualificationFloorsUnmet:
			return c, ReasonPlanSSDUnqualified, qual.Detail
		case infer_ssd.QualificationFreeBytesInsufficient:
			return c, ReasonPlanSSDStorageInsufficient, qual.Detail
		default:
			return c, ReasonPlanSSDUnqualified, qual.Detail
		}
	}
	c.ssdQual = qual

	// The vector: exclusive GPU hold (shared + reserve; the KV cache rides
	// KVCacheBytes and admission adds it once — P2-03's single-count
	// contract), the profile's additive host demands, and the storage
	// demand WITH the profile's measured floors (admission revalidates the
	// same facts the planner checked — the proposal is admission-shaped).
	c.vector = admission.ResourceVector{
		GPU: []admission.GPURequest{{
			GPUUUID:   gpu.UUID,
			VRAMBytes: vramDemand,
			Exclusive: true, // §8.8: one allocation per GPU
		}},
		RAMBytes:       profile.Resources.HostRAMBytes,
		PinnedRAMBytes: profile.Resources.PinnedRAMBytes,
		CPUThreads:     float64(profile.Resources.CPUThreads),
		KVCacheBytes:   kvBytes,
		Storage: []admission.StorageRequest{{
			DeviceID:              profile.Resources.Storage.DeviceID,
			MinimumFreeBytes:      expertTotal + profile.Resources.Storage.MinimumFreeBytes,
			MinimumReadMBps:       profile.Resources.Storage.MinimumReadMBps,
			MinimumRandomReadIOPS: profile.Resources.Storage.MinimumRandomReadIOPS,
			MaximumP95LatencyMs:   profile.Resources.Storage.MaximumP95LatencyMs,
			PathClass:             "model",
		}},
	}
	c.ssdProfile = profile

	// §8.8's concurrency capping: the profile's cap (exactly 1 in
	// v19.8.0) bounds the request's wish — the plan carries the capped
	// value with a generated explanation entry, never a silent edit.
	if req.MaxConcurrent > profile.Execution.MaxConcurrentRequests {
		c.ssdCapped = profile.Execution.MaxConcurrentRequests
	}
	return c, "", ""
}

// pickGPUForProfile is pickGPU with the §8.2 GPU compatibility join
// folded in: only healthy GPUs whose OBSERVED compute capability ∈ the
// profile's declared capabilities, whose driver CUDA matches the
// declared CUDA EXACTLY, and whose driver version meets the declared
// minimum can serve the profile — the declared combinations are the
// TESTED combinations, everything else is the named refusal. The
// tie-break sequence after the filter is unchanged (utilization →
// tightest fit → stable UUID). No healthy+compatible GPU →
// plan-ssd-gpu-incompatible; no fitting one → plan-gpu-insufficient.
func (p *Planner) pickGPUForProfile(profile *infer_ssd.RuntimeProfile, snap *inventory.InventorySnapshotV2, demand uint64) (*inventory.GPU, uint64, int, string, string, string) {
	type fit struct {
		gpu    inventory.GPU
		alloc  uint64
		util   int
		compat string
	}
	var fits []fit
	var firstCompatRefusal string
	for i := range snap.GPUs {
		g := snap.GPUs[i]
		if !g.Healthy {
			continue
		}
		ok, compatDetail := infer_ssd.GPUCompatibility(profile, g)
		if !ok {
			if firstCompatRefusal == "" {
				firstCompatRefusal = compatDetail
			}
			continue
		}
		total := uint64(g.VRAMTotalMB) << 20
		free := uint64(g.VRAMFreeMB) << 20
		headroom := uint64(float64(total) * p.policy.VRAMSafetyFraction)
		alloc := saturatingSub(free, headroom)
		if demand <= alloc {
			fits = append(fits, fit{gpu: g, alloc: alloc, util: g.UtilizationPct, compat: compatDetail})
		}
	}
	if len(fits) == 0 {
		// Distinguish the two refusals honestly: no GPU passed the §8.2
		// join at all → plan-ssd-gpu-incompatible (the declared
		// combinations are the tested combinations); a compatible GPU
		// exists but the demand exceeds its allocatable → the same
		// plan-gpu-insufficient the resident path names.
		compatible := 0
		largest := uint64(0)
		for i := range snap.GPUs {
			g := snap.GPUs[i]
			if !g.Healthy {
				continue
			}
			if ok, _ := infer_ssd.GPUCompatibility(profile, g); !ok {
				continue
			}
			compatible++
			total := uint64(g.VRAMTotalMB) << 20
			free := uint64(g.VRAMFreeMB) << 20
			alloc := saturatingSub(free, uint64(float64(total)*p.policy.VRAMSafetyFraction))
			if alloc > largest {
				largest = alloc
			}
		}
		if compatible == 0 {
			detail := firstCompatRefusal
			if detail == "" {
				detail = "no healthy GPU in the snapshot"
			}
			return nil, 0, 0, "", ReasonPlanSSDGPUIncompatible, fmt.Sprintf("no healthy GPU passed the §8.2 compatibility join — %s", detail)
		}
		return nil, 0, 0, "", ReasonPlanGPUInsufficient, fmt.Sprintf("demand %d bytes exceeds every compatible GPU's allocatable (largest %d bytes after the %v headroom) — the §8.2 join passed but the capacity did not", demand, largest, p.policy.VRAMSafetyFraction)
	}
	sort.SliceStable(fits, func(i, j int) bool {
		if fits[i].util != fits[j].util {
			return fits[i].util < fits[j].util
		}
		if fits[i].alloc != fits[j].alloc {
			return fits[i].alloc < fits[j].alloc // smaller sufficient allocatable = tighter fit
		}
		return fits[i].gpu.UUID < fits[j].gpu.UUID
	})
	best := fits[0]
	gpu := best.gpu
	return &gpu, best.alloc, best.util, best.compat, "", ""
}

// strategyExplanationTail renders the strategy-specific closing text of
// the strategy-derived explanation entry: the resident strategies name
// the v19.8.0 paging exception's boundary; ssd-backed-moe names its own
// §8 derivation. GENERATED text, deterministic per strategy — an LLM
// never authors it.
func strategyExplanationTail(strategy string) string {
	if strategy == StrategySSDBackedMoE {
		return "ssd-backed-moe (roadmap §8): shared weights + KV resident in VRAM, the experts paged from the approved SSD path behind the enabled runtime profile — the vector carries the storage demand WITH the measured floors"
	}
	return "infer_ssd's ssd-backed-moe (roadmap §8) is the v19.8.0 paging exception, derived only behind an enabled runtime profile with a measured qualification"
}

// assemblePlan builds the final plan: the content-hash PlanID (the
// identity IS the decision), the expiry, the generated explanation
// trail, and the ask's provenance.
func (p *Planner) assemblePlan(req ExecutionRequest, m *modelmeta.Manifest, verif *modelmeta.ArtifactVerification, c candidate, snap *inventory.InventorySnapshotV2, now time.Time, nodeID string) *ExecutionPlan {
	plan := &ExecutionPlan{
		BackendID:       c.backend,
		Strategy:        c.strategy,
		NodeID:          nodeID, // v19.7.2 local by construction; the v19.9.0 fabric planner passes the selected node (roadmap §9.4)
		ModelArtifactID: fmt.Sprintf("%s@%s#%s", m.ID, m.Revision, strings.ToLower(m.Checkpoint.SHA256)),
		ResourceVector:  c.vector,
		RequiredImages:  []PinnedImage{c.image},
		ConfigProfileID: "", // the resident strategies carry no config profile — a declared absence, never a guessed profile
		ExpiresAt:       now.Add(p.policy.PlanTTL),
		RequestID:       req.RequestID,
		ModelID:         m.ID,
		ModelRevision:   m.Revision,
		Principal:       req.Principal,
		Task:            req.Task,
		ContextTokens:   req.ContextTokens,
		MaxConcurrent:   req.MaxConcurrent,
		LatencyClass:    req.LatencyClass,
	}
	// v19.8.0 (roadmap §8): the ssd-backed-moe plan's config profile IS
	// the runtime profile the strategy derived from — the first real
	// value this field ever carries (v19.7.2's honest empty stays for
	// the resident strategies), and the §8.8 concurrency cap bounds the
	// ask's wish (the capped value rides the plan + a generated entry —
	// never a silent edit of the operator-visible ask).
	if c.ssdProfile != nil {
		plan.ConfigProfileID = c.ssdProfile.ProfileID
		if c.ssdCapped > 0 {
			plan.MaxConcurrent = c.ssdCapped
		}
	}
	if c.gpu != nil {
		plan.GPUUUIDs = []string{c.gpu.UUID}
	}

	// The generated explanation trail (machine-readable; every number
	// named; GENERATED here — an LLM never authors an entry).
	expl := []DecisionReason{
		{Code: "backend-selected", Detail: fmt.Sprintf("%s (tier %d, policy priority %d) — capability row: formats %v, architectures %v, experimental=%t", c.backend, tierOf(c.backend), p.priorityOf(c.backend)+1, c.row.ModelFormats, c.row.Architectures, c.row.Experimental)},
		{Code: "strategy-derived", Detail: fmt.Sprintf("%s from architecture %s × execution class (requires_gpu=%t) — the resident strategies carry no storage demand (the weights are already on disk, the artifact verification proved them there); %s", c.strategy, m.Architecture.Kind, c.row.RequiresGPU, strategyExplanationTail(c.strategy))},
		{Code: "artifact-verified", Detail: fmt.Sprintf("verified at %s (age bound %s) — %s", verif.VerifiedAt.UTC().Format(time.RFC3339), p.policy.VerificationMaxAge, plan.ModelArtifactID)},
		{Code: "snapshot-fresh", Detail: fmt.Sprintf("snapshot %s within the %s bound", snap.SnapshotID, p.policy.MaxSnapshotAge)},
		{Code: "image-pinned", Detail: c.image.Reference},
	}
	if c.gpu != nil {
		expl = append(expl, DecisionReason{Code: "gpu-assigned", Detail: fmt.Sprintf("%s (observed free %d MB, safety headroom %v, utilization %d%%) — exclusive per UUID (the v19.7.1+ safe default)", c.gpu.UUID, c.gpu.VRAMFreeMB, p.policy.VRAMSafetyFraction, c.gpu.UtilizationPct)})
	} else {
		expl = append(expl, DecisionReason{Code: "cpu-class", Detail: fmt.Sprintf("host-RAM resident — demand %d bytes against the observed available %d bytes", c.vector.RAMBytes, snap.Host.RAMAvailableBytes)})
	}
	if m.Runtime.KVCache.BytesPerTokenEstimate == 0 {
		expl = append(expl, DecisionReason{Code: "kv-cache-estimate-unknown", Detail: "the manifest declares no kv_cache.bytes_per_token_estimate — the proposed KV demand is 0 and the runtime sizes the KV cache itself (PlacementEligible's documented rule; admission holds only the declared demand)"})
	}
	if c.row.Experimental {
		expl = append(expl, DecisionReason{Code: "backend-experimental", Detail: fmt.Sprintf("%s is EXPERIMENTAL in the deployed stack — the selection is carried visibly, never silently", c.backend)})
	}
	// v19.8.0 (roadmap §8): the ssd-backed-moe plan's own generated
	// entries — the profile binding, the §8.2 GPU join, the §8.6
	// measured qualification, and the §8.8 concurrency cap (every
	// number named; GENERATED here, an LLM never authors one).
	if c.ssdProfile != nil {
		expl = append(expl,
			DecisionReason{Code: "ssd-profile-bound", Detail: fmt.Sprintf("runtime profile %q (experimental, image %s) binds model %q @ checkpoint %s — roadmap §8.2's exact-combination evidence record", c.ssdProfile.ProfileID, c.image.Reference, c.ssdProfile.Compatibility.ModelManifest, c.ssdProfile.Compatibility.CheckpointSHA256)},
			DecisionReason{Code: "ssd-gpu-compatibility-joined", Detail: c.ssdGPUCompat},
			DecisionReason{Code: "ssd-qualified-measured", Detail: c.ssdQual.Detail},
		)
		if c.ssdCapped > 0 {
			expl = append(expl, DecisionReason{Code: "ssd-concurrency-capped", Detail: fmt.Sprintf("the ask's max_concurrent %d is capped to the profile's §8.8 limit %d (one active workload per SSD profile unless contention evidence justifies more — none exists in v19.8.0)", req.MaxConcurrent, c.ssdCapped)})
		}
	}
	// v19.8.0: an ENABLED expert pack declaration on the model is
	// carried HONESTLY — declared, not planned. The §8.8 enablement
	// policy keeps pack execution off until pack-byte verification +
	// the §8.7 target-host acceptance matrix pass; the resident
	// strategy above IS the plan.
	if m.Artifacts.ExpertPack.Enabled {
		expl = append(expl, DecisionReason{Code: "expert-pack-declared-not-planned", Detail: fmt.Sprintf("the model declares an ENABLED Expert Pack for backend %q (%s) — v19.8.0 models the pack at the artifact tier (scarlix.artifact/v1) and keeps pack EXECUTION unplanned until pack-byte verification + the §8.7 target-host acceptance matrix pass (the §8.8 enablement policy); the strategy above is the plan", m.Artifacts.ExpertPack.CompatibleBackend, m.Artifacts.ExpertPack.Format)})
	}
	expl = append(expl, DecisionReason{Code: "plan-is-proposal", Detail: fmt.Sprintf("nothing is reserved, bound or launched — admission is still required; the plan expires at %s and is revalidated at admission time", plan.ExpiresAt.UTC().Format(time.RFC3339))})
	plan.Explanation = expl

	plan.PlanID = p.planContentHash(plan)
	return plan
}

// planContentHash hashes the decision tuple: the policy version (the
// policy identity that produced the decision), backend, strategy,
// node, GPUs, the artifact binding, the vector, the images, the
// config profile, and the ask's provenance — canonical JSON, SHA-256,
// 16 bytes hex. Identical inputs → identical ID (the determinism
// proof); the expiry clock and the derived identity ride separately.
func (p *Planner) planContentHash(plan *ExecutionPlan) string {
	tuple := struct {
		Policy string         `json:"policy"`
		Plan   *ExecutionPlan `json:"plan"`
	}{
		Policy: p.policy.PolicyVersion,
		Plan: &ExecutionPlan{
			BackendID:       plan.BackendID,
			Strategy:        plan.Strategy,
			NodeID:          plan.NodeID,
			GPUUUIDs:        plan.GPUUUIDs,
			ModelArtifactID: plan.ModelArtifactID,
			ResourceVector:  plan.ResourceVector,
			RequiredImages:  plan.RequiredImages,
			ConfigProfileID: plan.ConfigProfileID,
			RequestID:       plan.RequestID,
			ModelID:         plan.ModelID,
			ModelRevision:   plan.ModelRevision,
			Principal:       plan.Principal,
			Task:            plan.Task,
			ContextTokens:   plan.ContextTokens,
			MaxConcurrent:   plan.MaxConcurrent,
			LatencyClass:    plan.LatencyClass,
		},
	}
	b, err := json.Marshal(tuple)
	if err != nil {
		// Canonical JSON of plain strings/ints cannot fail; reaching
		// here is a programming error — the loud failure is more
		// honest than a fabricated identity.
		panic(fmt.Sprintf("planner: plan tuple marshal failed: %v", err))
	}
	sum := sha256.Sum256(b)
	return "plan-" + hex.EncodeToString(sum[:16])
}

// refuse builds a bare refusal (before the snapshot resolves).
func (p *Planner) refuse(code, explanation string, snap *inventory.InventorySnapshotV2) PlanResult {
	r := PlanResult{ReasonCode: code, Explanation: explanation, PolicyVersion: p.policy.PolicyVersion}
	if snap != nil {
		r.SnapshotID = snap.SnapshotID
	}
	return r
}

// refuseWith builds a refusal carrying the resolved-snapshot base.
func (p *Planner) refuseWith(base PlanResult, code, explanation string) PlanResult {
	base.Selected = false
	base.ReasonCode = code
	base.Explanation = explanation
	base.Plan = nil
	return base
}

// ---- small helpers ---------------------------------------------------------

func tierOf(b airuntime.BackendID) int {
	t, err := airuntime.BackendTier(b)
	if err != nil {
		return -1
	}
	return t
}

func findRuntime(snap *inventory.InventorySnapshotV2, id string) *inventory.Runtime {
	for i := range snap.Runtimes {
		if snap.Runtimes[i].ID == id {
			rt := snap.Runtimes[i]
			return &rt
		}
	}
	return nil
}

// requiredRuntimeFeatures returns the manifest's required runtime
