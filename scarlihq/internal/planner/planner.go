// Planner is the deterministic execution planner. Construction is
// cheap and fail-closed: the CLOSED backend capability registry is
// validated at construction (roadmap §7.2's "validated at startup" —
// an inconsistent registry is a construction error, never a
// per-request surprise), and the policy's closed shapes are validated
// the same way. Every Plan call is pure: no writes, no dials, no
// reservations — the output is a proposal admission still has to
// accept.
type Planner struct {
	policy    PlannerPolicy
	snapshots SnapshotSource
	models    ModelSource
	now       func() time.Time
}

// NewPlanner wires the planner. Fail-closed on an inconsistent
// capability registry or a malformed policy.
func NewPlanner(policy PlannerPolicy, snapshots SnapshotSource, models ModelSource) (*Planner, error) {
	if err := airuntime.ValidateBackendRegistry(); err != nil {
		return nil, fmt.Errorf("planner: the closed backend capability registry is inconsistent — refusing to construct (roadmap §7.2: validated at startup): %w", err)
	}
	if policy.PolicyVersion == "" {
		policy = DefaultPlannerPolicy()
	}
	if err := validatePolicy(policy); err != nil {
		return nil, fmt.Errorf("planner: policy malformed: %w", err)
	}
	if snapshots == nil || models == nil {
		return nil, fmt.Errorf("planner: sources must not be nil (a planner without inputs is a guess factory)")
	}
	return &Planner{policy: policy, snapshots: snapshots, models: models, now: time.Now}, nil
}

