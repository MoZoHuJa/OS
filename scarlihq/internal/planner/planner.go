// ---------------------------------------------------------------------------
// The request contract (roadmap §7.4 — the field set is the contract)
// ---------------------------------------------------------------------------

// LatencyClass values — the CLOSED request vocabulary (an unknown class
// is a named refusal, never a silent default).
const (
	LatencyInteractive = "interactive"
	LatencyThroughput  = "throughput"
	LatencyBatch       = "batch"
)

// ExecutionRequest is the typed operator ask. Deliberately WITHOUT any
// selection-steering field (roadmap §7.6): no preferred backend, no
// explanation echo, no policy override — the deterministic selection
// order belongs to the operator-owned PlannerPolicy alone, so an LLM
// proposal can only ever become a typed request, never a steering
// input.
type ExecutionRequest struct {
	// RequestID — the caller's request identity (required non-empty;
	// carried into the plan for traceability).
	RequestID string `json:"request_id"`
	// ModelID — the model to serve (must have a schema-valid,
	// placement-eligible, ARTIFACT-VERIFIED manifest).
	ModelID string `json:"model_id"`
	// ModelRevision — the checkpoint revision label. Empty = any; a
	// non-empty value must MATCH the manifest's revision exactly.
	ModelRevision string `json:"model_revision,omitempty"`
	// Task — the workload's task label (carried into the plan as
	// declared metadata; bounded free text, no control characters).
	Task string `json:"task"`
	// ContextTokens — the context length the workload demands. Must be
	// > 0 and <= the manifest's context limit (a named hard refusal
	// otherwise — planning a context the model cannot serve would be a
	// phantom capability).
	ContextTokens int `json:"context_tokens"`
	// MaxConcurrent — the workload's concurrency wish (carried into the
	// plan as declared metadata; v19.7.2 has no concurrency accounting —
	// admission is one-allocation-per-GPU — so the value informs, never
	// reserves). Bounded [1, 16].
	MaxConcurrent int `json:"max_concurrent"`
	// LatencyClass — one of interactive / throughput / batch (carried
	// into the plan; declared metadata for the operator — it does NOT
	// alter the deterministic selection order).
	LatencyClass string `json:"latency_class"`
	// Principal — the authenticated identity asking for the plan
	// (stamped SERVER-SIDE at the API layer, never caller-supplied).
	Principal string `json:"principal,omitempty"`
}

// Validate checks the request's shape (a named reason per violation).
func (r ExecutionRequest) Validate() []string {
	var reasons []string
	add := func(format string, args ...interface{}) {
		reasons = append(reasons, fmt.Sprintf(format, args...))
	}
	if r.RequestID == "" {
		add("request_id is empty")
	}
	if len(r.RequestID) > 128 {
		add("request_id exceeds 128 characters")
	}
	if r.ModelID == "" {
		add("model_id is empty")
	}
	if len(r.ModelID) > 128 {
		add("model_id exceeds 128 characters")
	}
	if r.Task == "" {
		add("task is empty")
	}
	if len(r.Task) > 256 {
		add("task exceeds 256 characters")
	}
	for _, s := range []string{r.RequestID, r.ModelID, r.ModelRevision, r.Task, r.LatencyClass} {
		for _, c := range s {
			if c < 0x20 || c == 0x7f {
				add("request fields must not contain control characters")
				break
			}
		}
	}
	if r.ContextTokens <= 0 {
		add("context_tokens must be > 0")
	}
	if r.MaxConcurrent < 1 || r.MaxConcurrent > 16 {
		add("max_concurrent %d outside [1,16]", r.MaxConcurrent)
	}
	switch r.LatencyClass {
	case LatencyInteractive, LatencyThroughput, LatencyBatch:
	default:
		add("latency_class %q is not one of interactive/throughput/batch", r.LatencyClass)
	}
	return reasons
}

