// Reason codes — the closed, stable refusal vocabulary (additions are
// additive, renames are breaking).
const (
	// ReasonPlanOK — a plan was produced (a proposal; admission still
	// required).
	ReasonPlanOK = "ok"
	// ReasonPlanRequestInvalid — malformed request (named reasons).
	ReasonPlanRequestInvalid = "plan-request-invalid"
	// ReasonPlanSnapshotUnavailable — the inventory snapshot could not
	// be built.
	ReasonPlanSnapshotUnavailable = "plan-snapshot-unavailable"
	// ReasonPlanSnapshotStale — HARD refusal (KPK-19.7.0-P2-01's rule:
	// never consume stale free-VRAM/free-space as current capacity).
	ReasonPlanSnapshotStale = "plan-snapshot-stale"
	// ReasonPlanModelUnknown — no manifest declares the model.
	ReasonPlanModelUnknown = "plan-model-unknown"
	// ReasonPlanModelIneligible — the manifest fails schema validation,
	// the placement gate, or the planner's own vector derivation
	// (metadata incomplete — named reasons, never a defaulted guess).
	ReasonPlanModelIneligible = "plan-model-ineligible"
	// ReasonPlanModelUnverified — no artifact verification record, the
	// record is not fully verified, or it is stale (KPK-19.7.0-P2-04's
	// rule: the planner consumes VERIFIED records, never declared
	// digests; a stale verification is absent verification).
	ReasonPlanModelUnverified = "plan-model-unverified"
	// ReasonPlanModelRevisionMismatch — the requested revision does not
	// match the manifest's revision.
	ReasonPlanModelRevisionMismatch = "plan-model-revision-mismatch"
	// ReasonPlanContextExceedsLimit — the demanded context exceeds the
	// model's declared context limit.
	ReasonPlanContextExceedsLimit = "plan-context-exceeds-limit"
	// ReasonPlanBackendNoCandidates — no declared backend survived the
	// capability × presence × capacity × image join (the trail names
	// every exclusion).
	ReasonPlanBackendNoCandidates = "plan-backend-no-candidates"
	// ReasonPlanGPUUnavailable — a GPU-class backend found no healthy
	// GPU in the snapshot.
	ReasonPlanGPUUnavailable = "plan-gpu-unavailable"
	// ReasonPlanGPUInsufficient — the weights+KV footprint exceeds every
	// single GPU's allocatable (multi-GPU plans need measured per-GPU
	// overhead profiles — v19.8.0+, never a guessed split).
	ReasonPlanGPUInsufficient = "plan-gpu-insufficient"
	// ReasonPlanRAMInsufficient — a CPU-class backend's host-RAM demand
	// exceeds the observed available RAM.
	ReasonPlanRAMInsufficient = "plan-ram-insufficient"
	// ReasonPlanImageUnconfigured — the operator policy declares no
	// image for the backend (the honest v19.7.2 default: no
	// digest-pinned references ship — the operator declares them).
	ReasonPlanImageUnconfigured = "plan-image-unconfigured"
	// ReasonPlanImageNotDigestPinned — the declared image reference
	// carries no @sha256: digest (roadmap §7.4's invariant, enforced).
	ReasonPlanImageNotDigestPinned = "plan-image-not-digest-pinned"
)

// PlanResult is the planner's answer: a plan (a PROPOSAL) or a named
// refusal — never a bare boolean. Selected=false is the planner
// working, not an error.
type PlanResult struct {
	// Selected — true iff a plan was produced.
	Selected bool `json:"selected"`
	// ReasonCode — one of the Reason* constants (machine-readable).
	ReasonCode string `json:"reason_code"`
	// Explanation — the human-readable summary behind the decision.
	Explanation string `json:"explanation"`
	// Plan — the proposed execution plan (set when selected).
	Plan *ExecutionPlan `json:"plan,omitempty"`
	// SnapshotID — the inventory snapshot the plan was computed
	// against (provenance).
	SnapshotID string `json:"snapshot_id"`
	// PolicyVersion — the policy that produced the plan.
	PolicyVersion string `json:"policy_version"`
	// Considered — the candidate trail: one entry per evaluated
	// backend with its outcome (deterministic order).
	Considered []string `json:"considered"`
}

// ---------------------------------------------------------------------------
// The policy (operator-owned; the ONLY selection-order input)
// ---------------------------------------------------------------------------

// PlannerPolicy is the operator-owned planning policy. The priority
// order here — and ONLY here — steers selection between eligible
// backends (roadmap §7.5's tie-break 1). Requests carry no steering
// fields; LLM output reaches the planner only as a typed
// operator-approved request.
type PlannerPolicy struct {
	// PolicyVersion — carried in every result (provenance).
	PolicyVersion string
	// MaxSnapshotAge — the freshness bound; a staler snapshot is HARD
	// refused (KPK-19.7.0-P2-01's rule, mirrored from admission).
	MaxSnapshotAge time.Duration
	// VerificationMaxAge — how old an artifact verification record may
	// be (KPK-19.7.0-P2-04's rule: stale verification is absent
	// verification).
	VerificationMaxAge time.Duration
	// PlanTTL — how long a plan is valid (revalidated at admission).
	PlanTTL time.Duration
	// PriorityBackends — the operator preference order (tie-break 1).
	// Backends not listed rank last, stably. The default mirrors the
	// v19.0.6 release-locked failover order; infer_ssd is deliberately
	// absent (never preferred while its adapter does not exist).
	PriorityBackends []airuntime.BackendID
	// Images — the operator-declared pinned image registry (roadmap
	// §7.4's "digest-pinned and allowlisted": an image HERE is the
	// allowlist; the plan enforces the digest pin BY NAME). Empty map =
	// the honest v19.7.2 default — every plan refuses
	// plan-image-unconfigured until the operator declares references.
	Images map[airuntime.BackendID]string
	// RuntimeOverheadRAMBytes — the host-RAM overhead of a serving
	// runtime process. HONEST DEFAULT 0: no measured runtime-RAM
	// profile exists in v19.7.1/19.7.2 — the operator sets a measured
	// value or the plan proposes zero overhead (admission still
	// enforces the requested RAM at reserve time; the zero is a
	// DECLARED unknown, not a guess).
	RuntimeOverheadRAMBytes uint64
	// DefaultCPUThreads — the CPU threads proposed for a serving
	// workload (operator policy default; admission revalidates).
	DefaultCPUThreads float64
	// VRAMSafetyFraction — the headroom fraction of a GPU's TOTAL VRAM
	// subtracted before the capacity check (mirrors admission's 5% so
	// the proposal is admission-shaped, never optimistic).
	VRAMSafetyFraction float64
}

// DefaultPlannerPolicy is the documented v19.7.2 policy.
func DefaultPlannerPolicy() PlannerPolicy {
	return PlannerPolicy{
		PolicyVersion:           "planner/v19.7.2",
		MaxSnapshotAge:          60 * time.Second,
		VerificationMaxAge:      7 * 24 * time.Hour,
		PlanTTL:                 5 * time.Minute,
		PriorityBackends:        []airuntime.BackendID{airuntime.BackendSGLang, airuntime.BackendVLLM, airuntime.BackendBeeLlama, airuntime.BackendOllama},
		Images:                  map[airuntime.BackendID]string{},
		RuntimeOverheadRAMBytes: 0,
		DefaultCPUThreads:       4,
		VRAMSafetyFraction:      0.05,
	}
}

