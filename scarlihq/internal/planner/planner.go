	// verification; the record voids until re-verification).
	ReasonPlanModelVerificationIdentityMismatch = "plan-model-verification-identity-mismatch"
	// ReasonPlanModelRevisionMismatch — the requested revision does not
	// match the manifest's revision.
	ReasonPlanModelRevisionMismatch = "plan-model-revision-mismatch"
	// ReasonPlanContextExceedsLimit — the demanded context exceeds the
	// model's declared context limit.
	ReasonPlanContextExceedsLimit = "plan-context-exceeds-limit"
	// ReasonPlanBackendNoCandidates — no declared backend survived the
	// capability × presence × capacity × image join (the trail names
	// every exclusion).
	ReasonPlanBackendNoCandidates = "plan-backend-no-candidates"
	// ReasonPlanGPUUnavailable — a GPU-class backend found no healthy
	// GPU in the snapshot.
	ReasonPlanGPUUnavailable = "plan-gpu-unavailable"
	// ReasonPlanGPUInsufficient — the weights+KV footprint exceeds every
	// single GPU's allocatable (multi-GPU plans need measured per-GPU
	// overhead profiles — v19.8.0+, never a guessed split).
	ReasonPlanGPUInsufficient = "plan-gpu-insufficient"
	// ReasonPlanRAMInsufficient — a CPU-class backend's host-RAM demand
	// exceeds the observed available RAM.
	ReasonPlanRAMInsufficient = "plan-ram-insufficient"
	// ReasonPlanImageUnconfigured — the operator policy declares no
	// image for the backend (the honest v19.7.2 default: no
	// digest-pinned references ship — the operator declares them).
	ReasonPlanImageUnconfigured = "plan-image-unconfigured"
	// ReasonPlanImageNotDigestPinned — the declared image reference
	// carries no @sha256: digest (roadmap §7.4's invariant, enforced).
	ReasonPlanImageNotDigestPinned = "plan-image-not-digest-pinned"
	// ReasonPlanSSDProfileUnconfigured — v19.8.0 (roadmap §8.8's
