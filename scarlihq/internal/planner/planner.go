// DecisionReason is one machine-readable explanation entry: a stable
// code + the numbers/names behind it. GENERATED by the planner — an
// LLM never authors one (roadmap §7.5's closing rule: "Never let a
// model-generated explanation alter the actual deterministic
// selection" — enforced structurally: explanations are outputs, never
// inputs).
type DecisionReason struct {
	Code   string `json:"code"`
	Detail string `json:"detail"`
}

// PinnedImage is one digest-pinned image the plan requires (roadmap
// §7.4's invariant: "Every image is digest-pinned and allowlisted").
// The reference comes from the OPERATOR-declared policy registry —
// never from an LLM, never from an unverified caller field.
type PinnedImage struct {
	// Reference — the canonical image reference; the v19.7.2 accepted
	// form is repo[:tag]@sha256:<64 hex> (digest-pinned).
	Reference string `json:"reference"`
	// DigestPinned — the reference carries a @sha256: digest.
	DigestPinned bool `json:"digest_pinned"`
}

// Strategy values — the CLOSED execution-strategy vocabulary derived
// deterministically from (architecture × backend execution class).
// The v19.7.2 set is deliberately resident-only: the deployed GPU
// backends serve MoE with ALL experts in VRAM, the CPU backends with
// the whole checkpoint in RAM — expert paging / SSD-backed experts
// arrive with v19.8.0's InferSSD + Expert Pack, never guessed here.
const (
	// StrategyDenseResident — dense weights fully resident in GPU VRAM.
	StrategyDenseResident = "dense-resident"
	// StrategyCPUResident — dense weights fully resident in host RAM.
	StrategyCPUResident = "cpu-resident"
	// StrategyMoEGPUResident — MoE checkpoint (shared + ALL experts)
	// fully resident in GPU VRAM (the deployed sglang/vllm behavior).
	StrategyMoEGPUResident = "moe-gpu-resident"
	// StrategyMoECPUResident — MoE checkpoint fully resident in host
	// RAM (llama.cpp-family CPU execution).
	StrategyMoECPUResident = "moe-cpu-resident"
)

// NodeLocal is the v19.7.2 node identity: the planner is single-node by
// construction. The v19.9.0 distributed fabric owns the multi-node
// contract; pinning the value here keeps the plan schema stable.
const NodeLocal = "local"

// ExecutionPlan is the deterministic planner output (roadmap §7.4's
// shape + the ask's provenance). It is a PROPOSAL: nothing is
// reserved, bound, or launched — admission is still required, and the
// plan EXPIRES (revalidated at admission time).
type ExecutionPlan struct {
	// PlanID — the CONTENT hash of the decision tuple (identical
	// inputs → identical ID; the identity IS the decision, the expiry
	// clock rides separately).
	PlanID string `json:"plan_id"`
	// BackendID — the selected capability-tier backend.
	BackendID airuntime.BackendID `json:"backend_id"`
	// Strategy — the derived execution strategy (closed vocabulary).
	Strategy string `json:"strategy"`
	// NodeID — "local" (v19.7.2 single-node; v19.9.0 owns multi-node).
	NodeID string `json:"node_id"`
	// GPUUUIDs — the proposed GPU assignment (one UUID; EMPTY for CPU
	// execution classes). v19.7.2 plans are SINGLE-GPU — a multi-GPU
	// split needs a measured per-GPU overhead profile.
	GPUUUIDs []string `json:"gpu_uuids,omitempty"`
	// ModelArtifactID — the verified artifact binding:
	// <model_id>@<revision>#<declared checkpoint sha256>.
	ModelArtifactID string `json:"model_artifact_id"`
	// ResourceVector — the proposed admission ask (admission-shaped:
	// the same safety-headroom discipline the admission gate applies,
	// so the proposal is realistic, never optimistic).
	ResourceVector admission.ResourceVector `json:"resource_vector"`
	// RequiredImages — the digest-pinned images the execution requires.
	RequiredImages []PinnedImage `json:"required_images"`
	// ConfigProfileID — the runtime config profile the plan recommends.
	// Honest v19.7.2: EMPTY (no profile registry exists yet) — a
	// declared absence, never a guessed profile.
	ConfigProfileID string `json:"config_profile_id"`
	// Explanation — the generated decision trail (machine-readable).
	Explanation []DecisionReason `json:"explanation"`
	// ExpiresAt — when the plan self-expires (revalidated at admission).
	ExpiresAt time.Time `json:"expires_at"`
	// RequestID / ModelID / ModelRevision / Principal / Task /
	// ContextTokens / MaxConcurrent / LatencyClass — the ask's
	// provenance, carried so the plan is self-contained.
	RequestID     string `json:"request_id"`
	ModelID       string `json:"model_id"`
	ModelRevision string `json:"model_revision"`
	Principal     string `json:"principal,omitempty"`
	Task          string `json:"task"`
	ContextTokens int    `json:"context_tokens"`
	MaxConcurrent int    `json:"max_concurrent"`
	LatencyClass  string `json:"latency_class"`
}

