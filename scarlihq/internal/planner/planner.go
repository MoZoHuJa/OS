// Package planner — the deterministic execution planner (v19.7.2,
// Compute Fabric Phase 3, roadmap §7 of
// docs/roadmaps/SCARLIXOS_UNIFIED_COMPUTE_FABRIC_IMPLEMENTATION_ROADMAP.md).
//
// CHARTER (the package's non-negotiable contract):
//
//   - The planner is PURE and SIDE-EFFECT-FREE (roadmap §7.1: "The
//     planner should consume capabilities and metadata; it must not
//     launch containers"): no network, no exec, no file I/O, no
//     reservation writes anywhere in the planning path — every input
//     arrives through the constructor-injected sources, every output
//     is a value. The production seams (env parsing, snapshot
//     building) live in production.go, the only file in this package
//     allowed to touch the environment.
//   - DETERMINISTIC for identical inputs (roadmap §7.4): same request
//   - same snapshot + same policy → the same plan, including the
//     same PlanID (a CONTENT hash of the decision tuple — the identity
//     IS the decision; the expiry clock rides separately). Candidate
//     evaluation is sorted; tie-breaking is lexicographic: policy
//     priority → observed utilization → tightest fit → stable IDs.
//   - HARD CONSTRAINTS BEFORE OPTIMIZATION (roadmap §7.5): model/
//     backend compatibility (format + architecture + required features
//     against the CLOSED capability registry — never a guess),
//     placement × runtime presence (declared AND observed running +
//     healthy — the join that refuses every v19.7.2 infer_ssd plan,
//     the declared-future backend), artifact verification (VERIFIED
//     records only — a declared digest is a DECLARATION,
//     KPK-19.7.0-P2-04's rule; a stale verification is absent
//     verification), snapshot freshness (HARD refusal,
//     KPK-19.7.0-P2-01's rule), capacity (the admission-shaped check
//     against the OBSERVED snapshot — safety headroom subtracted
//     before the check), and the digest-pinned + operator-declared
//     image. Only after every hard constraint passes does the priority
//     ordering decide.
//   - THE PLAN IS A PROPOSAL (roadmap §7.4's closing invariant):
//     planner output never reserves, never binds, never launches —
//     admission is still required, and every plan EXPIRES and is
//     revalidated at admission time.
//   - LLM OUTPUT IS NEVER SELECTION INPUT (roadmap §7.6 + this
//     release's must-not-do, "Do not make LLM output directly
//     executable"): ExecutionRequest has NO field that steers backend
//     selection — no preferred_backend, no explanation echo, no
//     free-form policy override; the selection order belongs ONLY to
//     the operator-owned PlannerPolicy. The plan's Explanation is
//     GENERATED by the planner (machine-readable DecisionReason codes
//   - the numbers behind them), never consumed from model output.
//     An accepted AI proposal becomes a typed request through
//     operator action; the request shape itself enforces the boundary.
//   - v19.7.2 plans are SINGLE-NODE ("local") and SINGLE-GPU, and
//     carry NO storage demand: the deployed GPU backends serve MoE
//     models with ALL experts resident in VRAM (expert paging and the
//     SSD-backed expert store are v19.8.0's InferSSD / Expert Pack
//     territory), and every planned model's weights are already on
//     disk — the artifact verification proved them there. A
//     weights+KV footprint exceeding every single GPU's allocatable is
//     a NAMED refusal — multi-GPU splits need measured per-GPU
//     overhead profiles that do not exist yet, never a guessed split.
