// Planner is the deterministic execution planner. Construction is
// cheap and fail-closed: the CLOSED backend capability registry is
// validated at construction (roadmap §7.2's "validated at startup" —
// an inconsistent registry is a construction error, never a
// per-request surprise), and the policy's closed shapes are validated
// the same way. Every Plan call is pure: no writes, no dials, no
// reservations — the output is a proposal admission still has to
// accept.
type Planner struct {
	policy    PlannerPolicy
	snapshots SnapshotSource
	models    ModelSource
	now       func() time.Time
}

// NewPlanner wires the planner. Fail-closed on an inconsistent
// capability registry or a malformed policy.
func NewPlanner(policy PlannerPolicy, snapshots SnapshotSource, models ModelSource) (*Planner, error) {
	if err := airuntime.ValidateBackendRegistry(); err != nil {
		return nil, fmt.Errorf("planner: the closed backend capability registry is inconsistent — refusing to construct (roadmap §7.2: validated at startup): %w", err)
	}
	if policy.PolicyVersion == "" {
		policy = DefaultPlannerPolicy()
	}
	if err := validatePolicy(policy); err != nil {
		return nil, fmt.Errorf("planner: policy malformed: %w", err)
	}
	if snapshots == nil || models == nil {
		return nil, fmt.Errorf("planner: sources must not be nil (a planner without inputs is a guess factory)")
	}
	return &Planner{policy: policy, snapshots: snapshots, models: models, now: time.Now}, nil
}

// SetNow overrides the clock (tests).
func (p *Planner) SetNow(now func() time.Time) { p.now = now }

// Policy returns the active policy (operator surface).
func (p *Planner) Policy() PlannerPolicy { return p.policy }

// validatePolicy checks the policy's closed shapes: valid backend IDs,
// no duplicate priorities, non-empty image references, positive
// freshness/TTL bounds.
func validatePolicy(policy PlannerPolicy) error {
	seen := map[airuntime.BackendID]bool{}
	for _, b := range policy.PriorityBackends {
		if err := b.Validate(); err != nil {
			return err
		}
		if seen[b] {
			return fmt.Errorf("priority list repeats backend %q", b)
		}
		seen[b] = true
	}
	for b, ref := range policy.Images {
		if err := b.Validate(); err != nil {
			return err
		}
		if strings.TrimSpace(ref) == "" {
			return fmt.Errorf("image reference for backend %q is empty (remove the entry or declare a real reference)", b)
		}
	}
	if policy.MaxSnapshotAge <= 0 {
		return fmt.Errorf("max_snapshot_age must be > 0 (a non-positive freshness bound refuses nothing)")
	}
	if policy.PlanTTL <= 0 {
		return fmt.Errorf("plan_ttl must be > 0 (a plan without expiry violates the revalidation invariant)")
	}
	return nil
}

// candidate is one backend's complete evaluation (only constructed
// when the backend survived every hard constraint — exclusions travel
// the named trail instead).
type candidate struct {
	backend airuntime.BackendID
	row     airuntime.BackendCapabilities

	// placement
	strategy string
	gpu      *inventory.GPU // nil for CPU execution classes
	vector   admission.ResourceVector
	image    PinnedImage
	util     int     // the observed utilization (queue-delay proxy)
	frag     float64 // demand/allocatable — higher = tighter fit = lower fragmentation
}

// Plan computes the deterministic execution plan for req (or the named
// refusal). The full §7.4/§7.5 pipeline: validate the request → verify
// snapshot freshness (HARD) → resolve the model (manifest, eligibility,
// revision, context, VERIFIED artifact) → the capability × presence ×
// capacity × image join over every DECLARED backend (hard constraints,
// named exclusions) → the deterministic priority ordering → assemble
// the plan (content-hash PlanID, expiry, the generated explanation).
func (p *Planner) Plan(req ExecutionRequest) PlanResult {
	now := p.now()

	// 1. request shape.
	if reasons := req.Validate(); len(reasons) > 0 {
		return p.refuse(ReasonPlanRequestInvalid, fmt.Sprintf("request invalid: %s", strings.Join(reasons, "; ")), nil)
	}

	// 2. snapshot availability + freshness (HARD — KPK-19.7.0-P2-01).
	snap, err := p.snapshots.Current()
	if err != nil || snap == nil {
		return p.refuse(ReasonPlanSnapshotUnavailable, fmt.Sprintf("inventory snapshot unavailable: %v", err), nil)
	}
	if age := now.Sub(snap.ObservedAt); age > p.policy.MaxSnapshotAge {
		return p.refuse(ReasonPlanSnapshotStale, fmt.Sprintf("snapshot %s is %s old (bound %s) — a stale free-VRAM/free-space value is never current capacity (KPK-19.7.0-P2-01, HARD refusal)", snap.SnapshotID, age.Truncate(time.Second), p.policy.MaxSnapshotAge), snap)
	}
	base := PlanResult{SnapshotID: snap.SnapshotID, PolicyVersion: p.policy.PolicyVersion}

	// 3. model resolution: manifest → schema → placement gate →
	// revision → context → VERIFIED artifact.
	manifest, ok := p.models.Manifest(req.ModelID)
	if !ok || manifest == nil {
		return p.refuseWith(base, ReasonPlanModelUnknown, fmt.Sprintf("no schema-valid manifest declares model %q", req.ModelID))
	}
	if invalid := modelmeta.ValidateManifest(manifest); len(invalid) > 0 {
		return p.refuseWith(base, ReasonPlanModelIneligible, fmt.Sprintf("manifest for %q fails validation: %s", req.ModelID, strings.Join(invalid, "; ")))
	}
	if elig := modelmeta.PlacementEligible(manifest); !elig.Eligible {
		return p.refuseWith(base, ReasonPlanModelIneligible, fmt.Sprintf("manifest for %q is placement-ineligible: %s", req.ModelID, strings.Join(elig.Reasons, "; ")))
	}
	// The planner's own derivation rule (honest extension of the
	// placement gate): the VECTOR derivation needs the weights
	// footprint — a dense model with unknown shared bytes is refused
	// BY NAME rather than planned from a parsed parameter label
	// ("14B" is a declared label, not bytes; never schedule from
	// unverified estimates).
	if manifest.Architecture.Kind == modelmeta.ArchitectureDense && manifest.Architecture.SharedBytes == 0 {
		return p.refuseWith(base, ReasonPlanModelIneligible, fmt.Sprintf("manifest for %q declares no architecture.shared_bytes — the planner's dense vector derivation requires the weights footprint (a parameter label is a label, not bytes; never schedule from unverified estimates)", req.ModelID))
	}
	if req.ModelRevision != "" && req.ModelRevision != manifest.Revision {
		return p.refuseWith(base, ReasonPlanModelRevisionMismatch, fmt.Sprintf("requested revision %q does not match the manifest revision %q", req.ModelRevision, manifest.Revision))
	}
	if req.ContextTokens > manifest.Runtime.ContextLimit {
		return p.refuseWith(base, ReasonPlanContextExceedsLimit, fmt.Sprintf("context_tokens %d exceeds the model's declared context limit %d — planning an unservable context would be a phantom capability", req.ContextTokens, manifest.Runtime.ContextLimit))
	}
	verif, ok := p.models.Verification(req.ModelID)
	if !ok || verif == nil || !verif.AllVerified {
		return p.refuseWith(base, ReasonPlanModelUnverified, fmt.Sprintf("model %q has no fully-verified artifact record (declared digests are declarations — the planner consumes VERIFIED records, KPK-19.7.0-P2-04)", req.ModelID))
	}
	if age := now.Sub(verif.VerifiedAt); age > p.policy.VerificationMaxAge {
		return p.refuseWith(base, ReasonPlanModelUnverified, fmt.Sprintf("model %q verification is %s old (bound %s) — a stale verification is absent verification", req.ModelID, age.Truncate(time.Second), p.policy.VerificationMaxAge))
	}

	// 4-6. the capability × presence × capacity × image join over every
	// DECLARED backend — hard constraints with named exclusions.
	declared := append([]string(nil), manifest.Runtime.SupportedBackends...)
	sort.Strings(declared) // deterministic evaluation order (the trail reads stably)
	trail := make([]string, 0, len(declared))
	complete := make([]candidate, 0, len(declared))
	var downstream []string // the named downstream refusal codes (image/capacity)

	for _, slug := range declared {
		b := airuntime.BackendID(slug)
		row, err := airuntime.BackendCapabilitiesFor(b)
		if err != nil {
			trail = append(trail, fmt.Sprintf("%s: not in the closed capability registry (%v)", slug, err))
			continue
		}
		// Hard constraint: model format × backend capability.
		if !containsFold(row.ModelFormats, manifest.Checkpoint.Format) {
			trail = append(trail, fmt.Sprintf("%s: excluded — format %q not in capability formats %v", slug, manifest.Checkpoint.Format, row.ModelFormats))
			continue
		}
		// Hard constraint: architecture × backend capability.
		arch := string(manifest.Architecture.Kind)
		if !containsFold(row.Architectures, arch) {
			trail = append(trail, fmt.Sprintf("%s: excluded — architecture %q not in capability architectures %v", slug, arch, row.Architectures))
			continue
		}
		if manifest.Architecture.Kind == modelmeta.ArchitectureMoE && !row.SupportsMoE {
			trail = append(trail, fmt.Sprintf("%s: excluded — supports_moe is false", slug))
			continue
		}
		// Hard constraint: required runtime features ⊆ capability
		// features (the v2 manifest schema does not yet declare
		// features — the empty set is the honest present; the check
		// stands for the schema's future, exact-match never fuzzy).
		if missing := firstMissingFeature(manifest, row); missing != "" {
			trail = append(trail, fmt.Sprintf("%s: excluded — required feature %q not provided (capability features %v)", slug, missing, row.Features))
			continue
		}
		// Hard constraint: placement × runtime presence (the join that
		// refuses a declared-but-not-running backend — and every
		// v19.7.2 infer_ssd plan, the declared-future backend).
		rt := findRuntime(snap, string(b))
		if rt == nil || !rt.Running || (row.HealthRequired && !rt.Healthy) {
			state := "not observed in the snapshot"
			if rt != nil {
				state = fmt.Sprintf("running=%t healthy=%t", rt.Running, rt.Healthy)
			}
			trail = append(trail, fmt.Sprintf("%s: excluded — runtime presence failed (%s)", slug, state))
			continue
		}
		// The hard capacity / image evaluation (the named downstream
		// refusal codes: image pinning, GPU/RAM capacity).
		c, exclCode, exclDetail := p.evaluateCapacity(b, row, manifest, rt, snap, req)
		if exclCode != "" {
			trail = append(trail, fmt.Sprintf("%s: excluded — %s (%s)", slug, exclCode, exclDetail))
			downstream = append(downstream, exclCode)
			continue
		}
		complete = append(complete, c)
		trail = append(trail, fmt.Sprintf("%s: eligible — strategy %s%s (utilization %d%%)", slug, c.strategy, gpuSuffix(c.gpu), c.util))
	}
	base.Considered = trail

	if len(complete) == 0 {
		// The precise-code path: when the join reached the downstream
		// evaluation for EXACTLY ONE backend, its named refusal IS the
		// answer (the common deployed shape — one model, one backend);
		// multiple failures aggregate honestly into no-candidates with
		// the full trail.
		if len(downstream) == 1 {
			return p.refuseWith(base, downstream[0], fmt.Sprintf("no declared backend survived the join — %s — trail: %s", downstream[0], strings.Join(trail, " | ")))
		}
		return p.refuseWith(base, ReasonPlanBackendNoCandidates, fmt.Sprintf("no declared backend survived the capability × presence × capacity × image join — trail: %s", strings.Join(trail, " | ")))
	}

	// 7. the deterministic ordering (roadmap §7.5's tie-break
	// sequence): (1) policy priority, (2) lowest observed utilization
	// (the honest v19.7.2 queue-delay proxy — a real queue model
	// arrives with workload metrics, v19.8.0+), (3) tightest fit
	// (lowest fragmentation), (4) stable lexical backend + GPU UUID.
	sort.SliceStable(complete, func(i, j int) bool {
		return p.less(complete[i], complete[j])
	})
	winner := complete[0]

	// 8. assembly: the plan is a PROPOSAL (admission still required).
	plan := p.assemblePlan(req, manifest, verif, winner, snap, now)
	out := base
	out.Selected = true
	out.ReasonCode = ReasonPlanOK
	out.Explanation = fmt.Sprintf("plan %s: model %s on %s (strategy %s, tier %d, policy priority %d) — a PROPOSAL: admission is still required; the plan expires at %s", plan.PlanID, req.ModelID, winner.backend, winner.strategy, tierOf(winner.backend), p.priorityOf(winner.backend)+1, plan.ExpiresAt.UTC().Format(time.RFC3339))
	out.Plan = plan
	return out
}

// less is the deterministic candidate comparator (roadmap §7.5's
// tie-break sequence): (1) policy priority, (2) lowest observed GPU
// utilization (the queue-delay proxy — CPU classes carry 0), (3)
// tightest fit (highest demand/allocatable ratio = lowest
// fragmentation), (4) stable lexical backend + GPU UUID.
func (p *Planner) less(a, b candidate) bool {
	pa, pb := p.priorityOf(a.backend), p.priorityOf(b.backend)
	if pa != pb {
		return pa < pb
	}
	if a.util != b.util {
		return a.util < b.util
	}
	if a.frag != b.frag {
		return a.frag > b.frag // tighter fit wins
	}
	if a.backend != b.backend {
		return a.backend < b.backend
	}
	return gpuUUID(a.gpu) < gpuUUID(b.gpu)
}

// priorityOf is the backend's position in the policy's priority list
// (not-listed ranks last, stably).
func (p *Planner) priorityOf(b airuntime.BackendID) int {
	for i, x := range p.policy.PriorityBackends {
		if x == b {
			return i
		}
	}
	return len(p.policy.PriorityBackends)
}

// evaluateCapacity computes the candidate's full vector + placement
// from the manifest × capability row × snapshot, or the named
// exclusion. The admission-shaped capacity math: the safety headroom
// is subtracted BEFORE the check; the OBSERVED free VRAM is the
// ceiling; single-GPU only; resident-only strategies (no storage
// demand in v19.7.2 — the weights are already on disk, the artifact
// verification proved them there).
func (p *Planner) evaluateCapacity(b airuntime.BackendID, row airuntime.BackendCapabilities, m *modelmeta.Manifest, rt *inventory.Runtime, snap *inventory.InventorySnapshotV2, req ExecutionRequest) (candidate, string, string) {
	c := candidate{backend: b, row: row}

	// The image hard constraint (operator-declared + digest-pinned).
	ref, has := p.policy.Images[b]
	if !has {
		return c, ReasonPlanImageUnconfigured, "the operator policy declares no image for this backend (the honest v19.7.2 default — declare digest-pinned references in the policy)"
	}
	if !strings.Contains(ref, "@sha256:") {
		return c, ReasonPlanImageNotDigestPinned, fmt.Sprintf("reference %q carries no @sha256: digest (roadmap §7.4's invariant — every image is digest-pinned)", ref)
	}
	c.image = PinnedImage{Reference: ref, DigestPinned: true}

	// The KV-cache derivation: declared when the manifest's estimate is
	// known; 0 + the honest explanation when it is not (runtimes size
	// the KV cache themselves — PlacementEligible's documented rule).
	kvBytes := uint64(req.ContextTokens) * m.Runtime.KVCache.BytesPerTokenEstimate

	// The weights footprint by architecture (the v19.7.2 strategies
	// are RESIDENT-ONLY: shared + ALL experts wherever they live).
	var sharedBytes, expertTotal uint64
	if m.Architecture.Kind == modelmeta.ArchitectureMoE {
		sharedBytes = m.Architecture.SharedBytes
		expertTotal = uint64(m.Architecture.ExpertCount) * m.Architecture.ExpertBytes
	} else {
		sharedBytes = m.Architecture.SharedBytes // dense: the whole checkpoint footprint
	}

	if row.RequiresGPU {
		// GPU execution class: the whole checkpoint + KV resident in
		// VRAM (the deployed sglang/vllm behavior).
		demand := sharedBytes + expertTotal + kvBytes
		if m.Architecture.Kind == modelmeta.ArchitectureMoE {
			c.strategy = StrategyMoEGPUResident
		} else {
			c.strategy = StrategyDenseResident
		}
		gpu, alloc, util, exclCode, exclDetail := p.pickGPU(snap, demand)
		if exclCode != "" {
			return c, exclCode, exclDetail
		}
		c.gpu = gpu
		c.util = util
		c.vector = admission.ResourceVector{
			GPU: []admission.GPURequest{{
				GPUUUID:   gpu.UUID,
				VRAMBytes: demand,
				Exclusive: true, // the v19.7.1+ safe default — sharing without compute-share enforcement is a phantom capability
			}},
			KVCacheBytes: kvBytes,
			RAMBytes:     p.policy.RuntimeOverheadRAMBytes, // honest 0 default: no measured runtime-RAM profile exists
			CPUThreads:   p.policy.DefaultCPUThreads,
		}
		c.frag = fragRatio(demand, alloc)
		return c, "", ""
	}

	// CPU execution class: the whole checkpoint + KV resident in host
	// RAM (llama.cpp-family behavior).
	ramDemand := sharedBytes + expertTotal + kvBytes + p.policy.RuntimeOverheadRAMBytes
	if m.Architecture.Kind == modelmeta.ArchitectureMoE {
		c.strategy = StrategyMoECPUResident
	} else {
		c.strategy = StrategyCPUResident
	}
	avail := snap.Host.RAMAvailableBytes
	if ramDemand > avail {
		return c, ReasonPlanRAMInsufficient, fmt.Sprintf("host-RAM demand %d bytes exceeds the observed available %d bytes (CPU execution class)", ramDemand, avail)
	}
	c.vector = admission.ResourceVector{
		RAMBytes:     ramDemand,
		KVCacheBytes: kvBytes,
		CPUThreads:   p.policy.DefaultCPUThreads,
	}
	c.frag = fragRatio(ramDemand, avail)
	return c, "", ""
}

// pickGPU deterministically selects the single GPU for a VRAM demand.
// The capacity check is admission-shaped: observed free minus the
// safety-headroom fraction of TOTAL. Among fitting GPUs the §7.5
// placement tie-breaks apply: lowest observed utilization (the
// queue-delay proxy) → tightest fit (lowest fragmentation) → stable
// UUID. No healthy GPU → plan-gpu-unavailable; no fitting GPU →
// plan-gpu-insufficient (multi-GPU splits are v19.8.0+ with measured
// per-GPU overhead profiles, never a guessed split).
func (p *Planner) pickGPU(snap *inventory.InventorySnapshotV2, demand uint64) (*inventory.GPU, uint64, int, string, string) {
	type fit struct {
		gpu   inventory.GPU
		alloc uint64
		util  int
	}
	var fits []fit
	for i := range snap.GPUs {
		g := snap.GPUs[i]
		if !g.Healthy {
			continue
		}
		total := uint64(g.VRAMTotalMB) << 20
		free := uint64(g.VRAMFreeMB) << 20
		headroom := uint64(float64(total) * p.policy.VRAMSafetyFraction)
		alloc := saturatingSub(free, headroom)
		if demand <= alloc {
			fits = append(fits, fit{gpu: g, alloc: alloc, util: g.UtilizationPct})
		}
	}
	if len(fits) == 0 {
		healthy := 0
		largest := uint64(0)
		for i := range snap.GPUs {
			if !snap.GPUs[i].Healthy {
				continue
			}
			healthy++
			total := uint64(snap.GPUs[i].VRAMTotalMB) << 20
			free := uint64(snap.GPUs[i].VRAMFreeMB) << 20
			alloc := saturatingSub(free, uint64(float64(total)*p.policy.VRAMSafetyFraction))
			if alloc > largest {
				largest = alloc
			}
		}
		if healthy == 0 {
			return nil, 0, 0, ReasonPlanGPUUnavailable, "no healthy GPU in the snapshot (GPU execution class)"
		}
		return nil, 0, 0, ReasonPlanGPUInsufficient, fmt.Sprintf("demand %d bytes exceeds every single GPU's allocatable (largest %d bytes after the %v headroom) — multi-GPU splits need measured per-GPU overhead profiles (v19.8.0+), never a guessed split", demand, largest, p.policy.VRAMSafetyFraction)
	}
	// (2) utilization → (3) tightest fit → (4) stable UUID.
	sort.SliceStable(fits, func(i, j int) bool {
		if fits[i].util != fits[j].util {
			return fits[i].util < fits[j].util
		}
		if fits[i].alloc != fits[j].alloc {
			return fits[i].alloc < fits[j].alloc // smaller sufficient allocatable = tighter fit
		}
		return fits[i].gpu.UUID < fits[j].gpu.UUID
	})
	best := fits[0]
	gpu := best.gpu
	return &gpu, best.alloc, best.util, "", ""
}

// assemblePlan builds the final plan: the content-hash PlanID (the
// identity IS the decision), the expiry, the generated explanation
// trail, and the ask's provenance.
func (p *Planner) assemblePlan(req ExecutionRequest, m *modelmeta.Manifest, verif *modelmeta.ArtifactVerification, c candidate, snap *inventory.InventorySnapshotV2, now time.Time) *ExecutionPlan {
	plan := &ExecutionPlan{
		BackendID:       c.backend,
		Strategy:        c.strategy,
		NodeID:          NodeLocal, // v19.7.2 single-node by construction (v19.9.0 owns multi-node)
		ModelArtifactID: fmt.Sprintf("%s@%s#%s", m.ID, m.Revision, strings.ToLower(m.Checkpoint.SHA256)),
		ResourceVector:  c.vector,
		RequiredImages:  []PinnedImage{c.image},
		ConfigProfileID: "", // honest: no v19.7.2 profile registry — a declared absence, never a guessed profile
		ExpiresAt:       now.Add(p.policy.PlanTTL),
		RequestID:       req.RequestID,
		ModelID:         m.ID,
		ModelRevision:   m.Revision,
		Principal:       req.Principal,
		Task:            req.Task,
		ContextTokens:   req.ContextTokens,
		MaxConcurrent:   req.MaxConcurrent,
		LatencyClass:    req.LatencyClass,
	}
	if c.gpu != nil {
		plan.GPUUUIDs = []string{c.gpu.UUID}
	}

	// The generated explanation trail (machine-readable; every number
	// named; GENERATED here — an LLM never authors an entry).
	expl := []DecisionReason{
		{Code: "backend-selected", Detail: fmt.Sprintf("%s (tier %d, policy priority %d) — capability row: formats %v, architectures %v, experimental=%t", c.backend, tierOf(c.backend), p.priorityOf(c.backend)+1, c.row.ModelFormats, c.row.Architectures, c.row.Experimental)},
		{Code: "strategy-derived", Detail: fmt.Sprintf("%s from architecture %s × execution class (requires_gpu=%t) — resident-only: no v19.7.2 storage demand (expert paging is v19.8.0 territory)", c.strategy, m.Architecture.Kind, c.row.RequiresGPU)},
		{Code: "artifact-verified", Detail: fmt.Sprintf("verified at %s (age bound %s) — %s", verif.VerifiedAt.UTC().Format(time.RFC3339), p.policy.VerificationMaxAge, plan.ModelArtifactID)},
		{Code: "snapshot-fresh", Detail: fmt.Sprintf("snapshot %s within the %s bound", snap.SnapshotID, p.policy.MaxSnapshotAge)},
		{Code: "image-pinned", Detail: c.image.Reference},
	}
	if c.gpu != nil {
		expl = append(expl, DecisionReason{Code: "gpu-assigned", Detail: fmt.Sprintf("%s (observed free %d MB, safety headroom %v, utilization %d%%) — exclusive per UUID (the v19.7.1+ safe default)", c.gpu.UUID, c.gpu.VRAMFreeMB, p.policy.VRAMSafetyFraction, c.gpu.UtilizationPct)})
	} else {
		expl = append(expl, DecisionReason{Code: "cpu-class", Detail: fmt.Sprintf("host-RAM resident — demand %d bytes against the observed available %d bytes", c.vector.RAMBytes, snap.Host.RAMAvailableBytes)})
	}
	if m.Runtime.KVCache.BytesPerTokenEstimate == 0 {
		expl = append(expl, DecisionReason{Code: "kv-cache-estimate-unknown", Detail: "the manifest declares no kv_cache.bytes_per_token_estimate — the proposed KV demand is 0 and the runtime sizes the KV cache itself (PlacementEligible's documented rule; admission holds only the declared demand)"})
	}
	if c.row.Experimental {
		expl = append(expl, DecisionReason{Code: "backend-experimental", Detail: fmt.Sprintf("%s is EXPERIMENTAL in the deployed stack — the selection is carried visibly, never silently", c.backend)})
	}
	expl = append(expl, DecisionReason{Code: "plan-is-proposal", Detail: fmt.Sprintf("nothing is reserved, bound or launched — admission is still required; the plan expires at %s and is revalidated at admission time", plan.ExpiresAt.UTC().Format(time.RFC3339))})
	plan.Explanation = expl

	plan.PlanID = p.planContentHash(plan)
	return plan
}

// planContentHash hashes the decision tuple: the policy version (the
// policy identity that produced the decision), backend, strategy,
// node, GPUs, the artifact binding, the vector, the images, the
// config profile, and the ask's provenance — canonical JSON, SHA-256,
// 16 bytes hex. Identical inputs → identical ID (the determinism
// proof); the expiry clock and the derived identity ride separately.
func (p *Planner) planContentHash(plan *ExecutionPlan) string {
	tuple := struct {
		Policy string         `json:"policy"`
		Plan   *ExecutionPlan `json:"plan"`
	}{
		Policy: p.policy.PolicyVersion,
		Plan: &ExecutionPlan{
			BackendID:       plan.BackendID,
			Strategy:        plan.Strategy,
			NodeID:          plan.NodeID,
			GPUUUIDs:        plan.GPUUUIDs,
			ModelArtifactID: plan.ModelArtifactID,
			ResourceVector:  plan.ResourceVector,
			RequiredImages:  plan.RequiredImages,
			ConfigProfileID: plan.ConfigProfileID,
			RequestID:       plan.RequestID,
			ModelID:         plan.ModelID,
			ModelRevision:   plan.ModelRevision,
			Principal:       plan.Principal,
			Task:            plan.Task,
			ContextTokens:   plan.ContextTokens,
			MaxConcurrent:   plan.MaxConcurrent,
			LatencyClass:    plan.LatencyClass,
		},
	}
	b, err := json.Marshal(tuple)
	if err != nil {
		// Canonical JSON of plain strings/ints cannot fail; reaching
		// here is a programming error — the loud failure is more
		// honest than a fabricated identity.
		panic(fmt.Sprintf("planner: plan tuple marshal failed: %v", err))
	}
	sum := sha256.Sum256(b)
	return "plan-" + hex.EncodeToString(sum[:16])
}

// refuse builds a bare refusal (before the snapshot resolves).
func (p *Planner) refuse(code, explanation string, snap *inventory.InventorySnapshotV2) PlanResult {
	r := PlanResult{ReasonCode: code, Explanation: explanation, PolicyVersion: p.policy.PolicyVersion}
	if snap != nil {
		r.SnapshotID = snap.SnapshotID
	}
	return r
}

// refuseWith builds a refusal carrying the resolved-snapshot base.
func (p *Planner) refuseWith(base PlanResult, code, explanation string) PlanResult {
	base.Selected = false
	base.ReasonCode = code
	base.Explanation = explanation
	base.Plan = nil
	return base
}

// ---- small helpers ---------------------------------------------------------

func tierOf(b airuntime.BackendID) int {
	t, err := airuntime.BackendTier(b)
	if err != nil {
		return -1
	}
	return t
}

func findRuntime(snap *inventory.InventorySnapshotV2, id string) *inventory.Runtime {
	for i := range snap.Runtimes {
		if snap.Runtimes[i].ID == id {
			rt := snap.Runtimes[i]
			return &rt
		}
	}
	return nil
}

// requiredRuntimeFeatures returns the manifest's required runtime
// feature tokens. The scarlix.model/v2 schema does not yet declare a
// features field (ModelExecution carries the slot; every v2 manifest
// resolves it to nil) — the EMPTY set is the honest present value and
// the §7.5 hard constraint stands ready for the schema's future,
// exact-match, never fuzzy.
func requiredRuntimeFeatures(m *modelmeta.Manifest) []string {
	return nil
}

// firstMissingFeature returns the first manifest-required feature the
// capability row does not provide ("" when every requirement is met).
func firstMissingFeature(m *modelmeta.Manifest, row airuntime.BackendCapabilities) string {
	for _, f := range requiredRuntimeFeatures(m) {
		if !containsFold(row.Features, f) {
			return f
		}
	}
	return ""
}

func containsFold(list []string, s string) bool {
	for _, x := range list {
		if strings.EqualFold(x, s) {
			return true
		}
	}
	return false
}

func saturatingSub(v, sub uint64) uint64 {
	if sub >= v {
		return 0
	}
	return v - sub
}

func fragRatio(demand, alloc uint64) float64 {
	if alloc == 0 {
		return 0
	}
	return float64(demand) / float64(alloc)
}

func gpuSuffix(g *inventory.GPU) string {
	if g == nil {
		return ""
	}
	return fmt.Sprintf(" on %s", g.UUID)
}

func gpuUUID(g *inventory.GPU) string {
	if g == nil {
		return ""
	}
	return g.UUID
}
